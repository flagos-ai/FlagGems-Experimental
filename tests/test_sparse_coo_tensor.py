def _make_coo(
    nnz, size, seed, device, dense_dim=0, coalesced=None, index_dtype=torch.int64
):
    """Build raw (indices, values) for a COO tensor.

    ``nnz`` coordinates are drawn without replacement from the flattened
    sparse-dim grid, so duplicates cannot occur and the caller controls the
    coalescing state through ``coalesced``. With ``dense_dim > 0`` the last
    ``dense_dim`` entries of ``size`` are dense dimensions and each value
    carries that many elements.
    """
    gen = torch.Generator(device="cpu").manual_seed(seed)
    sparse_size = size[: len(size) - dense_dim] if dense_dim else size
    grid = 1
    for s in sparse_size:
        grid *= s
    nnz = min(nnz, grid)
    flat = torch.randperm(grid, generator=gen)[:nnz]
    if coalesced:
        flat = flat.sort().values
    indices = torch.empty((len(sparse_size), nnz), dtype=torch.int64)
    rest = flat.clone()
    for d in reversed(range(len(sparse_size))):
        indices[d] = rest % sparse_size[d]
        rest = rest // sparse_size[d]
    value_shape = (nnz,) + tuple(size[len(sparse_size) :])
    values = torch.randn(value_shape, generator=gen).to(device)
    return indices.to(device).to(index_dtype), values


