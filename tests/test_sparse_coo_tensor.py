    # registered on must intercept the routed calls, proving the shipped
    # implementation is what executes rather than the native kernel.
    #
    # Measured per-key reachability (native_probe_u.log / GPU probe log):
    #   .size / .size_out  -> reached on the device key (and BackendSelect /
    #                         CompositeExplicitAutograd for the factory form)
    #   .indices / .indices_size -> reached ONLY on CompositeImplicitAutograd
    #                         (they are pure composites with no backend key)
    lib = torch.library.Library("aten", "IMPL")
    hits = []

    def sentinel_size(size, *, dtype=None, layout=None, device=None, pin_memory=False):
        hits.append("size")
        return flag_gems.sparse_coo_tensor_size(
            size, dtype=dtype, layout=layout, device=device, pin_memory=pin_memory
        )

    def sentinel_indices(
        indices,
        values,
        *,
        dtype=None,
        layout=None,
        device=None,
        pin_memory=None,
        is_coalesced=None,
    ):
        hits.append("indices")
        return flag_gems.sparse_coo_tensor_indices(
            indices,
            values,
            dtype=dtype,
            layout=layout,
            device=device,
            pin_memory=pin_memory,
            is_coalesced=is_coalesced,
        )

    def sentinel_indices_size(
        indices,
        values,
        size,
        *,
        dtype=None,
        layout=None,
        device=None,
        pin_memory=None,
        is_coalesced=None,
    ):
        hits.append("indices_size")
        return flag_gems.sparse_coo_tensor_indices_size(
            indices,
            values,
            size,
            dtype=dtype,
            layout=layout,
            device=device,
            pin_memory=pin_memory,
            is_coalesced=is_coalesced,
        )

    dev = flag_gems.device
    indices = torch.tensor([[0, 1, 1], [2, 0, 2]], dtype=torch.int64, device=dev)
    values = torch.tensor([3.0, 4.0, 5.0], device=dev)

    try:
        lib.impl("sparse_coo_tensor.size", sentinel_size, "CUDA")
        lib.impl("sparse_coo_tensor.size", sentinel_size, "BackendSelect")
        lib.impl(
            "sparse_coo_tensor.indices", sentinel_indices, "CompositeImplicitAutograd"
        )
        lib.impl(
            "sparse_coo_tensor.indices_size",
            sentinel_indices_size,
            "CompositeImplicitAutograd",
        )

        # Packet entry points.
        assert torch.ops.aten.sparse_coo_tensor.size([2, 4], device=dev)._nnz() == 0
        assert torch.ops.aten.sparse_coo_tensor.indices(indices, values)._nnz() == 3
        assert (
            torch.ops.aten.sparse_coo_tensor.indices_size(
                indices, values, [2, 4]
            )._nnz()
            == 3
        )
        # Python builtin entry points (the path a user actually takes).
        assert torch.sparse_coo_tensor([2, 4], device=dev)._nnz() == 0
        assert torch.sparse_coo_tensor(indices, values)._nnz() == 3
        assert torch.sparse_coo_tensor(indices, values, [2, 4])._nnz() == 3

        assert hits.count("size") >= 2, hits
        assert hits.count("indices") >= 2, hits
        assert hits.count("indices_size") >= 2, hits
    finally:
        lib._destroy()

    # After destroying the sentinel the routed path is native again and still
    # agrees with the submitted implementation.
    assert torch.ops.aten.sparse_coo_tensor.size([2, 4], device=dev)._nnz() == 0
    assert flag_gems.sparse_coo_tensor_size([2, 4], device=dev)._nnz() == 0
