def _native_error(inp, scale, zp, axis=0):
    """Native error raised for ``inp`` on ``inp``'s own device.

    The message is device dependent (CUDA reports the missing backend kernel
    for the allocation factory, CPU the factory's dtype requirement), so the
    comparison must be made on the same device as the implementation under test
    rather than against a device-shifted reference.
    """
    with pytest.raises(Exception) as exc:
        torch.ops.aten._make_per_channel_quantized_tensor(inp, scale, zp, axis)
    return exc.value


