def _gen_input(shape, dtype):
    """Integer data for the accepted input dtypes, from the dtype's full range.

    Values span both signs for int8/int32 so the copy must be sign-preserving,
    and the full uint8 extent so it must not saturate anything.
    """
    if shape == () or 0 in shape:
        return torch.empty(shape, dtype=dtype, device=flag_gems.device)
    info = torch.iinfo(dtype)
    if dtype == torch.int32:
        # torch.randint cannot sample the whole int32 range in one call; the
        # low 16 bits scaled up plus a sign sweep still hits both signs and the
        # extremes.
        low = torch.randint(-32768, 32768, shape, dtype=torch.int32, device="cpu")
        return (low * 65536 + torch.randint(0, 65536, shape, dtype=torch.int32)).to(
            flag_gems.device
        )
    return torch.randint(info.min, info.max, shape, dtype=dtype, device="cpu").to(
        flag_gems.device
    )


def _gen_float_input(shape, dtype):
    """Float data for the quantize branch, including negatives and halves."""
    if shape == () or 0 in shape:
        return torch.empty(shape, dtype=dtype, device=flag_gems.device)
    base = torch.arange(1, 1 + max(torch.Size(shape).numel(), 1), dtype=torch.float32)
    vals = torch.linspace(-8.0, 8.0, base.numel())
    return vals.reshape(shape).to(dtype).to(flag_gems.device)


def _channels(shape, axis):
    """Number of channels for ``axis`` on ``shape`` (0-dim counts as 1)."""
