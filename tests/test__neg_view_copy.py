def _gen_input(shape, dtype):
    """Deterministic input covering negatives, zeros and positive values."""
    if dtype.is_floating_point:
        base = torch.randn(shape, dtype=torch.float32, device=flag_gems.device)
        return base.to(dtype)
    info = torch.iinfo(dtype)
    # Keep magnitudes small so the negation stays in range for narrow dtypes.
    lo = max(info.min, -100)
    hi = min(info.max, 100)
    return torch.randint(lo, hi, shape, dtype=dtype, device=flag_gems.device)


