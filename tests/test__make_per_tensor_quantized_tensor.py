def _gen_input(shape, dtype):
    """Integer data for the accepted integer input dtypes.

    Values are drawn from the dtype's full range so the copy must preserve
    negative int8/int32 values and the whole uint8 extent exactly.
    """
    if shape == () or 0 in shape:
        return torch.empty(shape, dtype=dtype, device=flag_gems.device)
    info = torch.iinfo(dtype)
    # ``torch.randint`` cannot sample the full int32 range in one call without
    # overflow; sampling the low 16 bits plus a sign sweep still exercises both
    # signs and the extremes.
    if dtype == torch.int32:
        low = torch.randint(-32768, 32768, shape, dtype=torch.int32, device="cpu")
        return (low * 65536 + torch.randint(0, 65536, shape, dtype=torch.int32)).to(
            flag_gems.device
        )
    return torch.randint(info.min, info.max, shape, dtype=dtype, device="cpu").to(
        flag_gems.device
    )


