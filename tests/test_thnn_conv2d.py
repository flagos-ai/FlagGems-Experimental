# Accuracy: the registered .out overload
# ---------------------------------------------------------------------------
# Native's contract for thnn_conv2d.out, measured on this build (torch
# 2.8.0a0+5228986c39.nv25.05, CUDA 12.9, H20; probe jobs
# THNN692OUT-probe-accuracy-a1-07023a56 and
# THNN692OUT-probe3-accuracy-a1-5a240c1f / -probe4):
#   * the SAME object is returned, for a same-shape buffer and for a
#     wrong-shape one alike;
#   * a wrong-SHAPE buffer is resized in place to the result shape (a
#     zero-element buffer too);
#   * a same-shape CONTIGUOUS buffer receives exactly the base overload's
#     values;
#   * a same-shape NON-CONTIGUOUS buffer is measured GARBAGE (padded slice:
#     maxdiff 20.6 vs the contiguous result; empty_strided with non-dense
#     strides: 19.0; transposed view: 23.4 on |out| ~ 25), and the elements
#     OUTSIDE the view are written too (168 of the 336 padding elements of the
#     base tensor changed). The operative read is therefore:
#       native's .out is only correct for a contiguous buffer. Its strided
#       write overwrites the buffer's whole underlying storage linearly and
#       leaves the logical view wrong, which is a bug, not a layout contract.
#     The implementation must NOT reproduce it: correctness is defined as the
#     values of the base overload, so a strided buffer is staged contiguously
#     and copied back, and the test below pins that (copy semantics) while
#     explicitly asserting the deviation from the measured native bug.
#   * dtype/device mismatches never reach the implementation: the dispatcher
#     rejects them first ('expected scalar type Float but found Double'), so no
#     test asserts implementation-side dtype/device validation for .out.
#   * native's .out also rejects a 3-D input ('Expected 4D input tensor'), so
#     this implementation's pre-existing 4-D demand is unchanged by .out.
@pytest.mark.thnn_conv2d_out
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
@pytest.mark.parametrize("with_bias", [False, True])
def test_accuracy_thnn_conv2d_out_variant(dtype, with_bias):
    # Identity + values: the same object comes back and carries the base
    # overload's result.
    inp = _gen_input((2, 3, 8, 9), dtype)
    weight = _gen_input((4, 3, 3, 3), dtype)
    bias = _gen_input((4,), dtype) if with_bias else None
    ref = _reference(inp, weight, bias, (3, 3), (1, 1), (0, 0))
    out = torch.empty(ref.shape, dtype=dtype, device=flag_gems.device)
    _check_out(inp, weight, bias, (3, 3), (1, 1), (0, 0), out)
    # The base overload produces the same values through a fresh buffer (guards
    # against a .out path that merely happens to agree with the reference).
    base = flag_gems.thnn_conv2d(inp, weight, (3, 3), bias, (1, 1), (0, 0))
    utils.gems_assert_close(
        base,
        ref,
        inp.dtype,
        atol=_atol(inp.dtype, 27, float(ref.abs().max().item())),
    )
    assert out.data_ptr() != base.data_ptr()


