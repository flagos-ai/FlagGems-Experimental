@pytest.mark.thnn_conv2d_out
def test_thnn_conv2d_out_visible_through_registration():
    # Registration-declaration check, following the repo precedent of
    # test__make_dual.py and the sibling slow_conv_transpose2d_out: the
    # registry entry carries THIS implementation, so flag_gems.enable()
    # installs it on the backend key for aten::thnn_conv2d.out.
    #
    # The test harness deliberately does not call enable() (the reference side
    # must stay native, and tools/ci_checks/check_kernelgen_tests.py forbids
    # use_gems() in tests), so a bare schema-level call in a test process
    # resolves to the dispatch table as it exists WITHOUT FlagGems -- i.e. to
    # native. Asserting values through such a call would test native, not the
    # submission; the declaration and the entry-point identity are the check,
    # and the .out VALUE contract is covered by the direct-call tests above.
    from flag_gems import _FULL_CONFIG

    entries = [e for e in _FULL_CONFIG if e[0] == "thnn_conv2d.out"]
    assert len(entries) == 1, f"expected exactly one registry entry, got {entries}"
    assert entries[0][1] is flag_gems.thnn_conv2d_out
    impl_mod = sys.modules["flag_gems.ops.thnn_conv2d"]
    assert flag_gems.thnn_conv2d_out is impl_mod.thnn_conv2d_out
    assert flag_gems.thnn_conv2d_out.__name__ == "thnn_conv2d_out"
    # The base entry point keeps its own identity: the refactor into a shared
    # body must not have rebound the registered base implementation.
    base_entries = [e for e in _FULL_CONFIG if e[0] == "thnn_conv2d"]
    assert len(base_entries) == 1
    assert base_entries[0][1] is flag_gems.thnn_conv2d
