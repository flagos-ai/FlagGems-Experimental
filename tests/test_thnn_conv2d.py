def _reference(inp, weight, bias, kernel_size, stride, padding):
    """Build an exact reference for the comparison.

    The comparison is deliberately NOT against `aten::thnn_conv2d` on the
    upstream dtype: the native CUDA `slow_conv2d` kernel runs with the
    process-global `torch.backends.cuda.matmul.allow_tf32` default (measured
    True on this build), so a same-dtype reference is itself only tf32-accurate
    for fp32 and would make the acceptable tolerance depend on a global flag
    the test does not own. `utils.to_reference(..., upcast=True)` gives a
    float64 reference on CPU and on CUDA alike, so the assertion is
    implementation-vs-exact and the tolerance only has to cover the
    implementation's own accumulation.
    """
    exact = inp.dtype == torch.float64
    ref_inp = utils.to_reference(inp, upcast=not exact)
    ref_weight = utils.to_reference(weight, upcast=not exact)
    ref_bias = utils.to_reference(bias, upcast=not exact)
    ref_out = torch.ops.aten.thnn_conv2d(
        ref_inp,
        ref_weight,
        list(kernel_size),
        ref_bias,
        list(stride),
        list(padding),
    )
    return ref_out.to(inp.dtype)


def _atol(dtype, k_total, scale=1.0):
    """Absolute tolerance against the exact reference built by `_reference`.

    The bound is the accumulation depth times the precision the kernel
    actually uses; the measured residual against the same fp64 reference is
    at most ~2.5e-7 * |out| for fp32 / tf32x3 and ~0.5 * eps * |out| for
    fp16/bf16 (probe job thnn_conv2d-other-a1-65660022), so the factors below
    are guard bands, not fitted values.
    """
    if dtype == torch.float32 and k_total >= 256:
        # The kernel switches to input_precision="tf32" (11-bit mantissa) at
        # K_total >= 256; measured 4.7e-2 on |out| ~ 66 at K_total == 256.
        return 8.0 * _TF32_EPS * max(scale, 1.0) * max(1.0, (k_total / 256.0) ** 0.5)
    if dtype in _FP16_EPS:
        # Same shape as the fp32 branch: precision x output scale x a guard
        # factor over the measured <= 0.5 * eps * |out| residual.
        return _FP16_GUARD * _FP16_EPS[dtype] * max(scale, 1.0)
    if dtype == torch.float64:
        return 1e-9 * max(scale, 1.0)
    return 1e-4 * max(scale, 1.0)


