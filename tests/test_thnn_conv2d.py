@pytest.mark.thnn_conv2d_out
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES)
def test_accuracy_thnn_conv2d_out_strided_buffer(dtype):
    # A same-shape NON-CONTIGUOUS buffer: the implementation stages the result
    # contiguously and copies back, so the buffer keeps its strides and
    # receives the base overload's values.
    #
    # This is a DELIBERATE deviation from native, pinned here as such: native's
    # own strided write is measured garbage on this build (probe job
    # THNN692OUT-probe3-accuracy-a1-5a240c1f: maxdiff 20.6 on |out| ~ 25 for
    # this exact padded-slice layout, and it wrote 168 elements of the storage
    # outside the view). Asserting native's numbers here would be asserting a
    # bug; the property that matters is that the buffer holds the correct
    # result in its own layout.
    inp = _gen_input((2, 3, 8, 9), dtype)
    weight = _gen_input((4, 3, 3, 3), dtype)
    ref = _reference(inp, weight, None, (3, 3), (1, 1), (0, 0))
    n, c_out, h_out, w_out = ref.shape
    base = torch.full(
        (n, c_out, h_out, 2 * w_out), -777.0, dtype=dtype, device=flag_gems.device
    )
    view = base[:, :, :, :w_out]
    assert tuple(view.shape) == tuple(ref.shape)
    assert not view.is_contiguous()
    returned = flag_gems.thnn_conv2d_out(
        inp, weight, (3, 3), None, (1, 1), (0, 0), out=view
    )
    assert returned is view
    assert view.stride() == base[:, :, :, :w_out].stride()
    k_total = weight.shape[1] * 3 * 3
    scale = float(ref.abs().max().item())
    utils.gems_assert_close(view, ref, inp.dtype, atol=_atol(inp.dtype, k_total, scale))
    # Copy semantics, not "native's linear overwrite": the padding outside the
    # view must be untouched (native changed 168 of these elements).
    pad = base[:, :, :, w_out:]
    assert int((pad == -777.0).sum().item()) == pad.numel()


