    res_out = flag_gems.thnn_conv2d(inp, weight, kernel_size, bias, stride, padding)

    assert res_out.shape == ref_out.shape
    assert res_out.dtype == inp.dtype
    assert res_out.is_contiguous()
    assert res_out.device == inp.device
    k_total = weight.shape[1] * kernel_size[0] * kernel_size[1]
    scale = float(ref_out.abs().max().item()) if ref_out.numel() else 1.0
    utils.gems_assert_close(
        res_out, ref_out, inp.dtype, atol=_atol(inp.dtype, k_total, scale)
    )
    return res_out


