def test_sparse_compressed_tensor_size_inferred(layout, size, nnz, block, dense):
    # aten::sparse_compressed_tensor.comp_plain_value -- the size-inferring
    # constructor. The reference is the same overload, so the ported estimator
    # is compared against native rather than against a re-derivation.
    dev = flag_gems.device
    is_row = layout in _ROW_LAYOUTS
    br, bc = block if block is not None else (1, 1)
    c, p, v = _to_device(
        _gen_components(layout, size, nnz, block, dense, seed=2), dev, torch.int64
    )
    ref = _call_value(
        _VALUE,
        utils.to_reference(c),
        utils.to_reference(p),
        utils.to_reference(v),
        layout=layout,
    )
    res = flag_gems.sparse_compressed_tensor(c, p, v, layout=layout, device=dev)

    _assert_same(res, ref, "inferred")
    assert tuple(res.shape) == tuple(ref.shape)
    assert res._nnz() == nnz

    # The inferred extents follow len(compressed_indices) - 1 compressed blocks
    # and max(plain_indices) + 1 plain blocks, each times the block shape --
    # NOT the explicit size the components were laid out for.
    compressed_extent = c.numel() - 1
    plain_extent = int(p.max().item()) + 1 if p.numel() > 0 else 0
    if is_row:
        expected = (compressed_extent * br, plain_extent * bc)
    else:
        expected = (plain_extent * br, compressed_extent * bc)
    assert tuple(res.shape[:2]) == expected, (
        f"{tuple(res.shape[:2])} != {expected} "
        f"(compressed={compressed_extent}, plain={plain_extent})"
    )
    assert tuple(res.shape[2:]) == tuple(dense or ())


