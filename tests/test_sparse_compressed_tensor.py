def _base_extents(size, is_row, br, bc):
    """(rows, cols) of the logical matrix a case's components are laid out for.

    Only the first two entries of ``size`` describe the base matrix; any further
    entries are dense (or, for the batched test, driven by its own literal), so
    the index structure is built from the base extents alone.
    """
    return size[0], size[1]


def _gen_components(layout, size, nnz, block, dense, seed=0, index_dtype=torch.int64):
    """Build valid (compressed_indices, plain_indices, values) for one layout.

    CSR/BSR compress the rows: ``crow_indices[i] .. crow_indices[i + 1]`` is the
    range of stored entries/blocks of row (block) ``i``, so the compressed index
    has one entry per compressed row plus the terminator. CSC/BSC compress the
    columns instead, with the plain index carrying the row coordinate.

    ``values`` follows the ATen block layout ``(nnz, block_rows, block_cols,
    dense...)`` for BSR/BSC and ``(nnz, dense...)`` for CSR/CSC: the block
    dimensions sit *before* any dense dimensions. A logical size with more than
    two entries is 2-D base + trailing *dense* dimensions (the batched form has
    its own test), so only the first two entries drive the index structure.
    """
    is_row = layout in _ROW_LAYOUTS
    is_block = block is not None
    br, bc = block if is_block else (1, 1)
    dense = tuple(dense or ())
    rows, cols = _base_extents(size, is_row, br, bc)
    n_compressed = max(1, (rows if is_row else cols) // br)
    n_plain = max(1, (cols if is_row else rows) // bc)
    total_cells = n_compressed * n_plain
    nnz = min(nnz, total_cells)

    gen = torch.Generator(device="cpu").manual_seed(seed)
    flat = torch.randperm(total_cells, generator=gen)[:nnz].sort().values
    compressed = (flat // n_plain).to(torch.int64)
    plain = (flat % n_plain).to(torch.int64)
    counts = torch.bincount(compressed, minlength=n_compressed)
    cptr = torch.zeros(n_compressed + 1, dtype=torch.int64)
    cptr[1:] = torch.cumsum(counts, dim=0)

    vshape = (nnz,) + ((br, bc) if is_block else ()) + dense
    values = torch.randn(vshape, generator=gen)
    return cptr.to(index_dtype), plain.to(index_dtype), values


def _to_device(components, device, index_dtype):
    c, p, v = components
    return (
        c.to(device=device).to(index_dtype),
        p.to(device=device).to(index_dtype),
        v.to(device=device),
    )


def _fingerprint(t):
    """Metadata + component fingerprint of a sparse compressed tensor."""
    accessor = "crow_indices" if t.layout in _ROW_LAYOUTS else "ccol_indices"
    plain = "col_indices" if t.layout in _ROW_LAYOUTS else "row_indices"
    return (
        tuple(t.shape),
        t.dtype,
        t.layout,
        t.sparse_dim(),
        t.dense_dim(),
        t._nnz(),
        tuple(getattr(t, accessor)().shape),
        tuple(getattr(t, plain)().shape),
        tuple(t.values().shape),
        getattr(t, accessor)().dtype,
        getattr(t, plain)().dtype,
        t.values().dtype,
    )


def _assert_same(res, ref, label=""):
    assert _fingerprint(res) == _fingerprint(
        ref
    ), f"fingerprint mismatch{f' ({label})' if label else ''}:\n  gems={_fingerprint(res)}\n  ref ={_fingerprint(ref)}"


def _assert_same_components(res, ref, component_names, label=""):
    """Compare the stored component values (not just their shapes)."""
    for name in component_names:
        assert torch.equal(
            getattr(res, name)().cpu(), getattr(ref, name)().cpu()
        ), f"{name} differs{f' ({label})' if label else ''}"


def _dense_sum(t):
    """Sum of the dense expansion, computed portably on the CPU."""
    return float(t.to_dense().to("cpu").sum())


def _assert_same_dense(res, ref, label=""):
    """Compare the dense expansions, requiring the same well-definedness.

    ``to_dense`` is not defined for every input the constructor accepts --
    measured on this build, a logical size whose trailing entries are dense
    dimensions can make ``to_dense`` raise a shape-mismatch ``RuntimeError``
    even though the tensor itself is well formed. Both sides must therefore
    agree on *whether* a dense form exists, and on its value when one does.
    """
    res_exc = ref_exc = None
    dense_res = dense_ref = None
    try:
        dense_res = _dense_sum(res)
    except Exception as exc:  # noqa: BLE001 - mirrors native undefinedness
        res_exc = exc
    try:
        dense_ref = _dense_sum(ref)
    except Exception as exc:  # noqa: BLE001
        ref_exc = exc
    assert (res_exc is None) == (
        ref_exc is None
    ), f"dense expansion defined on one side only{f' ({label})' if label else ''}: gems={res_exc!r} ref={ref_exc!r}"
    if res_exc is None:
        assert dense_res == pytest.approx(dense_ref, rel=1e-5)


