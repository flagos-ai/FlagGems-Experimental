def test_sparse_compressed_tensor_size_explicit(layout, size, nnz, block, dense):
    # aten::sparse_compressed_tensor.comp_plain_value_size -- the explicit-size
    # constructor, over all four layouts. The size is stored verbatim.
    dev = flag_gems.device
    c, p, v = _to_device(
        _gen_components(layout, size, nnz, block, dense, seed=1),
        dev,
        torch.int64,
    )
    ref = _call_size(
        _VALUE_SIZE,
        utils.to_reference(c),
        utils.to_reference(p),
        utils.to_reference(v),
        size,
        layout=layout,
    )
    res = flag_gems.sparse_compressed_tensor_size(
        c, p, v, list(size), layout=layout, device=dev
    )

    _assert_same(res, ref, "size")
    accessor, plain = (
        ("crow_indices", "col_indices")
        if layout in _ROW_LAYOUTS
        else ("ccol_indices", "row_indices")
    )
    _assert_same_components(res, ref, (accessor, plain, "values"), "size")
    _assert_same_dense(res, ref, "size")
    # The size is taken verbatim, not re-derived from the components.
