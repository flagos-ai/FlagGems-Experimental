@pytest.mark.sparse_compressed_tensor
def test_sparse_compressed_tensor_components_are_aliased_not_copied():
    # set_member_tensors stores the caller's tensors: the constructor neither
    # copies nor coalesces, and a write through the caller's handle is visible
    # on the constructed tensor (and vice versa). Measured for both the
    # compressed and the plain indices as well as for values.
    dev = flag_gems.device
    c, p, v = _to_device(
        _gen_components(torch.sparse_csr, (4, 4), 3, None, None, seed=4),
        dev,
        torch.int64,
    )

    res = flag_gems.sparse_compressed_tensor_size(
        c, p, v, [4, 4], layout=torch.sparse_csr, device=dev
    )
    assert res.crow_indices().data_ptr() == c.data_ptr()
    assert res.col_indices().data_ptr() == p.data_ptr()
    assert res.values().data_ptr() == v.data_ptr()

    # The reference side gets its OWN components, cloned after conversion, so
    # the two constructions never share a handle: this keeps the test honest in
    # both phases (under --ref=cpu, to_reference returns different tensors than
    # on the GPU phase, and mutating one side must not touch the other).
    ref_c = utils.to_reference(c).clone()
    ref_p = utils.to_reference(p).clone()
    ref_v = utils.to_reference(v).clone()
    ref_constructed = _call_size(
        _VALUE_SIZE, ref_c, ref_p, ref_v, [4, 4], layout=torch.sparse_csr
    )
    assert ref_constructed.crow_indices().data_ptr() == ref_c.data_ptr()
    assert ref_constructed.col_indices().data_ptr() == ref_p.data_ptr()
    assert ref_constructed.values().data_ptr() == ref_v.data_ptr()

    # A write through the caller's handle is visible on the constructed tensor:
    # that is the observable form of the alias, and the reference behaves the
    # same way, which keeps both sides pinned.
    before = res.values().clone()
    values_after_add = v + 1.0
    v.copy_(values_after_add)
    ref_v.copy_(ref_v + 1.0)
    assert torch.equal(res.values().cpu(), v.cpu())
    assert torch.equal(ref_constructed.values().cpu(), ref_v.cpu())
    assert torch.equal(res.values().cpu(), before.cpu() + 1.0)
    assert not torch.equal(res.values().cpu(), before.cpu())

    # The same holds for the compressed index: a write through the constructed
    # tensor propagates back to the caller's handle.
    res.crow_indices().add_(1)
    ref_constructed.crow_indices().add_(1)
    assert torch.equal(c.cpu(), res.crow_indices().cpu())
    assert torch.equal(ref_c.cpu(), ref_constructed.crow_indices().cpu())


