"""Accuracy tests for the sparse compressed tensor constructor overloads.

``sparse_compressed_tensor`` is a host-side constructor: there is no elementwise
arithmetic to compare, so the assertions below compare the *metadata and
components* of the produced tensor (shape, dtype, layout, sparse/dense dim,
nnz, compressed/plain/values shapes and dtypes, dense expansion) plus the
aliasing contract, against the same ATen overload on the reference device.

Native semantics were measured first, in processes that never imported
flag_gems (``runs/sparse_compressed_tensor/native_probe_a.log`` and
``native_probe_c.log`` on CUDA, scheduler jobs
``sparse_compressed_tensor-other-a2-*``). Observations the assertions mirror:

  - the three component tensors are stored by reference
    (``SparseCsrTensorImpl::set_member_tensors``): ``values()``,
    ``crow_indices()``/``ccol_indices()`` and ``col_indices()``/``row_indices()``
    share storage with the caller's tensors, so a write through either handle is
    visible on the other. Nothing is copied, and no coalescing is attempted;
  - ``.comp_plain_value_size`` stores the requested size verbatim -- there is no
    divisibility, bound or nnz cross-check while the sparse-invariant checker is
    disabled (the default);
  - ``.comp_plain_value`` infers the size from the components: the compressed
    extent is ``len(compressed_indices) - 1`` (times the block rows) and the
    plain extent is ``max(plain_indices) + 1`` (times the block columns), so the
    inferred shape is generally *smaller* than the size a caller would pass
    explicitly. An empty plain index gives a plain extent of 0;
  - both overloads reject a missing or non-compressed ``layout`` from the
    composite itself, with the CTOR name (not the unsafe variant's);
  - the packet forms take the target device from the ``device=`` keyword only,
    and index dtypes are stored verbatim (no int32 promotion -- that promotion
    belongs to the Python builtin's argument parser, a different call path);
  - under the invariant checker, every structural rejection is raised from a
    *device-side* assert on CUDA which poisons the context, so those cases are
    pinned on the CPU device only.

The Python builtin ``torch.sparse_compressed_tensor`` is deliberately NOT
asserted on for routing: its C++ argument parser resolves the ``size`` argument
to one of the two packet overloads before the dispatcher is entered, and the
same overload is reached for both call forms. Including it would add a second
hit per call without proving a second routing path.
"""

