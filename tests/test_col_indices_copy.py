def _make_csr(nnz, ncols=64, nrows=1, dtype=torch.float32, index_dtype=torch.int64):
    """Build a CSR tensor with ``nnz`` stored entries on ``flag_gems.device``.

    Row 0 owns all entries when ``nrows`` is 1, so the column-index buffer has
    exactly ``nnz`` elements and the kernel-selection branch is determined by
    the requested size alone.
    """
    gen = torch.Generator().manual_seed(0)
    ccol = torch.randint(0, ncols, (nnz,), generator=gen).to(index_dtype)
    crow = torch.zeros(nrows + 1, dtype=index_dtype)
    crow[1] = nnz
    values = torch.ones(nnz, dtype=dtype)
    return torch.sparse_csr_tensor(
        crow.to(flag_gems.device),
        ccol.to(flag_gems.device),
        values.to(flag_gems.device),
        (nrows, ncols),
    )


def _make_bsr(nnz_blocks, block=(2, 2), dtype=torch.float32, index_dtype=torch.int64):
    """Build a BSR tensor with ``nnz_blocks`` stored blocks."""
