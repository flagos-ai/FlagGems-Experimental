SHAPES = [(16,), (1024,), (2, 3, 4), (16, 128, 64, 60)]
if QUICK_MODE:
    SHAPES = [(2, 3)]

# Offsets keep the output small: the full matrix has (n + |offset|)^2 elements.
OFFSET_LIST = [-2, -1, 0, 1] if QUICK_MODE else [-5, -2, -1, 0, 1, 2, 7]


def _gen_input(shape, dtype):
    if dtype in utils.FLOAT_DTYPES or dtype is torch.float64:
        return torch.randn(shape, dtype=dtype, device=flag_gems.device)
    if dtype in utils.INT_DTYPES or dtype in (torch.int8, torch.int64):
        return torch.randint(
            torch.iinfo(dtype).min,
            torch.iinfo(dtype).max,
            shape,
            dtype=dtype,
            device="cpu",
        ).to(flag_gems.device)
    if dtype in (torch.uint8, torch.uint16, torch.uint32, torch.uint64):
        return torch.randint(
            0,
            int(torch.iinfo(dtype).max) + 1,
            shape,
            dtype=dtype,
            device="cpu",
        ).to(flag_gems.device)
    # BOOL_TYPES
    return (
        torch.randint(0, 2, size=shape, dtype=torch.bool, device="cpu").to(
            flag_gems.device
        )
        if shape
        else torch.empty(shape, dtype=torch.bool, device=flag_gems.device)
    )


@pytest.mark.diagflat
@pytest.mark.parametrize("offset", OFFSET_LIST)
@pytest.mark.parametrize("shape", SHAPES)
@pytest.mark.parametrize(
    "dtype", utils.FLOAT_DTYPES + utils.INT_DTYPES + utils.BOOL_TYPES
)
def test_accuracy_diagflat(shape, dtype, offset):
    inp = _gen_input(shape, dtype)
    ref_inp = utils.to_reference(inp)
    ref_flat = ref_inp.reshape(-1)

    ref_out = torch.ops.aten.diagflat(ref_inp, offset)
    res_out = flag_gems.diagflat(inp, offset)

    m = inp.numel() + abs(offset)
    assert res_out.shape == (m, m)
    assert res_out.dtype == inp.dtype
    assert res_out.is_contiguous() == ref_out.is_contiguous()
    # A fresh allocation, never a view of the input.
    assert res_out.data_ptr() != inp.data_ptr()
    # diagflat semantics: out[i, i + offset] == flat[i] for offset >= 0,
    # out[i - offset, i] == flat[i] for offset < 0; everything else is zero.
    # Build the expected matrix on the reference side and compare fully —
    # this catches both a wrong diagonal value and a missed off-diagonal
    # zero (e.g. a bad CB chunk mask).
    rows = utils.to_cpu(res_out, ref_out)
    n = inp.numel()
    expected = torch.zeros((m, m), dtype=ref_inp.dtype)
    idx = torch.arange(n)
    if offset >= 0:
        expected[idx, idx + offset] = ref_flat
    else:
        expected[idx - offset, idx] = ref_flat
    assert torch.equal(rows, expected)


