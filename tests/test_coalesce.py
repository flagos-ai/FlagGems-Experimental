def _make_coo(nnd, nnz, size, dtype, device, seed=0):
    """Build an *uncoalesced* sparse COO tensor with duplicate index columns.

    Indices are drawn with replacement from the flattened index space so
    duplicates exist by construction; the rows are then permuted so the input
    is not already sorted (an already-sorted duplicate-free input would take
    the identity path and never exercise the kernels).
    """
    gen = torch.Generator(device="cpu").manual_seed(seed)
    numel = 1
    for s in size[:nnd]:
        numel *= s
    flat = torch.randint(0, numel, (nnz,), generator=gen, dtype=torch.int64)
    indices = torch.empty((nnd, nnz), dtype=torch.int64)
    for d in reversed(range(nnd)):
        indices[d] = flat % size[d]
        flat = flat // size[d]
    perm = torch.randperm(nnz, generator=gen)
    indices = indices[:, perm].contiguous()
    if dtype.is_floating_point:
        values = torch.randn(nnz, generator=gen).to(dtype)
    elif dtype == torch.bool:
        values = torch.randint(0, 2, (nnz,), generator=gen).to(dtype)
    else:
        values = torch.randint(0, 6, (nnz,), generator=gen).to(dtype)
    return torch.sparse_coo_tensor(indices.to(device), values.to(device), size)


