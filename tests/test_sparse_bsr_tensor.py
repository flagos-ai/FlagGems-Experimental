def test_sparse_bsr_tensor_aliases_components():
    # The BSR constructor is a wiring op: the result's member tensors share
    # storage with the inputs, so writes through either side are visible on the
    # other.
    #
    # The reference aliasing check is driven from the ALREADY-CONVERTED base
    # tensors (not from a second utils.to_reference call), because with
    # --ref=cpu each conversion produces an independent CPU copy and comparing
    # a reference member against a separately converted input would compare
    # two unrelated allocations.
    dev = flag_gems.device
    crow, col, values, size = _make_components(2, 2, 2, 2, 13, dev)
    res = gems_size(crow, col, values, list(size))

    for name, got, want in (
        ("crow_indices", res.crow_indices(), crow),
        ("col_indices", res.col_indices(), col),
        ("values", res.values(), values),
    ):
        assert got.data_ptr() == want.data_ptr(), f"{name} must alias its input"
        assert got.untyped_storage().nbytes() == want.untyped_storage().nbytes()

    # Native is an alias too, so the contract being mirrored is real. The
    # reference is built from the converted base and compared against those
    # same converted tensors.
    ref_crow = utils.to_reference(crow)
    ref_col = utils.to_reference(col)
    ref_values = utils.to_reference(values)
    ref = ref_size(ref_crow, ref_col, ref_values, list(size))
    assert ref.crow_indices().data_ptr() == ref_crow.data_ptr()
    assert ref.col_indices().data_ptr() == ref_col.data_ptr()
    assert ref.values().data_ptr() == ref_values.data_ptr()

    # A write through the input component shows up in the constructed tensor
    # on both sides.
    values.fill_(7.0)
    assert bool((res.values() == 7.0).all().item())
    ref_values.fill_(7.0)
    assert bool((ref.values() == 7.0).all().item())


