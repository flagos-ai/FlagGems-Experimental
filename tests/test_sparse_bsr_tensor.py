@pytest.mark.sparse_bsr_tensor
def test_sparse_bsr_tensor_repeated_dispatch():
    # Repeated dispatcher-routed calls must be stable: no recursion (the
    # implementation delegates to aten::_sparse_bsr_tensor_unsafe, never to the
    # overload it implements) and no cross-call state.
    dev = flag_gems.device
    crow, col, values, size = _make_components(2, 2, 2, 2, 18, dev)
    for _ in range(5):
        r1 = gems_size(crow, col, values, list(size))
        assert r1._nnz() == int(crow[-1].item())
