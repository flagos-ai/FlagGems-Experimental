# ``sparse_bsr_tensor`` is a host-side constructor: its accuracy contract is
# which component tensors are accepted or rejected, whether the resulting
# tensor aliases them, and what the resulting metadata is. There is no
# elementwise arithmetic to compare, so the assertions below compare the
# metadata fingerprint and the stored components against the reference
# constructor rather than elementwise closeness.
#
# Native metadata and error contract captured in a process that never imported
# flag_gems (runs/sparse_bsr_tensor/native_probe_e.log / native_probe_h.log /
# native_probe_i.log):
#   - the member tensors ALIAS the inputs (data_ptr identity on all three);
#   - `size` is stored verbatim: it is not checked for block divisibility and
#     need not match the block shape carried by `values`;
#   - the packet overloads take their target device AND dtype from the keyword
#     arguments ONLY (TensorOptions falls back to the default device and
#     float32 when they are absent) and then assert every member matches, so
#     CUDA components built without `device=` raise "Values and compressed
#     tensor instance need to be on the same device." and non-float32 values
#     without `dtype=` raise "dtype of values (Half) must match dtype of
#     sparse tensor (Float)". The Python builtin has no such requirement
#     because its C++ argument parser derives both from `values`; the packet
#     forms must pass them explicitly, so every call below does;
#   - the size-inference form reads the block shape from values.shape[-2:] and
#     the block-row count from crow_indices.shape[-1] - 1;
#   - only integral col_indices dtypes are accepted by the size estimator.
