def _make_components(
    n_block_rows,
    n_block_cols,
    block_rows,
    block_cols,
    seed,
    device,
    index_dtype=torch.int64,
    value_dtype=torch.float32,
):
    """Build raw BSR components with a valid structure.

    Block columns are drawn strictly increasing per block row so the tensor
    also satisfies the (opt-in) compressed-index invariants; nnz is the number
    of stored blocks.
    """
    gen = torch.Generator(device="cpu").manual_seed(seed)
    nnz = 0
    crow = [0]
    col = []
    for _ in range(n_block_rows):
        # At least one block per block row, capped by the block-column count.
        if n_block_cols > 1:
            k = int(torch.randint(1, n_block_cols, (1,), generator=gen).item())
        else:
            k = 1
        picks = torch.randperm(n_block_cols, generator=gen)[:k].sort().values
        col.extend(int(v) for v in picks)
        nnz += k
        crow.append(nnz)
    crow_indices = torch.tensor(crow, dtype=index_dtype, device=device)
    col_indices = torch.tensor(col, dtype=index_dtype, device=device)
    # The generator is a CPU generator, so the random tensors are built on CPU
    # and moved; passing device=device alongside it would raise
    # "Expected a 'cuda' device type for generator but found 'cpu'".
    values = torch.randn((nnz, block_rows, block_cols), generator=gen).to(device)
    if value_dtype.is_floating_point:
        values = values.to(value_dtype)
    else:
        values = torch.randint(0, 8, (nnz, block_rows, block_cols), generator=gen).to(
            device=device, dtype=value_dtype
        )
    size = [n_block_rows * block_rows, n_block_cols * block_cols]
    return crow_indices, col_indices, values, size


