@pytest.mark.sparse_bsr_tensor
def test_sparse_bsr_tensor_dispatch_sentinel():
    # Registration-path check: a sentinel on the key this operator registers on
    # must intercept the packet calls, proving the shipped implementation is
    # what executes rather than the native kernel.
    #
    # Measured reachability, one subset per fresh process (native_probe_c_matrix
    # .log, _d_matrix.log, _f.log, _k.log). Both overloads are composite
    # constructors with no backend kernel, and the dispatcher walks the
    # Autograd key before any composite key, so:
    #   - the Autograd key ALONE is never selected (the key is not in the
    #     arguments' keyset until a backend kernel is found);
    #   - the device key alone is selected only by the packet form that omits
    #     both layout and device;
    #   - the device key AND the Autograd key together catch every form --
    #     which is exactly the pair _FULL_CONFIG registers.
    # So the sentinel below mirrors the shipped arrangement (CUDA + Autograd)
    # rather than the Autograd key alone. The Python builtin
    # torch.sparse_bsr_tensor does NOT route through either overload (its C++
    # argument parser calls the shared
    # sparse_compressed_tensor.comp_plain_value[_size] op, owned by the
    # sparse_compressed_tensor integration), so the builtin is deliberately not
    # asserted on here.
    dev = flag_gems.device
    crow, col, values, size = _make_components(2, 2, 2, 2, 19, dev)
    lib = torch.library.Library("aten", "IMPL")
    hits = []

    def sentinel_size(crow_indices, col_indices, vals, sz, **kwargs):
        hits.append("size")
        return flag_gems.sparse_bsr_tensor_crow_col_value_size(
            crow_indices, col_indices, vals, sz, **kwargs
        )

    def sentinel_nosize(crow_indices, col_indices, vals, **kwargs):
        hits.append("nosize")
        return flag_gems.sparse_bsr_tensor_crow_col_value(
            crow_indices, col_indices, vals, **kwargs
        )

    try:
        for key in (flag_gems.backend_info.dispatch_key, "Autograd"):
            lib.impl("sparse_bsr_tensor.crow_col_value_size", sentinel_size, key)
            lib.impl("sparse_bsr_tensor.crow_col_value", sentinel_nosize, key)

        # (a) the packet form that omits layout and device is caught by the
        #     DEVICE key. It then fails the same-device check, exactly as the
        #     native path does -- reaching that check at all proves the
        #     sentinel ran, so the assertion is on the sentinel hit, not on a
        #     successful construction.
        with pytest.raises(RuntimeError, match="same device"):
            torch.ops.aten.sparse_bsr_tensor.crow_col_value(crow, col, values)
        assert hits.count("nosize") >= 1, hits

        # (b) the forms that supply layout/device are caught by Autograd.
        assert torch.ops.aten.sparse_bsr_tensor.crow_col_value_size(
            crow, col, values, list(size), device=torch.device(dev)
        )._nnz() == int(crow[-1].item())
        assert torch.ops.aten.sparse_bsr_tensor.crow_col_value(
            crow, col, values, device=torch.device(dev)
        )._nnz() == int(crow[-1].item())
        assert hits.count("size") >= 1, hits
        assert hits.count("nosize") >= 2, hits
    finally:
        lib._destroy()

    # After destroying the sentinel the routed path is native again and still
    # agrees with the submitted implementation.
    assert torch.ops.aten.sparse_bsr_tensor.crow_col_value_size(
        crow, col, values, list(size), device=torch.device(dev)
    )._nnz() == int(crow[-1].item())
    assert gems_size(crow, col, values, list(size))._nnz() == int(crow[-1].item())


@pytest.mark.sparse_bsr_tensor
def test_sparse_bsr_tensor_enabled_registration_reaches_the_impl():
    # End-to-end routing proof on the PRODUCTION registration arrangement:
    # flag_gems.enable() registers _FULL_CONFIG exactly as a user would trigger
    # it, then poisoning the delegate that the implementation calls proves the
    # shipped code -- not a native kernel -- is what executes for every packet
    # call form. Measured in native_probe_k.log ("ROUTED INTO OUR IMPL" on all
    # six forms).
    dev = flag_gems.device
    crow, col, values, size = _make_components(2, 2, 2, 2, 22, dev)
    flag_gems.enable()

    original = torch.ops.aten._sparse_bsr_tensor_unsafe

    def poison(*args, **kwargs):
        raise RuntimeError("POISON-UNSAFE")

    forms = [
        (
            "size, device only",
            lambda: torch.ops.aten.sparse_bsr_tensor.crow_col_value_size(
                crow, col, values, list(size), device=torch.device(dev)
            ),
        ),
        (
            "size, layout+device",
            lambda: torch.ops.aten.sparse_bsr_tensor.crow_col_value_size(
                crow,
                col,
                values,
                list(size),
                layout=torch.sparse_bsr,
                device=torch.device(dev),
            ),
        ),
        (
            "size, bare",
            lambda: torch.ops.aten.sparse_bsr_tensor.crow_col_value_size(
                crow, col, values, list(size)
            ),
        ),
        (
            "infer, device only",
            lambda: torch.ops.aten.sparse_bsr_tensor.crow_col_value(
                crow, col, values, device=torch.device(dev)
            ),
        ),
        (
            "infer, layout+device",
            lambda: torch.ops.aten.sparse_bsr_tensor.crow_col_value(
                crow,
                col,
                values,
                layout=torch.sparse_bsr,
                device=torch.device(dev),
            ),
        ),
        (
            "infer, bare",
            lambda: torch.ops.aten.sparse_bsr_tensor.crow_col_value(crow, col, values),
        ),
    ]
    try:
        torch.ops.aten._sparse_bsr_tensor_unsafe = poison
        for label, fn in forms:
            with pytest.raises(RuntimeError, match="POISON-UNSAFE"):
                fn()
    finally:
        torch.ops.aten._sparse_bsr_tensor_unsafe = original

    # Health after the poison is removed: the routed path is still correct.
    res = torch.ops.aten.sparse_bsr_tensor.crow_col_value_size(
        crow, col, values, list(size), device=torch.device(dev)
    )
    assert res._nnz() == int(crow[-1].item())
    assert _meta(res) == _meta(gems_size(crow, col, values, list(size)))
