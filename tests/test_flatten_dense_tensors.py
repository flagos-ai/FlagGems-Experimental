def _gen_tensor(shape, dtype, base):
    """A deterministic tensor of `shape` whose values encode `base`."""
    numel = 1
    for dim in shape:
        numel *= dim
    values = torch.arange(numel, dtype=torch.int64) + base
    if dtype.is_floating_point:
        return (values.to(torch.float64) * 0.5).to(dtype).to(flag_gems.device)
    if dtype == torch.bool:
        return (values % 2 == 0).to(flag_gems.device)
    return values.to(dtype).to(flag_gems.device)


