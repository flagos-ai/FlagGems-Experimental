def test_accuracy_dstack_out_int_into_float(in_dtype):
    # int/bool inputs may be written into any float out (can_cast holds).
    if in_dtype is torch.bool:
        a = torch.tensor([True, False, True], device=flag_gems.device)
        b = torch.tensor([False, True, True], device=flag_gems.device)
    else:
        a = torch.arange(1, 4, dtype=in_dtype, device=flag_gems.device)
        b = torch.arange(1, 4, dtype=in_dtype, device=flag_gems.device)
    ref_out = torch.ops.aten.dstack([utils.to_reference(a), utils.to_reference(b)])

    out = torch.empty(1, 3, 2, dtype=torch.float32, device=flag_gems.device)
    res = flag_gems.dstack_out([a, b], out=out)
    assert res is out
    assert out.dtype == torch.float32
    utils.gems_assert_equal(res, ref_out.to(torch.float32))


@pytest.mark.dstack_out
def test_exception_dstack_out_input_validated_before_resize():
    # An invalid input list must raise BEFORE the out buffer is resized.
    out = torch.empty(100, device=flag_gems.device)
    bad = [
        torch.ones(2, 3, device=flag_gems.device),
        torch.ones(2, 4, device=flag_gems.device),
    ]
    with pytest.raises(RuntimeError):
        flag_gems.dstack_out(bad, out=out)
    assert tuple(out.shape) == (100,)
    with pytest.raises(RuntimeError):
        flag_gems.dstack_out([], out=out)
    assert tuple(out.shape) == (100,)
