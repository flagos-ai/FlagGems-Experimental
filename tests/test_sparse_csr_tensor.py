# ``sparse_csr_tensor`` is a host-side constructor: there is no elementwise
# arithmetic to compare. The accuracy contract is (a) the resulting tensor's
# metadata and stored components, (b) the **aliasing** contract (the result's
# crow_indices/col_indices/values ARE the input tensors -- verified with
# data_ptr identity and write-through), and (c) which argument combinations are
# accepted or rejected, with the same exception class.
#
# Native behaviour measured on this build in processes that never imported
# flag_gems (runs/sparse_csr_tensor/probe5_cpu.py, probe6.py, probe7.py,
# probe8.py, probe10.py, probe12.py):
#   * both packet overloads ALIAS all three components (data_ptr identity);
#   * they do NOT cast: dtype=None resolves to the default dtype, so a float64
#     `values` with dtype=None raises "dtype of values (Double) must match
#     dtype of sparse tensor (Float)";
#   * the size-inferred overload derives the shape as
#     (crow_indices.shape[-1] - 1) x (max(col_indices) + 1) and stores an
#     out-of-range column index as a WIDER shape rather than rejecting it;
#   * the explicit-size overload stores `size` verbatim while the invariants
#     check is disabled (the default);
#   * with an explicit `device` kwarg the sparse instance is built on that
#     device; WITHOUT one the packet builds a CPU instance and rejects CUDA
#     components with "Values and compressed tensor instance need to be on the
#     same device" -- for the reference and the implementation alike (measured
#     on both). Every construction below therefore names the components'
#     device on both sides through the ``_ref_*``/``_gems_*`` helpers, and the
#     no-device rejection has its own test;
#   * structural validation (crow/col bounds, nnz agreement) happens only while
#     torch.sparse.check_sparse_tensor_invariants is enabled.
#
# The dtype *cast* in the package source belongs to the Python builtin, which
# materialises the components in the requested dtype before construction; it is
# pinned below through the builtin, not through the packet overloads.

