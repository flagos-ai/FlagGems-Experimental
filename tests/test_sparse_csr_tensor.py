@pytest.mark.sparse_csr_tensor
def test_sparse_csr_tensor_dispatch_reachable():
    # Registration-path check: a sentinel wrapper on the key this operator is
    # registered under (CompositeImplicitAutograd -- the only kernel the two
    # native overloads occupy, measured per key in a fresh process) proves the
    # packet call routes into the registered implementation instead of falling
    # through to the native kernel. A device-key sentinel is not selected for
    # this call form, which is exactly why the registration carries the
    # composite key. The sentinel delegates to the implementation, never back
    # through the aten overload, so it cannot recurse.
    hits = []

    def sentinel(*args, **kwargs):
        hits.append(1)
        return GEMS_CSR_VALUE(*args, **kwargs)

    lib = torch.library.Library("aten", "IMPL")
    try:
        lib.impl(
            "sparse_csr_tensor.crow_col_value",
            sentinel,
            torch._C.DispatchKey.CompositeImplicitAutograd.name,
        )
        crow, col, values = _make_components(3, 2, 3, seed=20)
        ref = torch.ops.aten.sparse_csr_tensor.crow_col_value(
            crow, col, values, device=flag_gems.device
        )
        assert len(hits) == 1, "the CompositeImplicitAutograd sentinel was not selected"
        assert _meta(ref) == _meta(_gems_value(crow, col, values))
    finally:
        lib._destroy()


@pytest.mark.sparse_csr_tensor
def test_sparse_csr_tensor_dispatch_size_overload_reachable():
    # The same reachability check for the explicit-size overload.
    hits = []

