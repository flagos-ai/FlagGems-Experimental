def _make_components(nnz, nrows, ncols, index_dtype=torch.int64, seed=0):
    """Build (crow_indices, col_indices, values) for a CSR tensor.

    ``crow`` is non-decreasing and ends at ``nnz``. At least one column index
    equals ``ncols - 1`` when ``nnz > 0``, so the size-inferred overload
    produces the same shape as the explicit ``(nrows, ncols)`` one -- which is
    what lets the two overloads be compared against each other.
    """
    gen = torch.Generator(device="cpu").manual_seed(seed)
    crow = torch.zeros(nrows + 1, dtype=torch.int64)
    if nnz:
        cuts = sorted(torch.randint(0, nnz + 1, (nrows,), generator=gen).tolist())
        crow[1:] = torch.tensor(cuts, dtype=torch.int64)
    crow[-1] = nnz
    if nnz:
        col = torch.randint(0, max(ncols, 1), (nnz,), generator=gen)
        col[0] = ncols - 1
    else:
        col = torch.empty(0, dtype=torch.int64)
    values = torch.randn(nnz, generator=gen) if nnz else torch.empty(0)
    dev = flag_gems.device
    return crow.to(index_dtype).to(dev), col.to(index_dtype).to(dev), values.to(dev)


def _meta(t):
    """Metadata fingerprint of a sparse CSR tensor."""
    assert t.layout == torch.sparse_csr, f"expected CSR layout, got {t.layout}"
    return (
        tuple(t.shape),
        t.dtype,
        t.layout,
        t.sparse_dim(),
        t.dense_dim(),
        t._nnz(),
        tuple(t.crow_indices().shape),
        tuple(t.col_indices().shape),
        tuple(t.values().shape),
        t.values().dtype,
    )


def _aliases(res, crow, col, values):
    """True when every component is the *same storage* as the input.

    The constructor stores the components verbatim, so the result must share
    their storage -- data_ptr identity alone is not enough, because a view of
    the same storage can carry a different data_ptr; both are checked.
    """
    return (
        res.crow_indices().data_ptr() == crow.data_ptr()
        and res.col_indices().data_ptr() == col.data_ptr()
        and res.values().data_ptr() == values.data_ptr()
        and res.crow_indices().untyped_storage().data_ptr()
        == crow.untyped_storage().data_ptr()
        and res.col_indices().untyped_storage().data_ptr()
        == col.untyped_storage().data_ptr()
        and res.values().untyped_storage().data_ptr()
        == values.untyped_storage().data_ptr()
    )


