_IMPL_REGISTERED = False


def _register_impl():
    """Install the submitted implementation on the dispatcher keys.

    The repository registration reaches COO tensors through the SparseCUDA
    key (never the plain CUDA key — measured), so the tests that exercise
    dispatcher-provided behaviour register the same way. Only the CUDA /
    SparseCUDA keys are touched, so the CPU references used by the
    value-comparison tests keep reaching the native kernel.
    """
    global _IMPL_REGISTERED
    if _IMPL_REGISTERED:
        return
    lib = torch.library.Library("aten", "IMPL")
    lib.impl("copy_sparse_to_sparse_", flag_gems.copy_sparse_to_sparse_, "CUDA")
    lib.impl("copy_sparse_to_sparse_", flag_gems.copy_sparse_to_sparse_, "SparseCUDA")
    _IMPL_REGISTERED = True


@pytest.mark.copy_sparse_to_sparse_
def test_copy_sparse_to_sparse__dispatcher_path():
    # The operator must be reachable through the dispatcher (the patched
    # ``Tensor.copy_`` form included), not only through a direct call.
    _register_impl()

    for tag, dst_nnz, src_shape, src_nnz in [
        ("inplace", 6, (3, 4), 6),
        ("grow", 0, (3, 4), 6),
        ("shrink-empty", 0, (2, 2), 3),
    ]:
        dst = _make_coo((3, 4), dst_nnz, seed=33).to(flag_gems.device)
        src = _make_coo(src_shape, src_nnz, seed=34).to(flag_gems.device)
        # A second name for the same object: the in-place op must update it.
        alias = dst
        res = torch.ops.aten.copy_sparse_to_sparse_(dst, src)
        assert res is dst, tag
        assert alias is dst, tag
        assert tuple(dst.shape) == tuple(src_shape), tag
        assert dst._nnz() == src_nnz, tag
        assert torch.equal(dst._indices(), src._indices()), tag
        assert torch.equal(dst._values(), src._values()), tag

    # ``Tensor.copy_`` on a COO pair reaches the same registered kernel
    # (measured: the SparseCUDA key intercepts it).
    dst = _make_coo((3, 4), 0, seed=35).to(flag_gems.device)
    src = _make_coo((3, 4), 5, seed=36).to(flag_gems.device)
    res = dst.copy_(src)
    assert res is dst
    assert dst._nnz() == 5
    assert torch.equal(dst._values(), src._values())

    # Version-counter parity with native: the dispatched in-place call goes
    # through the in-place view layer, which bumps the counter exactly once
    # (the implementation itself must not bump it a second time).
    t = _make_coo((3, 4), 4, seed=37).to(flag_gems.device)
    v0 = t._version
    torch.ops.aten.copy_sparse_to_sparse_(
        t, _make_coo((3, 4), 4, seed=38).to(flag_gems.device)
    )
    assert t._version == v0 + 1
    # The self-copy short-circuit is also a dispatched in-place call: native
    # bumps the counter once for it too (measured), and the implementation's
    # early return must leave the dispatcher-provided bump as the only one.
    torch.ops.aten.copy_sparse_to_sparse_(t, t)
    assert t._version == v0 + 2


