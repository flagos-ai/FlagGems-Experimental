def _numel(shape):
    n = 1
    for s in shape:
        n *= s
    return n


def _make_coo(shape, nnz, seed=0, flag=None, dtype=torch.float32, nnd=None):
    """A sparse COO tensor of ``shape`` with ``nnz`` stored entries.

    ``nnd`` is the sparse-dimension count (defaults to ``len(shape)``); a
    smaller value builds a hybrid tensor whose values carry trailing dense
    dimensions. ``flag`` forces the coalesced bit (``None`` keeps the
    constructor's own state); ``flag=False`` leaves the indices unsorted.
    """
    if nnd is None:
        nnd = len(shape)
    numel = _numel(shape[:nnd])
    nnz = min(nnz, numel)
    if nnz == 0:
        idx = torch.zeros(nnd, 0, dtype=torch.int64)
        dense = tuple(shape[nnd:])
        vals = torch.zeros((0,) + dense, dtype=dtype)
        t = torch.sparse_coo_tensor(idx, vals, shape)
        return t if flag is None else t._coalesced_(flag)
    gen = torch.Generator().manual_seed(seed)
    flat = torch.randperm(numel, generator=gen)[:nnz]
    if flag is not False:
        flat = flat.sort().values
    idx = torch.empty((nnd, nnz), dtype=torch.int64)
    f = flat.clone()
    for d in reversed(range(nnd)):
        idx[d] = f % shape[d]
        f = f // shape[d]
    dense = tuple(shape[nnd:])
    vals = torch.arange(nnz * _numel(dense), dtype=torch.float32)
    vals = vals.reshape((nnz,) + dense).to(dtype)
    t = torch.sparse_coo_tensor(idx, vals, shape)
    return t if flag is None else t._coalesced_(flag)


