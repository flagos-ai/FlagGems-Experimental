@pytest.mark._indices_copy
def test_accuracy_indices_copy_out_registration_path():
    # The production registration is keyed on SparseCUDA (COO tensors never
    # carry a plain CUDA key). Register through that exact key inside a
    # throwaway Library scope, then call the aten overload through the
    # dispatcher: a wrong key would raise the native "no kernel for this
    # backend" error instead of returning our values.
    lib = torch.library.Library("aten", "IMPL")
    lib.impl("_indices_copy", flag_gems._indices_copy, "SparseCUDA")
    lib.impl("_indices_copy.out", flag_gems._indices_copy_out, "SparseCUDA")
    try:
        x = _make_coo(3, (4, 5), flag_gems.device)
        res = torch.ops.aten._indices_copy.default(x)
        ref = _ref_indices_copy(utils.to_reference(x))
        assert torch.equal(utils.to_cpu(res, ref), ref)
        assert res.data_ptr() != x._indices().data_ptr()

        out = torch.empty((2, 3), dtype=torch.int64, device=flag_gems.device)
        res_out = torch.ops.aten._indices_copy.out(x, out=out)
        assert res_out is out
        assert torch.equal(utils.to_cpu(out, ref), ref)
    finally:
        lib._destroy()
