# Native reference for the copy: the ATen implementation of
# ``aten::_indices_copy`` is ``_indices(self).clone(memory_format=Contiguous)``
# (code-generated CompositeExplicitAutogradNonFunctional kernel, see
# torchgen/gen_functionalization_type.py GenCompositeViewCopyKernel). The
# shipped CUDA build registers that composite kernel only for the dense
# backend keys and *not* for SparseCUDA, so the dispatcher rejects every
# COO input natively -- probed: "Could not run 'aten::_indices_copy' with
# arguments from the 'SparseCUDA' backend". The reference below therefore
# evaluates the same formula through ops that do have SparseCUDA kernels
# (``aten::_indices``), which is what the native kernel itself would run.


def _ref_indices_copy(x):
    return torch.ops.aten._indices.default(x).clone(
        memory_format=torch.contiguous_format
    )


def _make_coo(nnz, shape, device, uncoalesced=False, hybrid=False, index_view=False):
    """Build a sparse COO tensor with ``nnz`` stored entries.

    ``hybrid=True`` makes the last dim of ``shape`` dense: the index matrix has
    ``len(shape) - 1`` rows and each value carries ``shape[-1:]`` elements.

    ``index_view=True`` builds the index matrix as a non-contiguous *view*
    (a slice of a wider int64 tensor), which is legal -- ``torch.sparse_coo_tensor``
    stores the given tensor as-is, and ``_indices()`` then reports a
    non-contiguous stride. That is the only way to reach the 2-D strided
    branch of the implementation.
    """
    n_sparse = len(shape) - 1 if hybrid else len(shape)
    if nnz == 0:
        indices = torch.empty((n_sparse, 0), dtype=torch.int64, device=device)
    else:
        indices = torch.randint(
            0, min(shape) if min(shape) > 0 else 1, (n_sparse, nnz), device=device
        )
    if index_view and nnz > 0:
        # Slice a wider buffer so the stored index matrix is a strided view.
        padded = torch.randint(0, 4, (n_sparse, nnz + 5), device=device)
        indices = padded[:, :nnz]
        assert not indices.is_contiguous()
    if hybrid:
        values = torch.randn((nnz,) + tuple(shape[n_sparse:]), device=device)
    else:
        values = torch.randn(nnz, device=device)
    out = torch.sparse_coo_tensor(indices, values, shape, device=device)
    if uncoalesced:
        out = out.coalesce() if not out.is_coalesced() else out
        out._coalesced_(False)
        assert not out.is_coalesced()
    return out


