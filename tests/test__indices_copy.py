@pytest.mark._indices_copy
@pytest.mark.parametrize("nnz,shape", COO_CASES)
def test_accuracy_indices_copy_coo(nnz, shape):
    # The result is a fresh, contiguous (sparse_dim, nnz) int64 copy: it must
    # never alias the input's stored index matrix.
    x = _make_coo(nnz, shape, flag_gems.device)
    ref_out = _ref_indices_copy(utils.to_reference(x))
    res_out = flag_gems._indices_copy(x)

    utils.gems_assert_equal(res_out, ref_out)
    assert res_out.shape == (x.sparse_dim(), nnz)
    assert res_out.dtype == torch.int64
    assert res_out.device == x.device
    assert res_out.is_contiguous()
    assert res_out._base is None
    if nnz > 0:
        # Fresh storage; an empty CUDA tensor has no backing page, so both
        # data_ptrs would be 0 and the property is not observable there. A
        # copy, not a view: mutating the input's indices afterwards must not
        # be reflected in the result either.
        assert res_out.data_ptr() != x._indices().data_ptr()
        before = res_out.clone()
        x._indices().zero_()
        assert torch.equal(res_out, before)


