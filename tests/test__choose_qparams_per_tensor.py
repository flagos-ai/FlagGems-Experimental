@pytest.mark._choose_qparams_per_tensor
def test_accuracy__choose_qparams_threaded_use():
    # The contiguous path shares one set of per-device scratch buffers (partial
    # min/max slots, an arrival counter, the packed result and the completion
    # flag), so calls from two threads on two streams run under the module
    # lock. Without it the second kernel overwrites the first call's partials,
    # and the first call's host spin can consume the other call's flag. Assert
    # both threads get their own input's answer.
    import threading

    a = torch.randn(1 << 16, device=_DEVICE)
    b = torch.randn(1 << 16, device=_DEVICE) * 5.0 + 2.0
    expected = {
        "a": _ATEN(a, False),
        "b": _ATEN(b, True),
    }
    results, errors = {}, []

    def worker(name, tensor, reduce_range):
        stream = torch.cuda.Stream()
        try:
            with torch.cuda.stream(stream):
                for _ in range(10):
                    results[name] = flag_gems._choose_qparams_per_tensor(
                        tensor, reduce_range
                    )
                stream.synchronize()
        except Exception as exc:  # noqa: BLE001 - reported through the assert
            errors.append(f"{name}: {type(exc).__name__}: {exc}")

    threads = [
        threading.Thread(target=worker, args=("a", a, False)),
        threading.Thread(target=worker, args=("b", b, True)),
    ]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()

    assert not errors, errors
    assert results["a"] == expected["a"], (results["a"], expected["a"])
    assert results["b"] == expected["b"], (results["b"], expected["b"])


@pytest.mark._choose_qparams_per_tensor
def test_accuracy__choose_qparams_caller_graph_capture():
    # A call can arrive while the *caller* holds a torch.cuda.graph() block.
    # Measured on the H20 build (probes Q3/R1/R2, clean process per case,
    # primed and unprimed cache, contiguous and strided): the launch is
    # recorded, not executed, so the pinned completion flag never rises -- a
    # bare implementation would hang the host spin for ever. With the capture
    # guard the call surfaces the same ``RuntimeError`` native raises for its
    # own ``min().item()`` under capture ("operation failed due to a previous
    # error during capture"). Neither side's capture context survives the
    # error (torch tears it down), and every later call outside the capture
    # returns the normal value on both sides. The test pins the raised class
    # plus the capture-status fragment rather than one build's full sentence.
    x = torch.randn(1 << 16, device=_DEVICE)
    expected = _ATEN(x, False)

    # Prime the replay entry so the cache-hit branch is the one under test.
    for _ in range(3):
        assert flag_gems._choose_qparams_per_tensor(x, False) == expected

    graph = torch.cuda.CUDAGraph()
    with pytest.raises(RuntimeError) as res_err:
        with torch.cuda.graph(graph):
            flag_gems._choose_qparams_per_tensor(x, False)
    assert "capture" in str(res_err.value).lower()

    # Native rejects a captured call the same way; assert class + fragment,
    # not the full sentence (wording comes from the CUDA runtime layer and
    # can differ between builds).
    with pytest.raises(RuntimeError) as ref_err:
        with torch.cuda.graph(graph):
            _ATEN(x, False)
    assert "capture" in str(ref_err.value).lower()

    # After the capture the normal path keeps working on both sides.
    assert flag_gems._choose_qparams_per_tensor(x, False) == expected
    assert _ATEN(x, False) == expected

    # The replay cache entry must not have been consumed or poisoned: a
    # primed tensor replays normally after the failed capture.
    assert flag_gems._choose_qparams_per_tensor(x, False) == expected
