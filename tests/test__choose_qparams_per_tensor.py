@pytest.mark._choose_qparams_per_tensor
def test_accuracy__choose_qparams_reduce_range_semantics():
    # ``reduce_range=True`` swaps the qmax divisor (255 -> 127), which scales
    # the raw scale by 255/127 and floors the zero point towards zero. Assert
    # the relationship against native rather than a constant, on a symmetric
    # and two one-sided ranges. The scale ratio is exactly 255/127 in the
    # float32 arithmetic both sides use (measured: 0.015748031496062992 ==
    # 0.00784313725490196 * 255 / 127; a 2.0 factor is NOT the relation --
    # 255/127 != 2 -- and failed the first GPU run).
    for values in ([-1.0, 1.0], [0.0, 1.0], [-1.0, 0.0]):
        x = torch.tensor(values, dtype=torch.float32, device=_DEVICE)
        ref_full = _ATEN(x, False)
        ref_reduced = _ATEN(x, True)
        res_full = flag_gems._choose_qparams_per_tensor(x, False)
        res_reduced = flag_gems._choose_qparams_per_tensor(x, True)
        _assert_same_result(res_full, ref_full, f"{values}/full")
        _assert_same_result(res_reduced, ref_reduced, f"{values}/reduced")
        assert res_reduced[0] == res_full[0] * 255.0 / 127.0
        assert res_reduced[1] == math.floor(res_full[1] / 2)


@pytest.mark._choose_qparams_per_tensor
def test_accuracy__choose_qparams_reduce_range_vs_qnnpack_engine():
    # Native silently DROPS reduce_range when the quantization engine is
    # QNNPACK (``qEngine() == QNNPACK``), because the fbgemm-style range
    # reduction is not what that engine wants. This implementation always
    # honours the argument, so the two disagree *only* under that engine.
    # Measured: with the default ``x86`` engine they agree; the engine is
    # restored before leaving the test either way.
    x = torch.tensor([-1.0, 1.0], dtype=torch.float32, device=_DEVICE)
    original = torch.backends.quantized.engine
    try:
        torch.backends.quantized.engine = "x86"
        ref = _ATEN(x, True)
        res = flag_gems._choose_qparams_per_tensor(x, True)
        _assert_same_result(res, ref, "x86 engine, reduce_range=True")

        torch.backends.quantized.engine = "qnnpack"
        ref_q = _ATEN(x, True)
        res_q = flag_gems._choose_qparams_per_tensor(x, True)
        # Native ignores the flag under QNNPACK: same answer as reduce_range=False.
        assert ref_q == _ATEN(x, False), ref_q
        # The implementation does not: it is the reduced-range answer.
        assert res_q == res, (res_q, res)
        assert res_q != ref_q
    finally:
        torch.backends.quantized.engine = original
    assert torch.backends.quantized.engine == original


