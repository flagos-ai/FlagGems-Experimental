def _gen(shape, dtype, device=None):
    """Generate a finite input of ``shape``/``dtype`` on the gems device."""
    device = device or _DEVICE
    if dtype.is_floating_point:
        return torch.randn(shape, dtype=dtype, device=device)
    if dtype == torch.bool:
        return torch.randint(0, 2, size=shape, dtype=dtype, device=device)
    info = torch.iinfo(dtype)
    return torch.randint(
        max(info.min, -128), min(info.max, 128), shape, dtype=dtype, device=device
    )


