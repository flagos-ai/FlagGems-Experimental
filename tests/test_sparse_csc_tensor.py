def _make_csc(
    nnz,
    nrows,
    ncols,
    seed,
    device,
    dtype=torch.float32,
    idx_dtype=torch.int64,
    dense=(),
):
    """Build raw (ccol, row, values) for a CSC tensor.

    ``nnz`` stored elements are laid out column-major across ``ncols`` columns
    without duplicates, so ``ccol_indices`` is non-decreasing and ends at nnz.
    A ``dense`` tuple adds trailing dense dimensions to ``values``.
    """
    gen = torch.Generator(device="cpu").manual_seed(seed)
    per_col = [0] * ncols
    for i in range(nnz):
        per_col[i % ncols] += 1
    row = torch.zeros(nnz, dtype=torch.int64)
    col = torch.zeros(nnz, dtype=torch.int64)
    pos = 0
    for c in range(ncols):
        if per_col[c] == 0:
            continue
        picks = torch.randperm(max(nrows, 1), generator=gen)[: per_col[c]].sort().values
        row[pos : pos + per_col[c]] = picks
        col[pos : pos + per_col[c]] = c
        pos += per_col[c]
    ccol = torch.zeros(ncols + 1, dtype=torch.int64)
    ccol[1:] = torch.tensor(per_col, dtype=torch.int64).cumsum(0)
    vshape = (nnz,) + tuple(dense)
    values = torch.randn(vshape, generator=gen).to(device).to(dtype)
    # CSC storage order: by column, then by row within the column.
    order = torch.argsort(col * max(nrows, 1) + row, stable=True)
    return ccol.to(device).to(idx_dtype), row[order].to(device).to(idx_dtype), values


def _meta(t):
    """Metadata fingerprint of a sparse CSC tensor."""
    assert t.layout == torch.sparse_csc, f"expected CSC layout, got {t.layout}"
    return (
        tuple(t.shape),
        t.dtype,
        t.layout,
        t.sparse_dim(),
        t.dense_dim(),
        t._nnz(),
        tuple(t.ccol_indices().shape),
        tuple(t.row_indices().shape),
        tuple(t.values().shape),
        t.ccol_indices().dtype,
        t.row_indices().dtype,
    )


def _alias(result, ccol, row, values):
    """True when every member tensor is the very tensor passed in."""
    return (
        result.ccol_indices().data_ptr() == ccol.data_ptr()
        and result.row_indices().data_ptr() == row.data_ptr()
        and result.values().data_ptr() == values.data_ptr()
    )


def _ref_components(ccol, row, values):
    """Convert the components for the reference side, together.

    ``utils.to_reference`` converts each tensor independently, so a pair of
    tensors that shared storage would not share it any more. Every reference
    call below therefore derives its arguments from these converted tensors,
    never from a fresh conversion of the live ones (the --ref=cpu trap).
    """
    return utils.to_reference(ccol), utils.to_reference(row), utils.to_reference(values)


def _device_of(ref_ccol):
    """Device the reference packet needs: the reference components' own."""
    return ref_ccol.device


