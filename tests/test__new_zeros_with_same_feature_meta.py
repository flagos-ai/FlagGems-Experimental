@pytest.mark._new_zeros_with_same_feature_meta_out
def test_accuracy_new_zeros_same_feature_meta_out_dtype_mismatch_raises():
    # Native raises RuntimeError when the out buffer's dtype differs from
    # other's; the message is asserted on both sides.
    other = _gen_input((2, 3), torch.float32)
    self_t = _gen_input((2, 3), torch.float32)
    out_wrong = torch.zeros((2, 3), dtype=torch.float64, device=flag_gems.device)

    with pytest.raises(RuntimeError, match="Expected out tensor to have dtype"):
        flag_gems._new_zeros_with_same_feature_meta_out(self_t, other, out=out_wrong)

    ref_self = utils.to_reference(self_t)
    ref_other = utils.to_reference(other)
    # The ref buffer shares the ref device (native checks device before dtype,
    # and the out tensor is device-bound), so both phases see the dtype error.
    ref_wrong = torch.zeros((2, 3), dtype=torch.float64, device=ref_other.device)
    with pytest.raises(RuntimeError, match="Expected out tensor to have dtype"):
        torch.ops.aten._new_zeros_with_same_feature_meta.out(
            ref_self, ref_other, self_num_batch_dims=0, out=ref_wrong
        )
