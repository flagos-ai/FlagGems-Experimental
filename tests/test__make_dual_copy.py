# (torchgen/gen_functionalization_type.py, GenCompositeViewCopyKernel): torchgen
# generates its body as
#     ``_make_dual(primal, tangent, level).clone(memory_format=Contiguous)``.
# The inner ``_make_dual`` is the inference-tensor-only composite, whose kernel
# asserts
#     ``InferenceMode::is_enabled() && primal.is_inference() &&
#       tangent.is_inference()``          (AutogradComposite.cpp:23)
# whenever it is reached. The measured gate matrix on this build is
#   default: runs under inference_mode (any tensor kind), or for a pair of
#            inference tensors outside it; raises in the other cells;
#   .out:    runs only under inference_mode with both operands inference
#            tensors; raises in the other cells.
# The accuracy matrix is driven in the cells where the shipped operator is
# callable, and the raising cells are pinned separately.

