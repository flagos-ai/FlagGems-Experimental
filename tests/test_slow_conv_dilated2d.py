def _gen_input(shape, dtype):
    return torch.randn(shape, dtype=dtype, device=flag_gems.device)


def _expected_shape(in_shape, w_shape, kernel_size, stride, padding, dilation):
    def pair(v):
        if isinstance(v, (tuple, list)):
            return int(v[0]), int(v[1])
        return int(v), int(v)

    kh, kw = pair(kernel_size)
    sh, sw = pair(stride)
    ph, pw = pair(padding)
    dh, dw = pair(dilation)
    h_out = (in_shape[2] + 2 * ph - dh * (kh - 1) - 1) // sh + 1
    w_out = (in_shape[3] + 2 * pw - dw * (kw - 1) - 1) // sw + 1
    return (in_shape[0], w_shape[0], h_out, w_out)


