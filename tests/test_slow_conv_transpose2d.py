@pytest.mark.slow_conv_transpose2d
@pytest.mark.parametrize(
    "name",
    [
        "stride_zero",
        "dilation_zero",
        "output_padding_too_large",
        "bad_bias_shape",
    ],
)
def test_accuracy_slow_conv_transpose2d_bad_arguments(name):
    # Each rejection below is also produced by native (measured on this build:
    # a 1 x 2 x 4 x 4 input and a (2, 3, 3, 3) weight) -- but the reference's
    # wording is never asserted: for the reference side only the class is pinned,
    # and the implementation-side fragment is this file's own literal. Note that
    # native's own guard is stricter in wording than the implementation is
    # inclusive: negative padding and negative output_padding are ACCEPTED by
    # native (measured) and by the implementation (pinned separately below).
    inp = torch.randn(1, 2, 4, 4, device=flag_gems.device)
    weight = torch.randn(2, 3, 3, 3, device=flag_gems.device)
    bias = torch.randn(3, device=flag_gems.device)
    kwargs = dict(
        stride=(1, 1),
        padding=(0, 0),
        output_padding=(0, 0),
        dilation=(1, 1),
    )
    fragment = None
    if name == "stride_zero":
        kwargs["stride"] = (0, 0)
        fragment = "non-positive stride"
    elif name == "dilation_zero":
        kwargs["dilation"] = (0, 0)
        fragment = "dilation should be greater than zero"
    elif name == "output_padding_too_large":
        kwargs["stride"] = (2, 2)
        kwargs["dilation"] = (2, 2)
        kwargs["output_padding"] = (2, 2)
        fragment = "smaller than either stride or dilation"
    elif name == "bad_bias_shape":
        bias = torch.randn(4, device=flag_gems.device)
        fragment = "one element per output channel"

    with pytest.raises(RuntimeError, match=fragment):
        flag_gems.slow_conv_transpose2d(inp, weight, (3, 3), bias, **kwargs)
    # Reference side: same class, no message assertion (A1 -- a different torch
    # build raises the same rejection from a different code path).
    try:
        torch.ops.aten.slow_conv_transpose2d.default(
            inp,
            weight,
            [3, 3],
            bias,
            list(kwargs["stride"]),
            list(kwargs["padding"]),
            list(kwargs["output_padding"]),
            list(kwargs["dilation"]),
        )
        raised = False
    except Exception as exc:  # noqa: BLE001
        raised = True
        assert isinstance(exc, RuntimeError), type(exc).__name__
    assert raised, f"native accepted {name}"


