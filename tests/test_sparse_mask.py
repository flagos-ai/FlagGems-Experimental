@pytest.mark.sparse_mask
def test_accuracy_sparse_mask_dispatch_sentinel():
    # Registration-path check (fresh-process sentinel matrix in the report):
    # a dense self x COO mask resolves on the MASK's SparseCUDA key -- the
    # plain CUDA key never sees this call. A sentinel on SparseCUDA must
    # intercept every real call form.
    hits = []

    def sentinel(self, mask):
        hits.append(str(mask.layout))
        return flag_gems.sparse_mask(self, mask)

    lib = torch.library.Library("aten", "IMPL")
    lib.impl("sparse_mask", sentinel, "SparseCUDA")

    dev = flag_gems.device
    d = torch.randn((3, 4), device=dev)
    mask = _make_coo_mask((3, 4), 3, torch.float32, seed=19)
    assert torch.ops.aten.sparse_mask(d, mask)._nnz() == 3
    assert d.sparse_mask(mask)._nnz() == 3
    assert torch.Tensor.sparse_mask(d, mask)._nnz() == 3
    assert len(hits) == 3
    assert set(hits) == {"torch.sparse_coo"}
    # The plain-CUDA key is NOT on the path (dense x dense natively raises
    # NotImplementedError from the CUDA backend before reaching us).


@pytest.mark.sparse_mask
def test_accuracy_sparse_mask_coexistence():
    # A sentinel on SparseCsrCUDA must NOT intercept COO-mask calls: the CSR
    # path stays native. Both keys must coexist without cross-routing.
    coo_hits = []

    def sentinel_coo(self, mask):
        coo_hits.append(str(mask.layout))
        return flag_gems.sparse_mask(self, mask)

