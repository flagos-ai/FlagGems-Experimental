def _bsc_components(size, block, nnz, seed, device, index_dtype=torch.int64):
    """Build (ccol_indices, row_indices, values) for a BSC tensor.

    BSC stores column blocks: ``ccol_indices[j] .. ccol_indices[j + 1]`` is the
    range of stored row-blocks of column-block ``j``, so the compressed index
    has one entry per column block plus the terminator. ``row_indices`` holds
    the row-block coordinate of each stored block, sorted within a column block
    so the structure is a legal BSC one.

    ``values`` follows the ATen block layout ``(nnz, block_rows, block_cols,
    dense...)``: the two block dimensions sit *before* any dense dimensions, so
    the trailing entries of ``size`` are appended after the block shape rather
    than before it (a 2-D ``size`` therefore has plain ``(nnz, br, bc)`` values).
    """
    block_rows, block_cols = block
    n_block_rows = max(1, size[0] // block_rows)
    n_block_cols = len(range(0, size[1] - block_cols + 1, block_cols))
    n_block_cols = max(1, n_block_cols)
    gen = torch.Generator(device="cpu").manual_seed(seed)

    # Distribute ``nnz`` blocks over the column blocks, at most one per
    # (row-block, column-block) cell, sorted by (column-block, row-block).
    total_cells = n_block_rows * n_block_cols
    nnz = min(nnz, total_cells)
    flat = torch.randperm(total_cells, generator=gen)[:nnz].sort().values
    rows = (flat % n_block_rows).to(torch.int64)
    cols = (flat // n_block_rows).to(torch.int64)
    counts = torch.bincount(cols, minlength=n_block_cols)
    ccol = torch.zeros(n_block_cols + 1, dtype=torch.int64)
    ccol[1:] = torch.cumsum(counts, dim=0)

    value_shape = (nnz,) + block + tuple(size[2:])
    values = torch.randn(value_shape, generator=gen)
    return (
        ccol.to(device).to(index_dtype),
        rows.to(device).to(index_dtype),
        values.to(device),
    )


