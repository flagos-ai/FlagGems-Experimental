def test__nnz_coexists_with_dense_dim():
    # Cross-op stability: repeated _nnz calls, interleaved with unrelated
    # dispatcher traffic, must keep returning the metadata count. dense_dim is
    # not part of this worktree's _FULL_CONFIG (separate branch), so it stays
    # native here and is only used as an interfering dispatcher-routed call.
    coo = _make_coo_plain(flag_gems.device)
    csr = _make_csr(flag_gems.device)
    csr_batched = _make_csr_batched(flag_gems.device)
    dense = torch.randn(3, 4, device=flag_gems.device)

    coo_nnz = utils.to_reference(coo)._nnz()
    csr_nnz = utils.to_reference(csr)._nnz()
    csr_batched_nnz = utils.to_reference(csr_batched)._nnz()

    for _ in range(3):
        assert flag_gems._nnz(coo) == coo_nnz
        assert torch.ops.aten._nnz(coo) == coo_nnz
        assert torch.ops.aten.dense_dim(coo) == 0
        assert flag_gems._nnz(csr) == csr_nnz
        assert torch.ops.aten._nnz(csr) == csr_nnz
        assert torch.ops.aten.dense_dim(csr) == 0
        assert flag_gems._nnz(csr_batched) == csr_batched_nnz
        assert torch.ops.aten._nnz(csr_batched) == csr_batched_nnz
        assert torch.ops.aten.dense_dim(dense) == 2
        with pytest.raises(NotImplementedError):
            flag_gems._nnz(dense)

    # Dispatching a related metadata op afterwards must not corrupt or re-route
    # _nnz (the implementation keeps no state between calls).
    assert torch.ops.aten.dense_dim(coo) == 0
    assert flag_gems._nnz(coo) == coo_nnz
    assert flag_gems._nnz(csr_batched) == csr_batched_nnz
