# rank, then the three operand shapes, then the output mask arity, then the
# dtypes. The wordings differ between the CPU and CUDA kernels, so every
# rejection is pinned by exception CLASS on the reference side and by a
# fragment invariant to the implementation's own documented wording (batch
# addendum A1: never pin one build's full sentence).
