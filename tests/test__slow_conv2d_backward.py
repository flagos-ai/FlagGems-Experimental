@pytest.mark._slow_conv2d_backward
@pytest.mark.parametrize("bad_rank", [3, 5])
def test_accuracy__slow_conv2d_backward_bad_operand_rank(bad_rank):
    """A wrong-rank grad_output or self is rejected. Native and the wrapper
    both raise RuntimeError mentioning "4D input"; only that invariant fragment
    is asserted (the reference also emits a different sentence for a wrong-rank
    grad_output)."""
    go, x, weight = _case_tensors(CONV2D_CASES[1], torch.float32)
    bad = torch.randn(
        [3, 4, 5, 6, 7][:bad_rank], dtype=torch.float32, device=flag_gems.device
    )
    for label, args in (
        ("grad_output", (bad, x, weight)),
        ("self", (go, bad, weight)),
    ):
        with pytest.raises(RuntimeError):
            ATEN_OP(
                utils.to_reference(args[0]),
                utils.to_reference(args[1]),
                utils.to_reference(args[2]),
                [3, 3],
                [1, 1],
                [1, 1],
                (True, True, True),
            )
        with pytest.raises(RuntimeError, match="4D input"):
            GEMS_OP(
                args[0], args[1], args[2], [3, 3], [1, 1], [1, 1], (True, True, True)
            )
        assert label


