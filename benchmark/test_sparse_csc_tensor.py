def _components(shape, dtype, device, index_dtype=torch.int64):
    """Build CSC components for ``shape`` = ``(nrows, ncols[, dense...])``.

    Roughly half of the (nrows, ncols) grid is stored, laid out column-major
    so ``ccol_indices`` is non-decreasing and ends at nnz.  Both sides receive
    the very same tensors, so the comparison is like for like.
    """
    nrows = max(int(shape[0]), 1)
    ncols = max(int(shape[1]), 1)
    dense = tuple(int(s) for s in shape[2:])
    grid = nrows * ncols
    nnz = max(1, grid // 2)
    gen = torch.Generator(device="cpu").manual_seed(42)
    flat = torch.randperm(grid, generator=gen)[:nnz].sort().values
    row = (flat % nrows).to(device).to(index_dtype)
    col = (flat // nrows).to(device).to(index_dtype)
    per_col = torch.bincount(col.long().cpu(), minlength=ncols)[:ncols]
    ccol = torch.zeros(ncols + 1, dtype=torch.int64)
    ccol[1:] = per_col.cumsum(0)
    order = torch.argsort(col.long() * nrows + row.long(), stable=True)
    values_shape = (nnz,) + dense
    if dtype == torch.bool:
        values = torch.ones(values_shape, device=device, dtype=dtype)
    else:
        values = utils.generate_tensor_input(values_shape, dtype, device)
    return ccol.to(device).to(index_dtype), row[order], values


