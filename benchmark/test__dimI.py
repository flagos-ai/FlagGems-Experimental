# Shape sweeps for the COO input. ``_dimI`` never reads index/value data, so
# the sparse dimension counts (and thus the O(1) host-side work) do not depend
# on the sizes; the sweep exists to vary the index-matrix shape metadata.
DIM_I_SHAPES = [(2, 3), (64, 128), (1024, 1024), (7, 4096)]


class DimIBenchmark(base.Benchmark):
    def set_shapes(self, shape_file_path=None):
        self.shapes = DIM_I_SHAPES

    def get_input_iter(self, cur_dtype):
        # Only sparse COO tensors are supported by aten::_dimI. Values follow
        # the benchmark dtype sweep, the indices stay int64. Yield a 1-tuple:
        # the harness unpacks each yielded item as an argument list, and
        # iterating a bare Tensor would pass its scalars instead.
        for shape in self.shapes:
            numel = shape[0] * shape[1]
            nnz = max(1, numel // 16)
            gen = torch.Generator().manual_seed(0)
            flat = torch.randperm(numel, generator=gen)[:nnz]
            indices = torch.empty((2, nnz), dtype=torch.int64)
            indices[0] = flat % shape[0]
            indices[1] = flat // shape[0]
            values = torch.randn(nnz, generator=gen).to(cur_dtype)
            inp = torch.sparse_coo_tensor(indices, values, shape).to(self.device)
            yield (inp,)


