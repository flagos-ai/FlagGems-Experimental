# (rows, cols, nnz, block_rows, block_cols) grids. The block shape is 1x1
# (CSR/CSC) or 2x2 (BSR/BSC); the fill ratio is ~50% of the block grid, capped
# so the largest case stays cheap to build.
BENCH_SHAPES = [(64, 64), (256, 256), (1024, 1024), (2048, 2048)]


def _gen_components(layout, shape, dtype, device, seed=42):
    """Valid components for one layout and a 2-D logical shape."""
    is_row = layout in (torch.sparse_csr, torch.sparse_bsr)
    is_block = layout in (torch.sparse_bsr, torch.sparse_bsc)
    br, bc = (2, 2) if is_block else (1, 1)
    n_compressed = max(1, (shape[0] if is_row else shape[1]) // br)
    n_plain = max(1, (shape[1] if is_row else shape[0]) // bc)
    total_cells = n_compressed * n_plain
    nnz = max(1, min(total_cells, total_cells // 2))

    gen = torch.Generator(device="cpu").manual_seed(seed)
    flat = torch.randperm(total_cells, generator=gen)[:nnz].sort().values
    compressed = (flat // n_plain).to(torch.int64)
    plain = (flat % n_plain).to(torch.int64)
    counts = torch.bincount(compressed, minlength=n_compressed)
    cptr = torch.zeros(n_compressed + 1, dtype=torch.int64)
    cptr[1:] = torch.cumsum(counts, dim=0)

    vshape = (nnz, br, bc) if is_block else (nnz,)
    # The values tensor is built with the harness dtype helper so the sweep
    # exercises the same input class as every other benchmark.
    values = base.generate_tensor_input(vshape, dtype, device)
    return (
        cptr.to(device),
        plain.to(device),
        values,
    )


