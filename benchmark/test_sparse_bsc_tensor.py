# Square block grids. The harness default shapes are 1-D and 3-D elementwise
# grids with no BSC reading: a BSC tensor is built from a 2-D block structure,
# and the 2**30-element defaults would ask for billions of block columns (an
# immediate OOM, measured on the sibling constructors). These four sizes span
# small to large while keeping the component build cheap; the block shape (2x2)
# and the 50% fill ratio are constant across the sweep.
BSC_SHAPES = [(64, 64), (256, 256), (1024, 1024), (2048, 2048)]

_BLOCK = 2


def _bsc_components(size, dtype, device, nnz_ratio=0.5):
    """Build valid BSC components (2x2 blocks) for a 2-D logical shape."""
    n_block_rows = max(1, size[0] // _BLOCK)
    n_block_cols = max(1, size[1] // _BLOCK)
    total_cells = n_block_rows * n_block_cols
    nnz = max(1, min(total_cells, int(total_cells * nnz_ratio)))

    gen = torch.Generator(device="cpu").manual_seed(42)
    flat = torch.randperm(total_cells, generator=gen)[:nnz].sort().values
    rows = (flat % n_block_rows).to(torch.int64)
    cols = (flat // n_block_rows).to(torch.int64)
    counts = torch.bincount(cols, minlength=n_block_cols)
    ccol = torch.zeros(n_block_cols + 1, dtype=torch.int64)
    ccol[1:] = torch.cumsum(counts, dim=0)

    values = torch.randn((nnz, _BLOCK, _BLOCK), generator=gen)
    return ccol.to(device), rows.to(device), values.to(device).to(dtype)


