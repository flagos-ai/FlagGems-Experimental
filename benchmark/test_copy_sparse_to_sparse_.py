def _make_sparse_coo(nnz, size, dtype, device, nnd=None):
    """A sparse COO tensor of ``size`` with ``nnz`` stored entries.

    ``nnd`` (the sparse-dimension count) defaults to ``len(size)``; a smaller
    value builds a hybrid tensor whose values carry trailing dense dimensions.
    """
    if nnd is None:
        nnd = len(size)
    numel = 1
    for s in size[:nnd]:
        numel *= s
    nnz = min(nnz, numel)
    if nnz == 0:
        return torch.sparse_coo_tensor(
            torch.zeros(nnd, 0, dtype=torch.int64, device=device),
            torch.zeros(0, dtype=dtype, device=device),
            size,
            device=device,
        )
    flat = torch.randperm(numel, device="cpu")[:nnz].sort().values
    indices = torch.empty((nnd, nnz), dtype=torch.int64)
    for d in reversed(range(nnd)):
        indices[d] = flat % size[d]
        flat = flat // size[d]
    dense = tuple(size[nnd:])
    values = generate_tensor_input((nnz,) + dense, dtype, device)
    return torch.sparse_coo_tensor(indices.to(device), values, size, device=device)


