def _bsr_components(shape, dtype, device, nnz_ratio=2):
    """Derive valid BSR components from a benchmark shape.

    ``shape`` is read as ``(n_block_rows, n_block_cols, block_rows,
    block_cols)``. Each block row stores up to ``nnz_ratio`` blocks, sorted so
    the tensor also satisfies the compressed-index invariants.
    """
    n_block_rows, n_block_cols, block_rows, block_cols = shape
    gen = torch.Generator(device="cpu").manual_seed(42)
    crow = [0]
    col = []
    nnz = 0
    for _ in range(n_block_rows):
        k = min(n_block_cols, nnz_ratio)
        picks = torch.randperm(n_block_cols, generator=gen)[:k].sort().values
        col.extend(int(v) for v in picks)
        nnz += k
        crow.append(nnz)
    crow_indices = torch.tensor(crow, dtype=torch.int64, device=device)
    col_indices = torch.tensor(col, dtype=torch.int64, device=device)
    values_shape = (nnz, block_rows, block_cols)
    if dtype in consts.FLOAT_DTYPES or dtype in consts.COMPLEX_DTYPES:
        values = torch.randn(values_shape, dtype=dtype, device=device)
    else:
        values = torch.randint(0, 2, values_shape, dtype=dtype, device="cpu").to(device)
    size = [n_block_rows * block_rows, n_block_cols * block_cols]
    return crow_indices, col_indices, values, size


