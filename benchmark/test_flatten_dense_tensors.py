# aten::flatten_dense_tensors takes a LIST of dense tensors, so the harness's
# default shapes (up to 2**30 elements per tensor) would mean hundreds of GiB
# of inputs for a realistic list length. The list length is fixed at 4 and the
# harness's `shapes` field carries the elements' flat TOTAL element counts,
# which is also what lands in the reported shape detail.
#
# The three implementation branches are covered:
#   - 2**10 / 2**16 totals -> _flatten_n4 maskless (equal, chunk-aligned elems)
#   - 2**20 - 3 total      -> _flatten_n4 MASKED=True (chunk-crossing tail)
#   - 64*512*512 total     -> large per-chunk counts, masked tail
# (1024**3,) is dropped for the memory reason above.
FE_T_SHAPES = [(2**10,), (2**16,), (2**20 - 3,), (64, 512, 512)]


