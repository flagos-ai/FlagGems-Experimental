def _make_sparse_coo(nnz, size, dtype, device, nnd=None):
    """A coalesced sparse COO tensor of ``size`` with ``nnz`` stored entries.

    ``nnd`` (the sparse-dimension count) defaults to ``len(size)``; a smaller
    value builds a hybrid tensor whose values carry trailing dense dimensions.
    """
    if nnd is None:
        nnd = len(size)
    numel = 1
    for s in size[:nnd]:
        numel *= s
    nnz = min(nnz, numel)
    flat = torch.randperm(numel, device="cpu")[:nnz].sort().values
    indices = torch.empty((nnd, nnz), dtype=torch.int64)
    for d in reversed(range(nnd)):
        indices[d] = flat % size[d]
        flat = flat // size[d]
    dense = tuple(size[nnd:])
    dnum = 1
    for s in dense:
        dnum *= s
    values = (
        torch.arange(nnz * dnum, dtype=torch.float32)
        .reshape((nnz,) + dense)
        .to(dtype)
        .to(device)
    )
    return torch.sparse_coo_tensor(indices.to(device), values, size)


