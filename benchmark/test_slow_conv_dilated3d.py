# 3-D conv is memory-hungry: the input is 5-D and the contraction is
# C_in * kD * kH * kW. These shapes stay small enough to run comfortably while
# covering each `_pick` tuning family of the implementation:
#
#   (a) per-N spatial output < 1024        -> BC=16, BP=16
#   (b) KVOL3 == 1 (1x1x1 channel GEMM)    -> BC=16, BP=128
#   (c) COUT <= 16 with a large spatial map-> BC=16, BP=128
#   (d) COUT <= 32 and K >= 800            -> BC=16, BP=64
#   (e) COUT <= 32 and K <  800            -> BC=32, BP=32
#   (f) COUT >= 64 and K >= 1024           -> BC=32, BP=64
#   (g) COUT >= 64 and K <  1024           -> BC=32, BP=32
#
# layout of a shape tuple:
#   (N, C_in, D, H, W, C_out, kD, kH, kW, stride, padding, dilation)
