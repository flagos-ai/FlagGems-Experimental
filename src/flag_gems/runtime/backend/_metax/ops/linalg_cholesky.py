# In-register Cholesky of a (TILE, TILE) symmetric positive definite tile S.
# Right-looking rank-1 form: at step k, column k of S is factored, then the
# trailing submatrix is updated with the masked outer product v v^T.  The
# full-tile outer subtraction is safe because cells of row/column k at or
# above the diagonal are never read again.  Only one full-tile reduction per
# column is required (extracting column k).
@triton.jit
def _chol_tile(S, TILE: tl.constexpr):
    cols = tl.arange(0, TILE)
    L = tl.zeros((TILE, TILE), dtype=S.dtype)
    for k in tl.static_range(TILE):
        colS = tl.sum(tl.where(cols[None, :] == k, S, 0.0), axis=1)  # S[:, k]
        d = tl.sum(tl.where(cols == k, colS, 0.0))
        lkk = tl.sqrt(d)
        v = tl.where(cols[None, :] >= k, colS[:, None] / lkk, 0.0)  # column k of L
        L = tl.where(cols[None, :] == k, v, L)
        S = S - v * tl.trans(v)
    return L


