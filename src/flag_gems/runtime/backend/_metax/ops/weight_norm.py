def weight_norm_interface(v, g, dim=0):
    logger.debug("GEMS METAX WEIGHT NORM INTERFACE FORWARD")
    v = v.contiguous()
    g = g.contiguous()
    output = torch.empty_like(v)
    if dim == 0:
        M = v.shape[0]
        N = math.prod(v.shape[1:])
        norm = torch.empty_like(g, dtype=torch.float32)
        grid = lambda META: (triton.cdiv(M, META["BLOCK_ROW_SIZE"]),)
        with torch_device_fn.device(v.device):
            weight_norm_kernel_first[grid](
                output, norm, v, g, M, N, eps=torch.finfo(torch.float32).tiny
            )
        return output, norm
    elif dim == v.ndim - 1:
        M = math.prod(v.shape[:-1])
        N = v.shape[dim]
        # For small reductions the two-pass + atomic scheme costs more in
        # launch/atomic overhead than it gains in parallelism, so fall back to
        # the generic single-kernel implementation.
        if M <= _WN_LAST_FALLBACK_M:
            norm = torch.empty_like(g, dtype=torch.float32)
            grid = lambda META: (triton.cdiv(N, META["BLOCK_COL_SIZE"]),)
            with torch_device_fn.device(v.device):
                weight_norm_kernel_last[grid](
                    output, norm, v, g, M, N, eps=torch.finfo(torch.float32).tiny
                )
            return output, norm
        # Pass 1: zero-init norm then atomic-accumulate per-column sum of
        # squares. ``reset_to_zero=["norm"]`` in the autotuner keeps the
        # per-config benchmark runs from double-accumulating.
        norm = torch.zeros_like(g, dtype=torch.float32)
        grid = lambda META: (
            triton.cdiv(M, META["BLOCK_M"]),
            triton.cdiv(N, META["BLOCK_N"]),
        )
        with torch_device_fn.device(v.device):
            _wn_last_partial_sqsum_kernel[grid](norm, v, M, N)
            # sqrt in-place to turn sum-of-squares into the norm (matches the
            # generic kernel which stores sqrt(sum + eps)). The atomic pass
            # already accumulated the plain sum (no eps); add eps here so the
            # final value equals sqrt(sum + tiny), identical to generic output.
            norm.add_(torch.finfo(torch.float32).tiny)
            norm.sqrt_()
            _wn_last_normalize_kernel[grid](output, v, g, norm, M, N)
        return output, norm
    else:  # pragma: no cover - interface is only called for dim in {0, last}
        raise RuntimeError("weight_norm_interface only supports dim 0 or last")


def weight_norm_interface_backward(w_grad, saved_v, saved_g, saved_norms, dim):
    logger.debug("GEMS METAX WEIGHT NORM INTERFACE BACKWARD")
    w_grad = w_grad.contiguous()
    saved_v = saved_v.contiguous()
    saved_g = saved_g.contiguous()
    saved_norms = saved_norms.contiguous()
    v_grad = torch.empty_like(saved_v)
    g_grad = torch.empty_like(saved_g)

    if dim == 0:
        M = saved_v.shape[0]
        N = math.prod(saved_v.shape[1:])
        grid = lambda META: (triton.cdiv(M, META["BLOCK_ROW_SIZE"]),)
        with torch_device_fn.device(saved_v.device):
            weight_norm_bwd_kernel_first[grid](
                v_grad,
                g_grad,
                w_grad,
                saved_v,
                saved_g,
                saved_norms,
                M,
                N,
                eps=torch.finfo(torch.float32).tiny,
            )
        return v_grad, g_grad
    elif dim == saved_v.ndim - 1:
        M = math.prod(saved_v.shape[:dim])
        N = saved_v.shape[dim]
        # Small-reduction fallback to the generic single-kernel backward.
        if M <= _WN_LAST_FALLBACK_M:
            grid = lambda META: (triton.cdiv(N, META["BLOCK_COL_SIZE"]),)
            with torch_device_fn.device(saved_v.device):
                weight_norm_bwd_kernel_last[grid](
                    v_grad,
                    g_grad,
                    w_grad,
                    saved_v,
                    saved_g,
                    saved_norms,
                    M,
                    N,
                    eps=torch.finfo(torch.float32).tiny,
                )
            return v_grad, g_grad
        vw_sum = torch.zeros_like(saved_g, dtype=torch.float32)
        grid = lambda META: (
            triton.cdiv(M, META["BLOCK_M"]),
            triton.cdiv(N, META["BLOCK_N"]),
        )
