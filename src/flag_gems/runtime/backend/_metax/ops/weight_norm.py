_WN_LAST_FALLBACK_M = 1024


# ---------------------------------------------------------------------------
# dim == -1 path: two-pass grid-tiled reduction.
#   M = prod(shape[:-1])  (the reduction axis)
#   N = shape[-1]
#
# Pass 1 (wn_last_partial_sqsum): each program owns a [BLOCK_M, BLOCK_N] tile
#   and atomically accumulates its per-column partial sum of squares into
#   ``norm`` (zero-initialized). Grid is (cdiv(M, BLOCK_M), cdiv(N, BLOCK_N)),
#   i.e. full GPU utilization even for large M / small N.
# Pass 2 (wn_last_normalize): each program re-loads its [BLOCK_M, BLOCK_N] tile
#   and writes ``v * g / norm`` (norm now holding the full sqrt(sum)).
# ---------------------------------------------------------------------------


@libentry()
@triton.autotune(
    configs=runtime.get_tuned_config("weight_norm_last_sqsum"),
    key=["M", "N"],
    reset_to_zero=["norm"],
)
@triton.jit
def _wn_last_partial_sqsum_kernel(
    norm,
    v,
    M,
    N,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    pid_m = ext.program_id(axis=0)
    pid_n = ext.program_id(axis=1)
    offs_m = pid_m * BLOCK_M + tl.arange(0, BLOCK_M)[:, None]
    offs_n_1d = pid_n * BLOCK_N + tl.arange(0, BLOCK_N)
    offs_n = offs_n_1d[None, :]
    mask = (offs_m < M) & (offs_n < N)
    # v is row-major (M, N): v[m, n] at m*N + n
    vv = tl.load(v + offs_m * N + offs_n, mask=mask, other=0.0).to(tl.float32)
    partial = tl.sum(vv * vv, axis=0)  # (BLOCK_N,)
    col_mask = offs_n_1d < N
    tl.atomic_add(norm + offs_n_1d, partial, mask=col_mask)


