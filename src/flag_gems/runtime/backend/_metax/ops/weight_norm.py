# Metax backend specialization of the weight_norm *interface* kernels
# (``weight_norm_kernel_first`` / ``weight_norm_kernel_last`` and their backward
# counterparts in ``flag_gems.ops.weightnorm``).
#
# Why specialize on Metax:
#   * The generic ``weight_norm_kernel_last`` (dim == -1, reduction over the
#     leading ``M = prod(shape[:-1])``) launches only ``cdiv(N, BLOCK_COL_SIZE)``
#     programs, each of which serially walks the *entire* ``M`` reduction axis.
#     When ``M`` is large and ``N`` is small (e.g. ``(64, 512, 512)`` dim=-1,
#     ``M = 32768, N = 512``), the program count drops to ~16 and the kernel
#     becomes heavily under-parallelized -- measured ~3x slower than torch.
#   * The generic backward uses ``tl_extra_shim.pow(norm_1, 3)`` (a libdevice
#     call) where plain multiplications suffice.
#
# The Metax specialization keeps the *dim == 0* path identical to the generic
# implementation (it is already fast: 1.1x-4.0x over torch) and replaces only
# the *dim == -1* path with a two-pass, grid-tiled reduction that exposes far
# more parallelism and replaces ``pow`` with multiplications.
#
# Following the metax specialization pattern (see PR #209,
# ``adaptive_max_pool3d_backward``): per-kernel autotune configs live in
# ``tune_configs.yaml`` (entries ``weight_norm_last_*``) and the accumulation
# passes carry ``reset_to_zero`` on their target buffer, so the autotuner's
# per-config benchmark runs do not double-accumulate into the real output.
#
# Only the op implementation is touched; no test / benchmark file is modified.
