@triton.jit
def _binary_gcd(ax, ay, normal, MAX_ITERS: tl.constexpr):
    """Binary GCD (Stein's algorithm).

    Both operands are pre-stripped of trailing zeros before entering
    the loop.  MAX_ITERS = 2 * (bit_width - 1) is the worst case
    for the given dtype.
    """
    zero_ax = ax == 0
    zero_ay = ay == 0
    gcd_zero = tl.where(zero_ax, ay, ax)
    both_nz = normal & (~zero_ax) & (~zero_ay)

    common = _ctz(tl.where(both_nz, ax | ay, 1))
    u = tl.where(
        both_nz,
        ax >> _ctz(tl.where(both_nz, ax, 1)),
        ax,
    )
    # Pre-strip v: saves one ctz call inside the loop.
    v = tl.where(
        both_nz,
        ay >> _ctz(tl.where(both_nz, ay, 1)),
        ay,
    )
    active = both_nz

    for _ in tl.static_range(MAX_ITERS):
        # After first iteration v is always even (odd - odd),
        # so _ctz(v) >= 1 and never called on zero.
        v_s = tl.where(active, v, 1)
        v_shifted = tl.where(active, v_s >> _ctz(v_s), v)
        swap = active & (u > v_shifted)
        small = tl.where(swap, v_shifted, u)
        large = tl.where(swap, u, v_shifted)
        u = tl.where(active, small, u)
        v = tl.where(active, large - small, v)
        active = active & (v != 0)

    return tl.where(both_nz, u << common, gcd_zero)


