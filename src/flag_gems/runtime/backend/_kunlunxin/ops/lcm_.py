_MAXD = 8
_STEP = 8


def _nloop_for(bits):
    # total guarded Euclid steps = nloop * _STEP, with exact Lamé worst case
    # |values| < 2^15 -> <= 22 ; |values| <= 2^31 -> <= 45, rounded to _STEP.
    if bits <= 16:
        return 3  # 24 steps >= 22
    if bits <= 32:
        return 6  # 48 steps >= 45
    return 12  # 96 steps, conservative int64 bound


def _broadcast_strides(self, other, nd):
    diff = nd - other.dim()
    ystrides = []
    for d in range(nd):
        od = d - diff
        if od < 0:
            ystrides.append(0)
        else:
            osz = other.shape[od]
            if osz == 1:
                ystrides.append(0)
            else:
                ystrides.append(other.stride(od))
    pad = _MAXD - nd
    rsz = tuple(reversed(self.shape)) + (1,) * pad
    rxs = tuple(reversed(self.stride())) + (0,) * pad
    rys = tuple(reversed(ystrides)) + (0,) * pad
    return rsz, rxs, rys


def lcm_(self, other):
    with torch_device_fn.device(
        (self if isinstance(self, torch.Tensor) else other).device
    ):
        n = self.numel()
        if n == 0:
            return self

        bits = self.dtype.itemsize * 8
        nloop = _nloop_for(bits)
        block = 1024
        grid = (triton.cdiv(n, block),)
        contig = (
            self.shape == other.shape and self.is_contiguous() and other.is_contiguous()
        )

        if bits <= 32:
            is_signed = self.dtype.is_signed
            if contig:
                _lcm32_contig_kernel[grid](
                    self,
                    other,
                    n,
                    nloop,
                    W=bits,
                    IS_SIGNED=is_signed,
                    STEPC=_STEP,
                    BLOCK=block,
                )
                return self
            nd = self.dim()
            rsz, rxs, rys = _broadcast_strides(self, other, nd)
            _lcm32_strided_kernel[grid](
                self,
                other,
                n,
                nloop,
                *(rsz + rxs + rys),
                W=bits,
                IS_SIGNED=is_signed,
                STEPC=_STEP,
                BLOCK=block,
            )
            return self

        # int64 path
        if contig:
            _lcm64_contig_kernel[grid](self, other, n, nloop, STEPC=_STEP, BLOCK=block)
            return self
        nd = self.dim()
        rsz, rxs, rys = _broadcast_strides(self, other, nd)
        _lcm64_strided_kernel[grid](
            self,
            other,
            n,
            nloop,
            *(rsz + rxs + rys),
            STEPC=_STEP,
            BLOCK=block,
        )
        return self
