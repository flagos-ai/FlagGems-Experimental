# ---------------------------------------------------------------------------
# lcm_(self, other): elementwise least-common-multiple written back into self.
#
# Reference semantics (torch, verified on target for int8..int64):
#   g = gcd(|a|, |b|);  out = (|a| / g) * |b|   computed in the native width
#   with wrapping; torch additionally applies abs() to the wrapped value for
#   the 32/64-bit signed dtypes (16/8-bit signed truncate the promoted
#   product without abs).
#
# Target caveats (Kunlunxin XPU backend):
#   * 32-bit-carried dynamic Euclid loops crash the backend code generator,
#     so the Euclid step loop is carried in int64 (magnitudes <= 2^31 fit).
#   * Integer '/' is lowered through fp32 (broken above ~2^24) but fp64
#     division is exact here (quotient <= 2^31 < 2^53), so the single exact
#     quotient is computed in fp64.  Verified byte-exact vs CPU torch on
#     full-range + INT_MIN + Fibonacci adversarial int32/int16 arrays.
#   * Each Euclid step costs ~0.8 ms over a full 4096x4096 array, dominated
#     by scf.for pass overhead, so STEP guarded steps are unrolled inside one
#     loop pass (STEP=8); output is provably identical to single-step.
# ---------------------------------------------------------------------------

# ---------------------------------------------------------------------------
# _STEP is passed into every kernel as the constexpr parameter STEPC (a bare
# module global cannot be referenced from a @triton.jit function).
# ---------------------------------------------------------------------------


@triton.jit
def _lcm32_contig_kernel(
    x_ptr,
    y_ptr,
    numel,
    nloop,
    W: tl.constexpr,
    IS_SIGNED: tl.constexpr,
    STEPC: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    m = offs < numel
    a = tl.load(x_ptr + offs, mask=m).to(tl.int64)
    b = tl.load(y_ptr + offs, mask=m).to(tl.int64)
    if IS_SIGNED:
        a = tl.where(a < 0, -a, a)
        b = tl.where(b < 0, -b, b)
    g = a
    r = b
    for _ in range(0, nloop):
        for _ in tl.static_range(STEPC):
            safe = tl.where(r == 0, 1, r)
            ng = tl.where(r != 0, r, g)
            nr = tl.where(r != 0, g % safe, 0)
            g = ng
            r = nr
    safe_g = tl.where(g == 0, 1, g)
    q = (a.to(tl.float64) / safe_g.to(tl.float64)).to(tl.int64)
    if W == 32:
        qi = q.to(tl.int32)
        bi = b.to(tl.int32)
        v = qi * bi
        if IS_SIGNED:
            v = tl.where(v < 0, -v, v)
        tl.store(x_ptr + offs, v.to(x_ptr.dtype.element_ty), mask=m)
    else:
        v = q * b
        tl.store(x_ptr + offs, v.to(x_ptr.dtype.element_ty), mask=m)


