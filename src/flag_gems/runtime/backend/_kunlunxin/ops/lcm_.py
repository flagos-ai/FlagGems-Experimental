@triton.jit
def _div_i64(n, d):
    q = tl.zeros_like(n)
    rem = tl.zeros_like(n)
    for k in tl.static_range(64):
        b = 63 - k
        bit = (n >> b) & 1
        rem = (rem << 1) | bit
        ge = rem >= d
        rem = tl.where(ge, rem - d, rem)
        q = q | (ge.to(tl.int64) << b)
    q = tl.where(d >= 4611686018427387904, (n >= d).to(tl.int64), q)
    return q


