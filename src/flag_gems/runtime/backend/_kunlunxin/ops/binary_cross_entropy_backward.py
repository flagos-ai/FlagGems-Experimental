import torch
import triton
import triton.language as tl

# Generated by KernelGen: https://github.com/flagos-ai/KernelGen
from flag_gems.runtime import torch_device_fn


@triton.jit
def _bce_bwd_unmasked(
    go_ptr,
    self_ptr,
    target_ptr,
    weight_ptr,
    out_ptr,
    scale,
    HAS_W: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(axis=0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    g = tl.load(go_ptr + offs).to(tl.float32)
    x = tl.load(self_ptr + offs).to(tl.float32)
    t = tl.load(target_ptr + offs).to(tl.float32)
    if HAS_W:
        w = tl.load(weight_ptr + offs).to(tl.float32)
        num = w * (x - t)
    else:
        num = x - t
    den = x * (1.0 - x)
    # aten reference keeps finite results for x==1 / x==0 clamp-boundary
    # inputs (fp16/bf16 round 1-1e-4 up to exactly 1.0); floor den to
    # reproduce it instead of emitting NaN / Inf.
    den = tl.maximum(den, 1.0e-12)
    res = g * num / den * scale
    tl.store(out_ptr + offs, res)


@triton.jit
def _bce_bwd_masked(
    go_ptr,
    self_ptr,
    target_ptr,
    weight_ptr,
    out_ptr,
    n_elements,
    scale,
    HAS_W: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(axis=0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n_elements
    g = tl.load(go_ptr + offs, mask=mask, other=0.0).to(tl.float32)
    x = tl.load(self_ptr + offs, mask=mask, other=0.0).to(tl.float32)
    t = tl.load(target_ptr + offs, mask=mask, other=0.0).to(tl.float32)
    if HAS_W:
        w = tl.load(weight_ptr + offs, mask=mask, other=0.0).to(tl.float32)
        num = w * (x - t)
    else:
        num = x - t
    den = x * (1.0 - x)
    den = tl.maximum(den, 1.0e-12)
    res = g * num / den * scale
    tl.store(out_ptr + offs, res, mask=mask)


def _norm_reduction(reduction):
    if isinstance(reduction, str):
        r = reduction
    else:
        r = {0: "none", 1: "mean", 2: "sum"}.get(int(reduction), "mean")
    if r not in ("none", "mean", "sum"):
        r = "mean"
    return r


def _pick_block(n, is_fp16):
    # Measured on the target: unmasked blocks producing 8-512 CTAs beat
    # both tiny grids (<8 CTAs, e.g. 32768-wide at n=131072 -> 4 CTAs)
    # and 1000+ CTA launches. fp16 favours BLOCK=16384 on the ~131K and
    # ~8.4M workloads; fp32 favours 8192 up to ~2M and 32768 beyond.
    if is_fp16:
        for blk, nw in ((16384, 8), (32768, 16), (8192, 8)):
            if n >= blk and n % blk == 0:
                return blk, nw
    else:
        if 8192 <= n <= 2097152 and n % 8192 == 0:
            return 8192, 8
        for blk, nw in ((32768, 16), (16384, 8), (8192, 8)):
            if n >= blk and n % blk == 0:
                return blk, nw
    return None


def binary_cross_entropy_backward(grad_output, self, target, weight=None, reduction=1):
    with torch_device_fn.device(grad_output.device):
        red = _norm_reduction(reduction)

        self_t = self if self.is_contiguous() else self.contiguous()
        targ = target if target.is_contiguous() else target.contiguous()
        go = grad_output.expand(self.shape).contiguous()

        out = torch.empty_like(self_t)
        n = self_t.numel()
        if n == 0:
            return out

        scale = (1.0 / n) if red == "mean" else 1.0
        has_w = weight is not None and torch.is_tensor(weight)

        x = self_t.view(-1)
        y = targ.view(-1)
        ov = out.view(-1)
        gv = go.view(-1)

        wv = None
        if has_w:
            wv = weight.expand(self.shape).contiguous().view(-1)
        wptr = wv if wv is not None else gv

        # Wide unmasked blocks keep the CTA count moderate on this target;
        # masked tail/small cases use BLOCK=512 (masked fp32 stores at
        # BLOCK=1024/2048 are miscompiled by the flagtree backend).
        chosen = _pick_block(n, self_t.dtype in (torch.float16, torch.bfloat16))
        if chosen is not None:
            blk, nw = chosen
            _bce_bwd_unmasked[(n // blk,)](
                gv, x, y, wptr, ov, scale, HAS_W=has_w, BLOCK=blk, num_warps=nw
            )
        else:
            _bce_bwd_masked[(triton.cdiv(n, 512),)](
                gv, x, y, wptr, ov, n, scale, HAS_W=has_w, BLOCK=512, num_warps=4
            )
        return out
