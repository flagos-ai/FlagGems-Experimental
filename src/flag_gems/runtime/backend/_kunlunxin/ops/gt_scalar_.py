# ---------------------------------------------------------------------------
# In-place greater-than-scalar: A.gt_(B) semantics
#   out = A > B computed in torch's promoted dtype, then cast back to A's
#   dtype (bool stays bool, numerics become 0/1) and written into A.
#   gt_scalar_(A, B) mutates A in place and returns the mutated A.
#
# Performance notes (P800/flagtree):
#  * A per-program scalar pointer load of B is very expensive in codegen, so
#    large contiguous workloads pass B's value as a plain scalar kernel
#    argument (one .item() per call); small workloads use a pointer-load
#    kernel to avoid the device->host sync round trip.
#  * Wide BLOCKs (8k/16k elements/program) give the compiler large
#    per-thread vector bursts.
# ---------------------------------------------------------------------------

_TORCH_TO_TL = {
    torch.float16: tl.float16,
    torch.bfloat16: tl.bfloat16,
    torch.float32: tl.float32,
    torch.float64: tl.float64,
    torch.int8: tl.int8,
    torch.int16: tl.int16,
    torch.int32: tl.int32,
    torch.int64: tl.int64,
    torch.uint8: tl.uint8,
    torch.bool: tl.int1,
}

_SMALL_BPTR_LIMIT = 1 << 19  # elements below this use the no-.item() kernel


# ----------------------------- fast numeric kernels -------------------------


@triton.jit
def _gt_num_flat_bptr(
    a_ptr,
    b_ptr,
    n,
    CT: tl.constexpr,
    DT: tl.constexpr,
    FP_MAT: tl.constexpr,
    EVEN: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    bv = tl.load(b_ptr)
    if EVEN:
        av = tl.load(a_ptr + offs)
    else:
        m = offs < n
        av = tl.load(a_ptr + offs, mask=m)
    gt = bv.to(CT) < av.to(CT)  # NaN-safe av > bv
    if FP_MAT:
        v = tl.where(gt, 1.0, 0.0)
    else:
        v = tl.where(gt, 1, 0).to(DT)
    if EVEN:
        tl.store(a_ptr + offs, v)
    else:
        tl.store(a_ptr + offs, v, mask=m)


