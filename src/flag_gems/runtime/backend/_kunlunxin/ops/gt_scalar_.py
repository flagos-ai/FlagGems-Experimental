# --------------------------- generic fallback kernels -----------------------


@triton.jit
def _gt_flat_kernel(
    a_ptr,
    b_ptr,
    n,
    CT: tl.constexpr,
    DT: tl.constexpr,
    A_BOOL: tl.constexpr,
    B_BOOL: tl.constexpr,
    OUT_BOOL: tl.constexpr,
    ELEM_B: tl.constexpr,
    EVEN: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)

    if ELEM_B:
        if EVEN:
            av = tl.load(a_ptr + offs)
            bv = tl.load(b_ptr + offs)
        else:
            m = offs < n
            av = tl.load(a_ptr + offs, mask=m)
            bv = tl.load(b_ptr + offs, mask=m)
    else:
        bv = tl.load(b_ptr)
        if EVEN:
            av = tl.load(a_ptr + offs)
        else:
            m = offs < n
            av = tl.load(a_ptr + offs, mask=m)

    if A_BOOL:
        avc = tl.where(av, 1, 0).to(CT)
    else:
        avc = av.to(CT)

    if B_BOOL:
        bvc = tl.where(bv, 1, 0).to(CT)
    else:
        bvc = bv.to(CT)

    c = avc > bvc

    if OUT_BOOL:
        if ELEM_B:
            if EVEN:
                tl.store(a_ptr + offs, c)
            else:
                tl.store(a_ptr + offs, c, mask=m)
        else:
            if EVEN:
                tl.store(a_ptr + offs, c)
            else:
                tl.store(a_ptr + offs, c, mask=m)
    else:
        val = tl.where(c, 1, 0).to(DT)
        if ELEM_B:
            if EVEN:
                tl.store(a_ptr + offs, val)
            else:
                tl.store(a_ptr + offs, val, mask=m)
        else:
            if EVEN:
                tl.store(a_ptr + offs, val)
            else:
                tl.store(a_ptr + offs, val, mask=m)


@triton.jit
def _gt_strided_kernel(
    a_ptr,
    b_ptr,
    n,
    s0,
    s1,
    s2,
    s3,
    s4,
    s5,
    s6,
    s7,
    t0,
    t1,
    t2,
    t3,
    t4,
    t5,
    t6,
    t7,
    RANK: tl.constexpr,
    CT: tl.constexpr,
    DT: tl.constexpr,
    A_BOOL: tl.constexpr,
    B_BOOL: tl.constexpr,
    OUT_BOOL: tl.constexpr,
    ELEM_B: tl.constexpr,
    EVEN: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    base = pid * BLOCK + tl.arange(0, BLOCK)
    q = base.to(tl.int64)
    off = tl.zeros([BLOCK], dtype=tl.int64)
    shapes = (s0, s1, s2, s3, s4, s5, s6, s7)
    strides = (t0, t1, t2, t3, t4, t5, t6, t7)
    for d in tl.static_range(RANK - 1, -1, -1):
        cdim = q % shapes[d]
        off += cdim * strides[d]
        q = q // shapes[d]

    if ELEM_B:
        if EVEN:
            av = tl.load(a_ptr + off)
            bv = tl.load(b_ptr + base.to(tl.int64))
        else:
            m = base < n
            av = tl.load(a_ptr + off, mask=m)
            bv = tl.load(b_ptr + base.to(tl.int64), mask=m)
    else:
        bv = tl.load(b_ptr)
        if EVEN:
            av = tl.load(a_ptr + off)
        else:
            m = base < n
            av = tl.load(a_ptr + off, mask=m)

    if A_BOOL:
        avc = tl.where(av, 1, 0).to(CT)
    else:
        avc = av.to(CT)

    if B_BOOL:
        bvc = tl.where(bv, 1, 0).to(CT)
    else:
        bvc = bv.to(CT)

    c = avc > bvc

    if OUT_BOOL:
        if EVEN:
            tl.store(a_ptr + off, c)
        else:
            tl.store(a_ptr + off, c, mask=m)
    else:
        val = tl.where(c, 1, 0).to(DT)
        if EVEN:
            tl.store(a_ptr + off, val)
        else:
            tl.store(a_ptr + off, val, mask=m)


# -------------------------------- host --------------------------------------


def _num_warps_for(BLOCK):
    if BLOCK <= 64:
        return 1
    if BLOCK <= 256:
        return 2
    return 4


def gt_scalar_(A, B):
    with torch_device_fn.device(A.device):
        n = A.numel()
        if n == 0:
            return A

        if isinstance(B, torch.Tensor):
            py_scalar = False
            b_t = B
            if b_t.device != A.device:
                b_t = b_t.to(A.device)
            scalar_b = b_t.numel() == 1
            if scalar_b and b_t.dim() != 0:
                b_t = b_t.reshape(())
        else:
            py_scalar = True
            b_t = None
            scalar_b = True

        a_num = A.dtype in (torch.float16, torch.bfloat16, torch.float32)

        # ---- fast path: contiguous numeric A, single-element scalar B ----------
        use_fast = A.is_contiguous() and a_num
        if use_fast:
            if py_scalar:
                use_fast = isinstance(B, float)  # python float scalar B
            else:
                use_fast = scalar_b
        if use_fast:
            if py_scalar:
                ct_dt = torch.promote_types(A.dtype, torch.float32)
                b_val = float(B)
            else:
                if A.dtype == b_t.dtype:
                    ct_dt = A.dtype
                else:
                    ct_dt = torch.result_type(A, b_t)
            if ct_dt in (torch.float16, torch.bfloat16, torch.float32):
                ct_tl = _TORCH_TO_TL[ct_dt]
                dt_tl = _TORCH_TO_TL[A.dtype]
                fp_mat = A.dtype != torch.bfloat16

                if (not py_scalar) and n <= _SMALL_BPTR_LIMIT:
                    # Avoid .item() sync: load scalar from the (0-dim) B pointer.
                    BLOCK = triton.next_power_of_2(min(max(n, 1), 4096))
                    EVEN = n % BLOCK == 0
                    grid = (triton.cdiv(n, BLOCK),)
                    num_warps = _num_warps_for(BLOCK)
                    _gt_num_flat_bptr[grid](
                        A,
                        b_t,
                        n,
                        CT=ct_tl,
                        DT=dt_tl,
                        FP_MAT=fp_mat,
                        EVEN=EVEN,
                        BLOCK=BLOCK,
                        num_warps=num_warps,
                    )
                else:
                    if not py_scalar:
                        b_val = b_t.item()
                        if isinstance(b_val, float):
                            b_val = float(b_val)
                        else:
                            b_val = int(b_val)
                    BLOCK = 8192 if A.dtype == torch.float32 else 16384
                    if n < BLOCK:
                        BLOCK = triton.next_power_of_2(max(n, 1))
                    EVEN = n % BLOCK == 0
                    grid = (triton.cdiv(n, BLOCK),)
                    _gt_num_flat_sarg[grid](
                        A,
                        b_val,
                        n,
                        CT=ct_tl,
                        DT=dt_tl,
                        FP_MAT=fp_mat,
                        EVEN=EVEN,
                        BLOCK=BLOCK,
                        num_warps=4,
                    )
                return A

        # ---- generic path (bool/int dtypes, equal-shape B, python scalar,
        #      non-contiguous layouts, fp64/mixed promotions) --------------------
        if b_t is None:
            b_t = torch.tensor(B, device=A.device)
        ct_dt = torch.result_type(A, b_t)
        if ct_dt == torch.bool:
            ct_tl = tl.int32  # compare bool operands as 0/1 integers
        else:
            ct_tl = _TORCH_TO_TL[ct_dt]

        out_bool = A.dtype == torch.bool
        if not out_bool:
            dt_tl = _TORCH_TO_TL[A.dtype]
        else:
            dt_tl = tl.int1

        a_bool = A.dtype == torch.bool
        b_bool = b_t.dtype == torch.bool

        elem_b = (not isinstance(B, torch.Tensor)) or (b_t.numel() == n)
        if elem_b and b_t.numel() == 1:
            elem_b = False  # numel == 1 is the scalar case

        if A.is_contiguous():
            BLOCK = triton.next_power_of_2(min(max(n, 1), 1024))
            EVEN = n % BLOCK == 0
            grid = (triton.cdiv(n, BLOCK),)
            num_warps = _num_warps_for(BLOCK)
            _gt_flat_kernel[grid](
                A,
                b_t,
                n,
                CT=ct_tl,
                DT=dt_tl,
                A_BOOL=a_bool,
                B_BOOL=b_bool,
                OUT_BOOL=out_bool,
                ELEM_B=elem_b,
                EVEN=EVEN,
                BLOCK=BLOCK,
                num_warps=num_warps,
            )
        else:
            rank = A.dim()
            if rank == 0:
                A = A.reshape(1)
                rank = 1
            if rank > 8:
                raise NotImplementedError("gt_scalar_: rank > 8 unsupported")
            shape = A.shape
            stride = A.stride()
            s = list(shape) + [1] * (8 - rank)
            t = list(stride) + [1] * (8 - rank)
            BLOCK = triton.next_power_of_2(min(max(n, 1), 512))
            EVEN = n % BLOCK == 0
            grid = (triton.cdiv(n, BLOCK),)
            num_warps = _num_warps_for(BLOCK)
            _gt_strided_kernel[grid](
                A,
                b_t,
                n,
                s[0],
                s[1],
                s[2],
                s[3],
                s[4],
                s[5],
                s[6],
                s[7],
                t[0],
                t[1],
                t[2],
                t[3],
                t[4],
                t[5],
                t[6],
                t[7],
                RANK=rank,
                CT=ct_tl,
                DT=dt_tl,
                A_BOOL=a_bool,
                B_BOOL=b_bool,
                OUT_BOOL=out_bool,
                ELEM_B=elem_b,
                EVEN=EVEN,
                BLOCK=BLOCK,
                num_warps=num_warps,
            )

        return A
