_SEED = 0x1234ABCD
_OFFSET = 0
_ALIGN = 2048
_WARPS = 8


def _is_pow2(v):
    return v > 0 and (v & (v - 1)) == 0


def _log2(v):
    return v.bit_length() - 1


def _run_flat(inp, out, p, scale, log2s, pattern):
    numel = inp.numel()
    n_full = (numel // _ALIGN) * _ALIGN
    if n_full > 0:
        _fd_aligned_kernel[(n_full // _ALIGN,)](
            inp,
            out,
            p,
            scale,
            LOG2S=log2s,
            BLOCK=_ALIGN,
            num_warps=_WARPS,
            PATTERN_OUT=pattern,
        )
    n_tail = numel - n_full
    if n_tail > 0:
        tblock = triton.next_power_of_2(n_tail)
        if tblock < 64:
            tblock = 64
        if tblock > 1024:
            tblock = 1024
        _fd_tail_kernel[(triton.cdiv(n_tail, tblock),)](
            inp,
            out,
            n_full,
            numel,
            p,
            scale,
            LOG2S=log2s,
            BLOCK=tblock,
            num_warps=4,
            PATTERN_OUT=pattern,
        )


def _run_channel_fallback(inp, out, nc, spatial, p, scale):
    bs = triton.next_power_of_2(spatial)
    if bs > 2048:
        bs = 2048
    bc = max(1, 8192 // bs)
    grid = (triton.cdiv(nc, bc), triton.cdiv(spatial, bs))
    _fd_channel_kernel[grid](
        inp,
        out,
        nc,
        spatial,
        p,
        scale,
        _SEED,
        _OFFSET,
        BLOCK_C=bc,
        BLOCK_S=bs,
        num_warps=16,
    )


def feature_dropout(input, p, train=True):
    # Effective parameters (same observable semantics as the reference):
    #   not train or p == 0 -> identity copy; p >= 1 (train) -> zeros.
    with torch_device_fn.device(input.device):
        if not train or p == 0:
            p_eff = -1.0
            scale = 1.0
        elif p >= 1:
            p_eff = 2.0
            scale = 1.0
        else:
            p_eff = float(p)
            scale = 1.0 / (1.0 - float(p))

        if not input.is_contiguous():
            input = input.contiguous()

        numel = input.numel()
        if numel == 0:
            return torch.empty_like(input)

        spatial = 1
        if input.ndim >= 2:
            for i in range(2, input.ndim):
                spatial *= input.shape[i]

        out = torch.empty_like(input)
        pattern = input.dtype == torch.bfloat16
        out_store = out.view(torch.int16) if pattern else out
        if _is_pow2(spatial):
            _run_flat(
                inp=input,
                out=out_store,
                p=p_eff,
                scale=scale,
                log2s=_log2(spatial),
                pattern=pattern,
            )
        elif input.ndim >= 2:
            nc = input.shape[0] * input.shape[1]
            _run_channel_fallback(input, out, nc, spatial, p_eff, scale)
        else:
            _run_flat(
                inp=input, out=out_store, p=p_eff, scale=scale, log2s=0, pattern=pattern
            )
        return out
