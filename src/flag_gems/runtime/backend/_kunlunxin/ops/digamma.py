@triton.jit
def _digamma_kernel(X, Y, N, BLOCK: tl.constexpr):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < N
    x = tl.load(X + offs, mask=mask, other=1.0)
    xf = x.to(tl.float32)
    neg = xf < 0.0
    z = tl.where(neg, 1.0 - xf, xf)
    # Universal recurrence: psi(z) = psi(z+2) - 1/z - 1/(z+1) for every z > 0,
    # so z+2 >= 2 and the asymptotic expansion below is always valid.
    # The two reciprocal terms are merged into a single division:
    #   1/z + 1/(z+1) = (2z+1) / (z*(z+1)).
    s = (2.0 * z + 1.0) / (z * (z + 1.0))
    y = z + 2.0
    w = 1.0 / y
    q = w * w
    p = 0.08333333333333333 + q * (
        -0.008333333333333333 + q * (0.003968253968253968 + q * (-0.004166666666666667))
    )
    pos = tl.log(y) - (0.5 * w) - (q * p) - s
    # reflection correction for negative x:  psi(x) = psi(1-x) - pi*cot(pi*x)
    # cot(pi*x) = cot(pi*r) with r = x - nearest_int(x) in [-0.5, 0.5] (exact).
    # corr = -pi*cot(u) = -(1/r)*g(u) with u = pi*r and g(u) = u*cot(u),
    # using the convergent series g(u) = 1 - w/3 - w^2/45 - 2w^3/945 - ...
    # (w = u*u).  Selected away for non-negative lanes by tl.where.
    r = xf - tl.floor(xf + 0.5)
    u = 3.141592653589793 * r
    w2 = u * u
    g = 1.0 + w2 * (
        -0.3333333333333333
        + w2
        * (
            -0.022222222222222223
            + w2
            * (
                -0.0021164021164021164
                + w2
                * (
                    -0.00021164021164021164
                    + w2 * (-2.137757468531478e-05 + w2 * (-2.164404e-06))
                )
            )
        )
    )
    corr = -g / r
    res = tl.where(neg, pos + corr, pos)
    tl.store(Y + offs, res.to(x.dtype), mask=mask)


