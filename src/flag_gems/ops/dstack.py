@triton.jit
def _dstack_u3(
    out_ptr,
    p0,
    p1,
    p2,
    p3,
    p4,
    p5,
    p6,
    p7,
    K,
    R,
    K_total,
    N: tl.constexpr,
    BR: tl.constexpr,
    BK: tl.constexpr,
):
    pid_r = tl.program_id(0)
    pid_k = tl.program_id(1)

    rows = pid_r * BR + tl.arange(0, BR)
    ks = pid_k * BK + tl.arange(0, BK)
