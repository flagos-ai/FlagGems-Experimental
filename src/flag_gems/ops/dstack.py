def _run_3d(tensors, dev, dtype, out=None):
    M = N = None
    Ks = []
    ptrs = []
    contig_all = True
    for t in tensors:
        d = t.dim()
        if d == 1:
            M_, N_, K_ = 1, t.numel(), 1
        elif d == 2:
            M_, N_, K_ = t.shape[0], t.shape[1], 1
        else:
            M_, N_, K_ = t.shape[0], t.shape[1], t.shape[2]
        if M is None:
            M, N = M_, N_
        Ks.append(K_)
        ptrs.append(t.data_ptr())
        contig_all = contig_all and t.is_contiguous()

    K_total = sum(Ks)
    R = M * N
    if out is None:
        out = torch.empty((M, N, K_total), dtype=dtype, device=dev)
    if out.numel() == 0:
        # Nothing to copy (empty batch/rows, or a zero-width K). Returning
        # here also keeps the kernel grid non-degenerate; the result is the
        # same fresh empty allocation native produces.
        return out
    Nt = len(tensors)

    with torch_device_fn.device(dev):
        if Nt == 1 and contig_all:
            total = R * K_total
            _dstack_flat_copy[(triton.cdiv(total, 1024),)](
                tensors[0], out, total, BLOCK=1024
            )
            return out

        uniform = all(k == Ks[0] for k in Ks)
        if contig_all and uniform and Nt <= NMAX:
            K = Ks[0]
            if K == 1:
                BR = 256
                grid = (triton.cdiv(R, BR),)
                if Nt <= 4:
                    args = ptrs + [0] * (4 - Nt)
                    _dstack_u3_1d_tile4[grid](
                        out, *args, R, K_total, N=Nt, BR=BR, PAD=4, num_warps=4
                    )
                else:
                    args = ptrs + [0] * (NMAX - Nt)
                    _dstack_u3_1d_tile8[grid](
                        out, *args, R, K_total, N=Nt, BR=64, PAD=8, num_warps=4
                    )
            else:
                BR, BK = 1, 512
                grid = (triton.cdiv(R, BR), triton.cdiv(K, BK))
                args = ptrs + [0] * (NMAX - Nt)
                _dstack_u3[grid](
                    out, *args, K, R, K_total, N=Nt, BR=BR, BK=BK, num_warps=4
                )
            return out

        # fallback: device metadata table. Every row must have the width the
        # kernel selects through CONTIG, so the strides are emitted for *all*
        # inputs as soon as one input is non-contiguous (a contiguous tensor's
        # (stride(0), stride(1), stride(2)-equivalents) are exactly what the
        # CONTIG=False branch indexes with, so the recorded values stay valid).
        metas = []
        for idx, t in enumerate(tensors):
            d = t.dim()
            if d == 1:
                st = t.stride(0)
                s0, s1, s2 = st * t.numel(), st, 1
            elif d == 2:
                s0, s1, s2 = t.stride(0), t.stride(1), 1
            else:
                s0, s1, s2 = t.stride(0), t.stride(1), t.stride(2)
            if contig_all:
                metas.append([t.data_ptr(), 0, Ks[idx]])
            else:
                metas.append([t.data_ptr(), 0, Ks[idx], s0, s1, s2])
        k_off = 0
        for row in metas:
            row[1] = k_off
            k_off += row[2]
        meta = torch.tensor(metas, dtype=torch.int64, device=dev)
        maxK = max(Ks)
        BR, BK = (128, 1) if maxK == 1 else (1, 512)
        grid = (triton.cdiv(R, BR), Nt, triton.cdiv(maxK, BK))
        _dstack_fused3[grid](out, meta, R, K_total, N, CONTIG=contig_all, BR=BR, BK=BK)
        return out


def _run_nd(tensors, D, dev, dtype, out=None):
    S = tuple(int(s) for s in tensors[0].shape)
    Ks = [int(t.shape[2]) for t in tensors]
    K_total = sum(Ks)
    if out is None:
        out = torch.empty(S[:2] + (K_total,) + S[3:], dtype=dtype, device=dev)
    if out.numel() == 0:
        # Empty output (zero-element batch/trailing dims, or a zero-width K);
        # also guards the row count division below when K_total == 0.
        return out
    os = tuple(int(s) for s in out.stride())
    R = out.numel() // K_total
    metas = []
    k_off = 0
    for t in tensors:
        st = tuple(int(s) for s in t.stride())
        metas.append([t.data_ptr(), k_off, int(t.shape[2]), *st, *S, *os])
        k_off += int(t.shape[2])
    with torch_device_fn.device(dev):
        meta = torch.tensor(metas, dtype=torch.int64, device=dev)
        maxK = max(Ks)
        BR, BK = (128, 1) if maxK == 1 else (1, 512)
        grid = (triton.cdiv(R, BR), len(tensors), triton.cdiv(maxK, BK))
        _dstack_fused_nd[grid](out, meta, R, K_total, D=D, BR=BR, BK=BK)
        return out


def _promoted_shape(t):
    """Input's shape after native's implicit ``atleast_3d`` promotion.

    ``aten::dstack`` is ``cat([atleast_3d(t) for t in tensors], dim=2)``, so
    0-D/1-D/2-D inputs are read as 3-D (``(1, 1, 1)`` / ``(1, N, 1)`` /
    ``(M, N, 1)``). The (M, N, K) triple is exactly what the kernels index
    with, which is why validation runs on this promoted view of each input.
    """
    d = t.dim()
    if d == 0:
        return 1, 1, 1
    if d == 1:
        return 1, t.numel(), 1
    if d == 2:
        return t.shape[0], t.shape[1], 1
    return t.shape[0], t.shape[1], t.shape[2]


def _promoted_rank(t):
    d = t.dim()
    return d if d >= 3 else 3


def _expected_shape(tensors, rank):
    """Output shape native produces for an already-validated tensor list."""
    if rank == 3:
        m0, n0, _ = _promoted_shape(tensors[0])
        k_total = sum(_promoted_shape(t)[2] for t in tensors)
        return (m0, n0, k_total)
    first = tuple(int(s) for s in tensors[0].shape)
    k_total = sum(int(t.shape[2]) for t in tensors)
    return first[:2] + (k_total,) + first[3:]


