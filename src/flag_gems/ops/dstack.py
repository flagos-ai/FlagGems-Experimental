@triton.jit
def _dstack_flat_copy(
    in_ptr,
    out_ptr,
    total,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < total
    v = tl.load(in_ptr + offs, mask=mask)
    tl.store(out_ptr + offs, v, mask=mask)


