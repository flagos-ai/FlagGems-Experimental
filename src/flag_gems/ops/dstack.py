# Fast path for K == 1 (1-D / 2-D inputs), uniform K, contiguous,
# N <= 4. Each program handles BR rows and loads an interleaved
# (BR, PAD) tile directly (one column per input, PAD = next_pow2(N)
# >= N) via a per-column pointer-vector select, so the store lanes
# are memory-contiguous (the whole tile is a contiguous span of the
# output row-major layout). This avoids the stride-K_total scatter
# stores of the naive per-input loop. Inputs arrive as plain int64
# scalar args: no meta table, no H2D. grid = (R/BR,)
# ---------------------------------------------------------------
@triton.jit
def _dstack_u3_1d_tile4(
    out_ptr,
    p0,
    p1,
    p2,
    p3,
    R,
    K_total,
    N: tl.constexpr,
    BR: tl.constexpr,
    PAD: tl.constexpr,
):
    pid = tl.program_id(0)
    rows = pid * BR + tl.arange(0, BR)
    rmask = rows < R
    cols = tl.arange(0, PAD)
    cmask = cols < N
    mask = rmask[:, None] & cmask[None, :]

    dt = out_ptr.dtype.element_ty
    col_ptr = tl.where(
        cols == 0, p0, tl.where(cols == 1, p1, tl.where(cols == 2, p2, p3))
    )
    col_ptr_p = col_ptr.to(tl.pointer_type(dt))
    v = tl.load(
        col_ptr_p[None, :] + rows[:, None], mask=mask, eviction_policy="evict_last"
    )
    tl.store(
        out_ptr + rows[:, None] * K_total + cols[None, :],
        v,
        mask=mask,
        eviction_policy="evict_last",
    )


