# Fused dstack kernel for tensors with ndim <= 3 (fallback path:
# non-uniform K, non-contiguous inputs, or N > NMAX).
# meta rows (int64):
#   CONTIG:   [data_ptr, k_off, k_i]            (width 3)
#   non-CONT: [data_ptr, k_off, k_i, s0, s1, s2] (width 6)
# grid = (R/BR, N, K/BK)
# ---------------------------------------------------------------
@triton.jit
def _dstack_fused3(
    out_ptr,
    meta_ptr,
    R,
    K_total,
    Ndim,
    CONTIG: tl.constexpr,
    BR: tl.constexpr,
    BK: tl.constexpr,
):
    W: tl.constexpr = 3 if CONTIG else 6
    pid_i = tl.program_id(1)
    pid_r = tl.program_id(0)
    pid_k = tl.program_id(2)

    base = pid_i * W
    in_ptr = tl.load(meta_ptr + base + 0)
    k_off = tl.load(meta_ptr + base + 1)
    k_i = tl.load(meta_ptr + base + 2)

    rows = pid_r * BR + tl.arange(0, BR)
    ks = pid_k * BK + tl.arange(0, BK)
    rmask = rows < R
    kmask = ks < k_i
    mask = rmask[:, None] & kmask[None, :]

    if CONTIG:
        in_base = rows * k_i
        s2 = 1
    else:
        s0 = tl.load(meta_ptr + base + 3)
        s1 = tl.load(meta_ptr + base + 4)
        s2 = tl.load(meta_ptr + base + 5)
        m = rows // Ndim
        n = rows % Ndim
        in_base = m * s0 + n * s1

    in_off = in_base[:, None] + ks[None, :] * s2
    out_off = rows[:, None] * K_total + k_off + ks[None, :]

    in_ptr_p = in_ptr.to(tl.int64).to(tl.pointer_type(out_ptr.dtype.element_ty))
    v = tl.load(in_ptr_p + in_off, mask=mask)
    tl.store(out_ptr + out_off, v, mask=mask)


# ---------------------------------------------------------------
# General fused dstack kernel for ndim >= 4: concatenation along
# dim 2 of shape (S0, S1, K_i, S3, ..., S_{D-1}).
# meta rows (int64, width 3 + 3*D):
#   [ptr, k_off, k_i, s0..s_{D-1}, S0..S_{D-1}, os0..os_{D-1}]
# ---------------------------------------------------------------
@triton.jit
def _dstack_fused_nd(
    out_ptr,
    meta_ptr,
    R,
    K_total,
    D: tl.constexpr,
    BR: tl.constexpr,
    BK: tl.constexpr,
):
    pid_i = tl.program_id(1)
    pid_r = tl.program_id(0)
    pid_k = tl.program_id(2)

    W: tl.constexpr = 3 + 3 * D
    base = pid_i * W
    in_ptr = tl.load(meta_ptr + base + 0)
    k_off = tl.load(meta_ptr + base + 1)
    k_i = tl.load(meta_ptr + base + 2)
    s2 = tl.load(meta_ptr + base + 3 + 2)
    os2 = tl.load(meta_ptr + base + 3 + 2 * D + 2)

    rows = pid_r * BR + tl.arange(0, BR)
    ks = pid_k * BK + tl.arange(0, BK)
    rmask = rows < R
    kmask = ks < k_i
    mask = rmask[:, None] & kmask[None, :]

    rem = rows.to(tl.int64)
    in_base = tl.zeros((BR,), dtype=tl.int64)
    out_base = tl.zeros((BR,), dtype=tl.int64)
    for jj in tl.static_range(D):
        j = D - 1 - jj
        if j != 2:
            S_j = tl.load(meta_ptr + base + 3 + D + j)
            s_j = tl.load(meta_ptr + base + 3 + j)
            o_j = tl.load(meta_ptr + base + 3 + 2 * D + j)
            c_j = rem % S_j
            rem = rem // S_j
            in_base += c_j * s_j
            out_base += c_j * o_j

    in_off = in_base[:, None] + ks[None, :] * s2
    out_off = out_base[:, None] + (k_off + ks[None, :]) * os2

    in_ptr_p = in_ptr.to(tl.int64).to(tl.pointer_type(out_ptr.dtype.element_ty))
    v = tl.load(in_ptr_p + in_off, mask=mask)
    tl.store(out_ptr + out_off, v, mask=mask)


