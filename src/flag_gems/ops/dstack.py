    kmask = ks < K
    mask = rmask[:, None] & kmask[None, :]
    in_off = rows[:, None] * K + ks[None, :]

    for i in tl.static_range(N):
        if i == 0:
            p = p0
        elif i == 1:
            p = p1
        elif i == 2:
            p = p2
        elif i == 3:
            p = p3
        elif i == 4:
            p = p4
        elif i == 5:
            p = p5
        elif i == 6:
            p = p6
        else:
            p = p7
