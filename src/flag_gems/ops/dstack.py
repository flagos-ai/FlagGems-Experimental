# Fast path for K > 1 (3-D inputs), uniform-K contiguous,
# N <= 8: row-chunked copy, one row per program (BR=1, BK=512),
# input loop unrolled at trace time. Each program writes its row's
# K segments contiguously.
# grid = (R, cdiv(K, BK))
