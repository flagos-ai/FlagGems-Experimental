def _normalized(
    tensors: Union[Tuple[torch.Tensor, ...], List[torch.Tensor]],
) -> Tuple[List[torch.Tensor], torch.dtype, int]:
    """Validate ``tensors`` and return (canonicalised list, dtype, rank).

    Implements the measured native order: non-empty list -> device -> dtype
    promotion -> promoted rank -> promoted sizes. ``rank`` is the rank after
    native's ``atleast_3d`` promotion, so 0-D/1-D/2-D all report 3.
    """
    if len(tensors) == 0:
        raise RuntimeError("dstack expects a non-empty TensorList")

    # 0-D inputs are read as (1, 1, 1) by native's atleast_3d. Making that
    # explicit here keeps them on the wrapper's existing 1-D code path (a raw
    # 0-D tensor has no shape[1]/shape[2] for the kernels to index with).
    tensors = [t.view(1) if t.dim() == 0 else t for t in tensors]

    device = tensors[0].device
    for t in tensors[1:]:
        if t.device != device:
            raise RuntimeError(
                f"Tensor on device {t.device} is not on the expected device "
                f"{device}!"
            )

    # Type promotion across the list, as native does before concatenating.
    dtype = tensors[0].dtype
    for t in tensors[1:]:
        dtype = torch.promote_types(dtype, t.dtype)
    tensors = [t if t.dtype == dtype else t.to(dtype) for t in tensors]

    rank = _promoted_rank(tensors[0])
    for t in tensors[1:]:
        if _promoted_rank(t) != rank:
            raise RuntimeError(
                f"Tensors must have same number of dimensions: "
                f"got {rank} and {_promoted_rank(t)}"
            )

    # Sizes must agree in every dimension except dim 2. The check walks the
    # list in order and reports the first offending tensor/dimension, which is
    # the order native reports in. Rank-3 lists validate against the promoted
    # (M, N, K) triple; higher-rank lists validate against the raw shape.
    if rank == 3:

        def checked_shape_of(t):
            return _promoted_shape(t)

    else:

        def checked_shape_of(t):
            return tuple(t.shape)

    base_shape = checked_shape_of(tensors[0])
    for i, t in enumerate(tensors[1:], start=1):
        shape = checked_shape_of(t)
        for j in range(rank):
            if j != 2 and shape[j] != base_shape[j]:
                raise RuntimeError(
                    f"Sizes of tensors must match except in dimension 2. "
                    f"Expected size {base_shape[j]} but got size "
                    f"{shape[j]} for tensor number {i} in the list."
                )

    return tensors, dtype, rank


def dstack(
    tensors: Union[Tuple[torch.Tensor, ...], List[torch.Tensor]],
) -> torch.Tensor:
    """Stack tensors in sequence along the third axis, mirroring ``aten::dstack``.

    Native ``dstack`` is the composite
    ``cat([atleast_3d(t) for t in tensors], dim=2)``: every input is promoted
    to at least three dimensions (0-D -> ``(1, 1, 1)``, 1-D -> ``(1, N, 1)``,
    2-D -> ``(M, N, 1)``) and rank >= 3 inputs are concatenated along dim 2
    unchanged. All of the following was measured against native on this build
    (CPU probes, container torch 2.8.0a0, see the run report):

    - an empty list raises ``RuntimeError`` (``dstack expects a non-empty
      TensorList``);
    - all tensors must live on the first tensor's device, else ``RuntimeError``;
    - the output dtype is the type promotion of all input dtypes, and the
      promotion is computed *before* the rank/size checks (so a pair whose
      promotion is unsupported reports the promotion error, not a shape one);
    - ranks are compared after promotion, so a 1-D and a 2-D input are legal
      together when their promoted shapes agree;
    - sizes must agree in every promoted dimension except dim 2, else
      ``RuntimeError`` (``Sizes of tensors must match except in dimension 2``);
    - the result is always a fresh contiguous allocation.

    Validation order therefore is: non-empty list -> device -> dtype promotion
    -> promoted rank -> promoted sizes, matching native's observable order.

    Args:
        tensors: A non-empty list/tuple of tensors, all on the same device.

    Returns:
        torch.Tensor: The concatenated tensor.
    """
    logger.debug("GEMS DSTACK")

    tensors, dtype, rank = _normalized(tensors)
    dev = tensors[0].device
    if rank >= 4:
        return _run_nd(tensors, rank, dev, dtype)
    return _run_3d(tensors, dev, dtype)


def dstack_out(
    tensors: Union[Tuple[torch.Tensor, ...], List[torch.Tensor]],
    *,
    out: torch.Tensor,
) -> torch.Tensor:
    """``aten::dstack.out``: write the concatenation into ``out`` and return it.

    Measured native behaviour on this build:

    - the result *is* ``out`` (same object, same storage); a correctly shaped
      ``out`` is written in place;
    - when the shape does not match, ``out`` is resized to the computed shape
      (native does this through ``resize_output``; a resized ``out`` is made
      contiguous again), so a non-contiguous or oversized buffer comes back
      contiguous and correctly shaped;
    - the input lists is validated first: an invalid list leaves ``out``
      untouched and raises before any resize;
    - the write dtype rule is exactly ``torch.can_cast(promoted_input_dtype,
      out.dtype)`` (checked over 20+ dtype pairs); when it holds, the promoted
      values are cast into ``out.dtype``.

    The kernels are reused unchanged: a non-conforming ``out`` is resized to a
    contiguous buffer first and the kernels write directly into it.

    Args:
        tensors: A non-empty list/tuple of tensors, all on the same device.
        out: Destination tensor, written in place and returned.

    Returns:
        torch.Tensor: ``out``.
    """
    logger.debug("GEMS DSTACK_OUT")

    tensors, dtype, rank = _normalized(tensors)
    dev = tensors[0].device

    if not torch.can_cast(dtype, out.dtype):
        # Native raises this from the underlying cat(). The C++ type spelling
        # in the tail of the message is build-specific, so only the stable
        # semantic fragment is reproduced here (tests assert class + fragment).
        raise RuntimeError(
            "torch.cat(): input types can't be cast to the desired output "
            f"type {_cpp_dtype_name(out.dtype)}"
        )
    expected_shape = _expected_shape(tensors, rank)
    if tuple(out.shape) != expected_shape:
        # Native resizes a wrongly shaped out (and a resized buffer comes back
        # contiguous). A matching-shape buffer keeps its own layout, so no
        # resize happens in that case.
        out.resize_(expected_shape)
    if out.numel() == 0:
        return out

    if out.dtype == dtype and out.is_contiguous():
        target = out
    else:
        # Two cases cannot be written in place by the kernels: a non-contiguous
        # out (the kernels store through flat offsets), and an out dtype that
        # differs from the promoted input dtype (the kernels type their input
        # pointers from out_ptr, which is a reinterpret, not a cast). Both go
        # through a contiguous scratch buffer of the promoted dtype; the final
        # copy_ performs the cast and preserves out's layout, matching native.
        target = torch.empty(expected_shape, dtype=dtype, device=dev)
    if rank >= 4:
        res = _run_nd(tensors, rank, dev, dtype, out=target)
    else:
        res = _run_3d(tensors, dev, dtype, out=target)
    if target is not out:
        out.copy_(res)
    return out
