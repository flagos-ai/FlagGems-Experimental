# Naive direct-conv kernel: used for float64 inputs (tl.dot has no fp64 path)
# ---------------------------------------------------------------------------
@triton.jit
def _slow_conv2d_naive(
    inp,
    wgt,
    bias_ptr,
    out,
    N: tl.constexpr,
    C_in: tl.constexpr,
    H: tl.constexpr,
    W: tl.constexpr,
    C_out: tl.constexpr,
    KH: tl.constexpr,
    KW: tl.constexpr,
    H_out: tl.constexpr,
    W_out: tl.constexpr,
    stride_h: tl.constexpr,
    stride_w: tl.constexpr,
    pad_h: tl.constexpr,
    pad_w: tl.constexpr,
    has_bias: tl.constexpr,
    IS_FP64: tl.constexpr,
    BLOCK_W: tl.constexpr,
):
    pid = tl.program_id(0)
    pid_w = tl.program_id(1)

    h_out = pid % H_out
    t = pid // H_out
    co = t % C_out
    n = t // C_out

    w = pid_w * BLOCK_W + tl.arange(0, BLOCK_W)
    wm = w < W_out

    ih0 = h_out * stride_h - pad_h
    iw0 = w * stride_w - pad_w

    if IS_FP64:
        acc = tl.zeros([BLOCK_W], dtype=tl.float64)
    else:
        acc = tl.zeros([BLOCK_W], dtype=tl.float32)
    for c in range(C_in):
        for kh in tl.static_range(KH):
            ih = ih0 + kh
            hok = (ih >= 0) & (ih < H)
            for kw in tl.static_range(KW):
                iw = iw0 + kw
                m = wm & hok & (iw >= 0) & (iw < W)
                x = tl.load(
                    inp + n * (C_in * H * W) + c * (H * W) + ih * W + iw,
                    mask=m,
                    other=0.0,
                )
                wv = tl.load(wgt + co * (C_in * KH * KW) + c * (KH * KW) + kh * KW + kw)
                if IS_FP64:
                    acc += x * wv
                else:
                    acc += x.to(tl.float32) * wv.to(tl.float32)
    if has_bias:
        acc += tl.load(bias_ptr + co)
    tl.store(
        out + n * (C_out * H_out * W_out) + co * (H_out * W_out) + h_out * W_out + w,
        acc,
        mask=wm,
    )


