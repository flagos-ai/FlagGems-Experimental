# Implicit-GEMM kernel (input-major "m" = flattened N*H_out*W_out pixels).
# A[m, k] = input gather at tap k = c*KH*KW + kh*KW + kw (im2col on the fly),
# B[k, co] = weight in (C_in, KH, KW, C_out) layout (transposed in wrapper).
# The K loop is statically unrolled over exactly NCHUNK = ceil(K / K_CHUNK)
# chunks (no pow2 padding waste) and the k < K tail mask folds away at compile
# time for full chunks. Accumulate with tl.dot:
#   - fp16 / bf16 inputs: native tensor-core dot (exact products, fp32 acc)
#   - fp32 inputs (X3): fp16x3 split (A = hi + lo, B = hi + lo; three fp16
#     dots) reproduces ~fp32 accuracy at fp16 tensor-core rate.
# ---------------------------------------------------------------------------
@triton.jit
def _slow_conv2d_igemm(
    inp,
    wgt_t,
    bias_ptr,
    out,
    N: tl.constexpr,
    C_in: tl.constexpr,
    H: tl.constexpr,
    W: tl.constexpr,
    C_out: tl.constexpr,
    KH: tl.constexpr,
    KW: tl.constexpr,
    H_out: tl.constexpr,
    W_out: tl.constexpr,
    stride_h: tl.constexpr,
    stride_w: tl.constexpr,
    pad_h: tl.constexpr,
    pad_w: tl.constexpr,
    has_bias: tl.constexpr,
    X3: tl.constexpr,  # fp32 inputs: use fp16x3 split dot
    K: tl.constexpr,  # reduction length C_in*KH*KW
    NCHUNK: tl.constexpr,  # ceil(K / K_CHUNK)
    BLOCK_M: tl.constexpr,
    BLOCK_CO: tl.constexpr,
    K_CHUNK: tl.constexpr,
):
    pid_m = tl.program_id(0)
    pid_co = tl.program_id(1)

    M = N * H_out * W_out
    HW = H_out * W_out

    m = pid_m * BLOCK_M + tl.arange(0, BLOCK_M)
    mm = m < M
    co = pid_co * BLOCK_CO + tl.arange(0, BLOCK_CO)
    com = co < C_out

    n = m // HW
    rem = m % HW
    h_out = rem // W_out
    w_out = rem % W_out

    ih0 = h_out * stride_h - pad_h
    iw0 = w_out * stride_w - pad_w

    acc = tl.zeros([BLOCK_M, BLOCK_CO], dtype=tl.float32)
    for i in tl.static_range(NCHUNK):
        k = i * K_CHUNK + tl.arange(0, K_CHUNK)
        kw = k % KW
        kh = (k // KW) % KH
        c = k // (KH * KW)
        km = k < K

        a_ih = ih0[:, None] + kh[None, :]
        a_iw = iw0[:, None] + kw[None, :]
        a_ptr = (
            inp + n[:, None] * (C_in * H * W) + c[None, :] * (H * W) + a_ih * W + a_iw
        )
        a_mask = (
            mm[:, None]
            & km[None, :]
            & (a_ih >= 0)
            & (a_ih < H)
            & (a_iw >= 0)
            & (a_iw < W)
        )
        A = tl.load(a_ptr, mask=a_mask, other=0.0)

        b_ptr = wgt_t + k[:, None] * C_out + co[None, :]
        b_mask = km[:, None] & com[None, :]
        B = tl.load(b_ptr, mask=b_mask, other=0.0)

        if X3:
            A_hi = A.to(tl.float16)
            A_lo = (A - A_hi.to(tl.float32)).to(tl.float16)
            B_hi = B.to(tl.float16)
            B_lo = (B - B_hi.to(tl.float32)).to(tl.float16)
            acc += tl.dot(A_hi, B_hi)
            acc += tl.dot(A_hi, B_lo)
            acc += tl.dot(A_lo, B_hi)
        else:
            acc += tl.dot(A, B)

    if has_bias:
        acc += tl.load(bias_ptr + co, mask=com, other=0.0)[None, :]

    out_ptr = (
        out
        + n[:, None] * (C_out * HW)
        + co[None, :] * HW
        + h_out[:, None] * W_out
        + w_out[:, None]
    )
    tl.store(out_ptr, acc, mask=mm[:, None] & com[None, :])


def _next_pow2(x):
    p = 1
    while p < x:
        p *= 2
    return p


