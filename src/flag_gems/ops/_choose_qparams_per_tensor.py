def _get_buffers(dev):
    b = _buffers.get(dev)
    if b is None:
        pmn = torch.empty(_MAX_PROGRAMS, dtype=torch.float32, device=dev)
        pmx = torch.empty(_MAX_PROGRAMS, dtype=torch.float32, device=dev)
        counter = torch.zeros(1, dtype=torch.int32, device=dev)
        # pinned host-mapped output and completion flag: the kernel writes the
        # packed min/max directly to host-visible memory (valid device address
        # via UVA), then raises the flag; the host spins on the flag and reads
        # the result with no D2H copy and no stream query.
        out = torch.empty(1, dtype=torch.int64, pin_memory=True)
