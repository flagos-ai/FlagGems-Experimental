def _capture_fused(x, pmn, pmx, counter, out, flag, n, n_progs, BLOCK, nw):
    # Capture is only entered from the plain-launch branch, and only after the
    # caller has been cleared of holding a capture (see the caller).
    g = torch.cuda.CUDAGraph()
    # ``capture_error_mode="thread_local"``: torch.cuda.graph's default
    # "global" mode makes the capture forbid potentially-unsafe calls
    # *process-wide* -- a ``.item()``/stream sync issued by another thread
    # (here: the non-contiguous path's ``out2[0].item()``) errors with
    # "operation not permitted when stream is capturing" and poisons every
    # concurrent caller with a sticky CUDA error. Measured (H20, mixed
    # contiguous + non-contiguous threads): with the default mode a single
    # capture window kills four concurrent workers; with "thread_local" the
    # capture only constrains the capturing thread, which is the scope the
    # module lock already serializes. Scratch-buffer safety is unaffected:
    # the lock below still serializes every contiguous call, and the
    # non-contiguous path keeps its own per-call buffers.
    with torch.cuda.graph(g, capture_error_mode="thread_local"):
        _launch_fused(x, pmn, pmx, counter, out, flag, n, n_progs, BLOCK, nw)
    return g


def _choose_qparams_per_tensor(self, reduce_range=False):
    """Return the affine quantization parameters of ``self``.

    Mirrors ``aten::_choose_qparams_per_tensor(Tensor self, bool
    reduce_range=False) -> (float, int)``: a plain ``(scale, zero_point)``
    Python tuple, ``scale`` a Python float and ``zero_point`` a Python int.

    Two kernels are used. The contiguous path streams the tensor with a fused
    min/max kernel whose last program packs the two float32 results into one
    int64, writes them to pinned host memory and raises a release-ordered
    completion flag; the caller spins on that flag instead of synchronizing the
    device. The non-contiguous path walks the logical index space through an
    int32 shape/stride table with int64 offsets: each per-axis term is
    accumulated into an int64 ``off``, so an offset whose *sum* exceeds
    ``2**31`` is still walked correctly. The table is int32 rather than int64
    because the kernel's loop-carried ``rem`` (``rem = idx``) is int32 and
    Triton rejects the loop when an int64 load re-types it; a size or stride
    at or above ``2**31`` therefore fails when the table is built. The
    reduction itself uses ``atomic_min``/``atomic_max``.

    The ``(scale, zero_point)`` arithmetic that follows the reduction is the
    reference one, in float32: ``scale = (max(max, 0) - min(min, 0)) / qmax``
    with ``qmax = 127`` when ``reduce_range`` else ``255``, floored at
    ``float32(0.000061)``; a zero raw scale becomes ``(0.1, 0)``; otherwise
    ``zero_point = -round(min(min, 0) / scale_raw)`` clamped to ``[0, qmax]``.

    Documented, measured differences from the native operator on the H20 build
    (``torch 2.8.0a0+5228986c39.nv25.05``); the tests pin each of them on both
    sides rather than pretending they agree:

    - Subnormal ranges. Native replaces the scale with the fixed ``0.1`` when
      the float32 reciprocal of the raw scale is infinite (``[0, x]`` with
      ``x`` below ~``1.2e-38``), while the reference formula only floors at the
      small-scale threshold. Measured on ``[0, 1e-38]``: native
      ``(0.1, 0)``, this implementation ``(6.0999998822808266e-05, 0)``; the
      boundary sits between ``1e-37`` and ``1e-36``, where both sides return
      the floor again. The contiguous and non-contiguous paths of this
      implementation agree with *each other* across the whole window.
    - ``inf`` input: native returns ``scale = inf`` with ``zero_point``
      ``-2**31`` for a positive-infinite maximum, but the clamp (``qmax``) for
      a negative-infinite minimum, since only the latter reaches native's
      clamp. A finite maximum with ``min = -inf`` is answered ``(inf, qmax)``
      here as well; the reference formula would instead compute ``inf / inf``
      -> NaN and fail on ``round(nan)``. Native's NaN input raises
      ``RuntimeError: In ChooseQuantizationParams, min should be less than or
      equal to max`` and is not matched. All of this is pinned by the tests.
    - A tensor with no device storage (``meta``, whose ``data_ptr()`` is 0), a
      host tensor, a float8/complex dtype, or a sparse layout cannot be
      launched on (or must be answered by native's own rejection); those
      inputs are delegated to the native math kernel unchanged, so native's
      own behaviour is what the caller sees. Without the delegation the
      pinned-flag spin would never terminate for a meta tensor (measured: a
      meta tensor hung the caller past a 30 s probe timeout), a float8 tensor
      would get numbers where native raises, and a CPU tensor would fail
      inside the launcher instead of reproducing native's answer.
    - ``reduce_range`` is dropped by native when the quantization engine is
      QNNPACK (``qengine() == QNNPACK``); this implementation always honours
      the argument. The default engine on this build is ``x86``, where the two
      agree.
    - Thread safety and capture are this implementation's own concern, not
      native's: see ``_call_lock`` and the capture guard in the contiguous
      branch.
    """
    logger.debug("GEMS _CHOOSE_QPARAMS_PER_TENSOR")
    try:
        device_context = torch_device_fn.device(self.device)
    except Exception:
        # Not a device this backend can launch on (meta, or a host tensor):
        # hand the call back to the native math kernel.
        return _native_fallback(self, reduce_range)

    dev = self.device
    with device_context:
        # A storage-less tensor has numel > 0 but a null item data pointer;
        # launching on it would leave the completion flag unset for ever.
        # Float8 and complex dtypes are delegated too: native rejects both
        # (``RuntimeError`` from its min()/max() or dtype checks) and must not
        # be answered with numbers (float8, measured: source returned
        # (0.0117, 170) where native raises) or a foreign error class.
        if (
            self.layout != torch.strided
            or self.data_ptr() == 0
            or self.dtype in _NATIVE_UNSUPPORTED_DTYPES
            or self.dtype.is_complex
        ):
            return _native_fallback(self, reduce_range)

        n = self.numel()
        if n == 0:
            # Mirrors the source implementation's explicit empty-input guard.
            # Native raises the same error from its own ``min()`` call; the
            # integration container's build emits this exact sentence, and CI
            # runs a different build, so the tests assert the class plus the
            # semantic fragments (``min()``, ``dim``, ``numel() == 0``) rather
            # than the whole string.
            raise RuntimeError(
                "min(): Expected reduction dim to be specified for "
                "input.numel() == 0."
            )

        if self.is_contiguous():
            # A launch recorded inside someone else's CUDA capture is not
            # *executed* (measured: the completion flag never rises), so the
            # host spin below would wait for ever. Native has the same
            # limitation -- ``min().item()`` cannot be captured either -- so the
            # call is handed back to the native math kernel, which reports the
            # capture error to the caller exactly as it would without this
            # registration. This is the same "no launch possible here"
            # delegation as the meta/host guard above.
            if torch.cuda.is_current_stream_capturing():
                return _native_fallback(self, reduce_range)

            pmn, pmx, counter, out, out_np, flag, flag_np = _get_buffers(dev)
            # Larger blocks / fewer programs for big tensors: identical
            # streaming throughput with less device-side block-launch overhead.
            if n >= 1048576:
                BLOCK = 2048
                gridcap = 512
                nw = 4
            else:
                BLOCK = _BLOCK
                gridcap = _MAX_PROGRAMS
                nw = _NUM_WARPS
            n_progs = min((n + BLOCK - 1) // BLOCK, gridcap)
            # The scratch buffers hold one call's partials, arrival counter,
            # packed result and completion flag at a time, so the whole
            # contiguous call -- launch, host spin and flag reset -- runs under
            # the module lock. Measured before the lock: two threads on two
            # streams corrupt each other's reduction, because each writes its
            # own partials into the same slots and the last arrival of either
            # kernel resets the shared counter for both.
            with _call_lock:
                key = (dev, self.data_ptr(), n, self.dtype)
                entry = _graph_cache.get(key)
                if entry is None:
                    _launch_fused(
                        self, pmn, pmx, counter, out, flag, n, n_progs, BLOCK, nw
                    )
                    _graph_cache[key] = [None, 1]
                else:
                    g, count = entry
                    if count >= 2:
                        g.replay()
                    else:
                        g = _capture_fused(
                            self, pmn, pmx, counter, out, flag, n, n_progs, BLOCK, nw
                        )
                        if len(_graph_cache) > _MAX_GRAPHS:
                            _graph_cache.pop(next(iter(_graph_cache)))
                        _graph_cache[key] = [g, count + 1]
                        g.replay()
                # spin on the release-ordered completion flag (pinned host
                # memory). This is the source design: no D2H copy and no stream
                # query. The guards above are what keep it from spinning for
                # ever -- every input that can reach this point launches a
                # kernel that raises the flag.
                while flag_np[0] == 0:
                    pass
                mn = float(out_np[0])
                mx = float(out_np[1])
                flag_np[0] = 0
        else:
            out2 = torch.tensor(
                [float("inf"), float("-inf")], device=dev, dtype=torch.float32
            )
            shape_t = torch.tensor(self.shape, device=dev, dtype=torch.int32)
            stride_t = torch.tensor(self.stride(), device=dev, dtype=torch.int32)
            n_progs = min((n + _BLOCK - 1) // _BLOCK, _MAX_PROGRAMS)
            _minmax_strided_kernel[(n_progs,)](
                self,
                out2,
                out2[1:],
                n,
                shape_t,
                stride_t,
                self.dim(),
                BLOCK=_BLOCK,
                num_warps=_NUM_WARPS,
            )
            mn = float(out2[0].item())
            mx = float(out2[1].item())

    qmax = 127 if reduce_range else 255
    mn_neg = mn if mn < 0.0 else 0.0
    mx_pos = mx if mx > 0.0 else 0.0
    scale_raw = (mx_pos - mn_neg) / float(qmax)

    if scale_raw == 0.0:
        scale = 0.1
        zero_point = 0
    else:
        # A negative-only infinite range makes ``scale_raw`` +inf, so the
        # reference ``-round(mn_neg / scale_raw)`` below is ``-round(nan)`` and
        # raises ``ValueError``. Native answers ``(inf, qmax)`` here, so return
        # that instead of crashing. (``mn_neg`` is the only negative term, so
        # ``scale_raw`` is +inf exactly when the range is infinite.)
        if np.isinf(scale_raw) and mn_neg < 0.0:
            return (float("inf"), qmax)
        if scale_raw < _SCALE_FLOOR:
            scale = _SCALE_FLOOR
        else:
            scale = scale_raw
        zero_point = -round(mn_neg / scale_raw)
        if zero_point < 0:
            zero_point = 0
        if zero_point > qmax:
            zero_point = qmax

    return (scale, zero_point)
