def slow_conv_transpose3d(
    self,
    weight,
    kernel_size,
    bias=None,
    stride=1,
    padding=0,
    output_padding=0,
    dilation=1,
) -> torch.Tensor:
    """Applies a 3-D transposed convolution (aten::slow_conv_transpose3d).

    ``self`` is (N, C_in, D, H, W) and ``weight`` is (C_in, C_out, kD, kH, kW)
    -- note the transposed-convolution channel order, the same one
    ``torch.nn.functional.conv_transpose3d`` uses. ``kernel_size``, ``stride``,
    ``padding``, ``output_padding`` and ``dilation`` are (D, H, W) triples
    (plain ints are accepted and broadcast, which the dispatched schema itself
    does not allow). The result is a freshly allocated contiguous
    (N, C_out, D_out, H_out, W_out) tensor with

        D_out = (D - 1) * sD - 2 * pD + dD * (kD - 1) + opD + 1

    and likewise for H and W. The strategy is an outer-product FFMA kernel for
    fp64, a sub-grid dense kernel for fp32 when the dilation divides the
    stride, a residue-class dot kernel for the remaining strided cases, and an
    implicit-GEMM dot kernel otherwise.
    """
    logger.debug("GEMS SLOW_CONV_TRANSPOSE3D")
    x = self

    kD, kH, kW = _triple(kernel_size, "kernel_size")
    sD, sH, sW = _triple(stride, "stride")
    pD, pH, pW = _triple(padding, "padding")
    opD, opH, opW = _triple(output_padding, "output_padding")
    dD, dH, dW = _triple(dilation, "dilation")

    # The kernels index the operands as flat contiguous arrays with the layout
    # fixed by this operator's contract, so every operand is normalised first
    # (a no-op for the contiguous tensors the dispatcher sees in the common
    # case; native accepts strided operands and computes the same values).
    x = x.contiguous()
    weight = weight.contiguous()
    if bias is not None:
        bias = bias.contiguous()

    if x.dim() != 5:
        raise RuntimeError(
            "slow_conv_transpose3d: expected a 5-D (N, C_in, D, H, W) input, "
            "but got shape %s" % (tuple(x.shape),)
        )
    if weight.dim() != 5:
        raise RuntimeError(
            "slow_conv_transpose3d: expected a 5-D (C_in, C_out, kD, kH, kW) "
            "weight, but got shape %s" % (tuple(weight.shape),)
        )
    if x.dtype not in (torch.float16, torch.bfloat16, torch.float32, torch.float64):
        raise TypeError("slow_conv_transpose3d: unsupported dtype %s" % (x.dtype,))
    if weight.dtype != x.dtype:
        raise RuntimeError(
            "slow_conv_transpose3d: expected the weight to have the same dtype "
            "as the input, but got %s and %s" % (x.dtype, weight.dtype)
        )

    N, C_in, D, H, W = x.shape
    C_out = weight.shape[1]

    if weight.shape[0] != C_in:
        raise RuntimeError(
            "slow_conv_transpose3d: expected the weight to have C_in == %d input "
            "channels, but got %d" % (C_in, weight.shape[0])
        )
    # The kernels address the weight as [C_in, C_out, kD, kH, kW] using the
    # kernel_size triple, so a triple that disagrees with the weight's own
    # kernel dimensions would read outside the weight storage.
    if (kD, kH, kW) != tuple(weight.shape[2:]):
        raise RuntimeError(
            "slow_conv_transpose3d: kernel_size %s does not match the weight's "
            "kernel dimensions %s" % ((kD, kH, kW), tuple(weight.shape[2:]))
        )

    if C_out <= 0 or N <= 0 or C_in <= 0 or D <= 0 or H <= 0 or W <= 0:
        raise RuntimeError(
            "slow_conv_transpose3d: expected non-empty (N, C_in, D, H, W) input "
            "and (C_in, C_out, kD, kH, kW) weight, but got input %s and weight %s"
            % (tuple(x.shape), tuple(weight.shape))
        )
    if bias is not None and (bias.dim() != 1 or bias.shape[0] != C_out):
        raise RuntimeError(
            "slow_conv_transpose3d: expected a 1-D bias with one element per "
            "output channel (%d), but got shape %s" % (C_out, tuple(bias.shape))
        )
    if bias is not None and bias.dtype != x.dtype:
        raise RuntimeError(
            "slow_conv_transpose3d: expected the bias to have the same dtype as "
            "the input, but got %s and %s" % (x.dtype, bias.dtype)
        )
    if sD <= 0 or sH <= 0 or sW <= 0:
        raise RuntimeError(
            "slow_conv_transpose3d: stride must be greater than zero, but got "
            "%s" % ((sD, sH, sW),)
        )
    if dD <= 0 or dH <= 0 or dW <= 0:
        raise RuntimeError(
            "slow_conv_transpose3d: dilation must be greater than zero, but got "
            "%s" % ((dD, dH, dW),)
        )
    if (
        min(opD, opH, opW) < 0
        or max(opD - max(sD, dD), opH - max(sH, dH), opW - max(sW, dW)) >= 0
    ):
        raise RuntimeError(
            "slow_conv_transpose3d: output_padding must be non-negative and "
            "smaller than either stride or dilation, but got output_padding %s "
            "stride %s dilation %s" % ((opD, opH, opW), (sD, sH, sW), (dD, dH, dW))
        )

    D_out = (D - 1) * sD - 2 * pD + dD * (kD - 1) + opD + 1
    H_out = (H - 1) * sH - 2 * pH + dH * (kH - 1) + opH + 1
    W_out = (W - 1) * sW - 2 * pW + dW * (kW - 1) + opW + 1

    if D_out <= 0 or H_out <= 0 or W_out <= 0:
        raise RuntimeError(
            "slow_conv_transpose3d: given input size (D, H, W) = (%d, %d, %d), "
            "the calculated output size (%d, %d, %d) is too small"
            % (D, H, W, D_out, H_out, W_out)
        )

    out = torch.empty((N, C_out, D_out, H_out, W_out), device=x.device, dtype=x.dtype)
    b_ptr = bias if bias is not None else weight

    with torch_device_fn.device(x.device):
        if x.dtype == torch.float64:
            # FFMA outer-product path (exact fp64)
            co_block, ho_tile, wo_tile = 8, 4, 16
            WT = triton.cdiv(W_out, wo_tile)
            grid = (
                N * D_out * WT,
                triton.cdiv(H_out, ho_tile),
                triton.cdiv(C_out, co_block),
            )
            _ct3d_ffma_kernel[grid](
                x,
                weight,
                b_ptr,
                out,
                C_in,
                C_out,
                D,
                H,
                W,
                D_out,
                H_out,
                W_out,
                HAS_BIAS=bias is not None,
                ACC_BITS=64,
                CO_BLOCK=co_block,
                HO_TILE=ho_tile,
                WO_TILE=wo_tile,
                kD=kD,
                kH=kH,
                kW=kW,
                sD=sD,
                sH=sH,
                sW=sW,
                pD=pD,
                pH=pH,
                pW=pW,
                dD=dD,
                dH=dH,
                dW=dW,
                num_warps=4,
                num_stages=2,
            )
        elif (
            (sH > 1 or sW > 1)
            and dH % sH == 0
            and dW % sW == 0
            and x.dtype == torch.float32
        ):
            # all-or-nothing residue classes (dilation divisible by stride):
            # bias-fill every output, then dense sub-grid conv on the single
            # active residue class. Only for fp32 (3-pass fp16-pair dots make
            # the masked flattened path expensive); fp16/bf16 stay flattened.
            rh = (-pH) % sH
            rw = (-pW) % sW
            rd = (-pD) % sD
            skip_do = (dD % sD) == 0
            co_block, ci_block, ht_tile, wt_tile, nw, ns = 32, 16, 8, 8, 8, 3
            if skip_do:
                md = (D_out - 1 - rd) // sD + 1
            else:
                md = D_out
            hn = (H_out - 1 - rh) // sH + 1
            wn = (W_out - 1 - rw) // sW + 1
            htn = triton.cdiv(hn, ht_tile)
            wtn = triton.cdiv(wn, wt_tile)
            hw_block = max(16, min(1024, triton.next_power_of_2(H_out * W_out)))
            # The fill kernel writes bias[co] into every output element, so the
            # residue classes with no tap keep a defined value. With bias=None
            # nothing may be added, and the source's dummy pointer (the weight)
            # would have the fill kernel read weight[co] into those elements --
            # measured native behaviour is a plain zero fill, so a zero tensor
            # supplies the fill value in that case.
            fill_ptr = b_ptr if bias is not None else out.new_zeros(C_out)
            _ct3d_bias_kernel[
                (N * C_out * D_out, triton.cdiv(H_out * W_out, hw_block))
            ](
                out,
                fill_ptr,
                C_out,
                D_out,
                H_out,
                W_out,
                BLOCK=hw_block,
                num_warps=4,
            )
            grid = (N * md * htn * wtn, triton.cdiv(C_out, co_block))
            _ct3d_sub_kernel[grid](
                x,
                weight,
                b_ptr,
                out,
                C_in,
                C_out,
                D,
                H,
                W,
                D_out,
                H_out,
                W_out,
                HAS_BIAS=bias is not None,
                PAIR=x.dtype == torch.float32,
                CO_BLOCK=co_block,
                CI_BLOCK=ci_block,
                HT_TILE=ht_tile,
                WT_TILE=wt_tile,
                kD=kD,
                kH=kH,
                kW=kW,
                sD=sD,
                sH=sH,
                sW=sW,
                pD=pD,
                pH=pH,
                pW=pW,
                dD=dD,
                dH=dH,
                dW=dW,
                RH=rh,
                RW=rw,
                RD=rd,
                SKIP_DO=skip_do,
                num_warps=nw,
                num_stages=ns,
            )
        elif (sH > 1 or sW > 1) and (dH % sH != 0 or dW % sW != 0):
            # residue-class dot kernel (no wasted parity lanes for strided H/W).
            # Only used when dilation is NOT divisible by stride in at least one
            # strided dim; otherwise residue classes are all-or-nothing (e.g.
            # d=s=2 checkerboard) and the flattened kernel balances better.
            sp_total = H_out * W_out
            if sp_total >= 900 and C_out >= 32:
                co_block, ci_block, ht_tile, wt_tile, nw, ns = 32, 16, 8, 8, 8, 3
            else:
                co_block, ci_block, ht_tile, wt_tile, nw, ns = 16, 16, 4, 8, 4, 3
            HN = triton.cdiv(H_out, sH)
            WN = triton.cdiv(W_out, sW)
            HTN = triton.cdiv(HN, ht_tile)
            WTN = triton.cdiv(WN, wt_tile)
            grid = (N * D_out * HTN * WTN, triton.cdiv(C_out, co_block), sH * sW)
            _ct3d_res_kernel[grid](
                x,
                weight,
                b_ptr,
                out,
                C_in,
                C_out,
                D,
                H,
                W,
                D_out,
                H_out,
                W_out,
                HAS_BIAS=bias is not None,
                PAIR=x.dtype == torch.float32,
                CO_BLOCK=co_block,
                CI_BLOCK=ci_block,
                HT_TILE=ht_tile,
                WT_TILE=wt_tile,
                kD=kD,
                kH=kH,
                kW=kW,
                sD=sD,
                sH=sH,
                sW=sW,
                pD=pD,
                pH=pH,
                pW=pW,
                dD=dD,
                dH=dH,
                dW=dW,
                num_warps=nw,
                num_stages=ns,
            )
        else:
            # implicit-GEMM dot path (fp16/bf16 tensor cores; fp32 fp16-pair emulation)
            sp_total = H_out * W_out
            is_fp16like = x.dtype in (torch.float16, torch.bfloat16)
            if sp_total >= 900 and C_out >= 32:
                co_block, ci_block, sp_block, nw, ns = 32, 16, 64, 8, 3
            elif is_fp16like and C_out >= 32 and sp_total >= 100:
                if C_in >= 32 and C_out >= 64:
                    co_block, ci_block, sp_block, nw, ns = 32, 32, 32, 8, 3
                else:
                    co_block, ci_block, sp_block, nw, ns = 32, 16, 32, 4, 3
            elif (not is_fp16like) and C_out >= 32 and sp_total >= 100:
                co_block, ci_block, sp_block, nw, ns = 32, 16, 16, 4, 3
            else:
                co_block, ci_block, sp_block, nw, ns = 16, 16, 32, 4, 3
            SPT = triton.cdiv(H_out * W_out, sp_block)
            grid = (N * D_out * SPT, triton.cdiv(C_out, co_block))
            _ct3d_dot_kernel[grid](
                x,
                weight,
                b_ptr,
                out,
                C_in,
                C_out,
                D,
                H,
                W,
                D_out,
                H_out,
                W_out,
                HAS_BIAS=bias is not None,
                PAIR=x.dtype == torch.float32,
                CO_BLOCK=co_block,
                CI_BLOCK=ci_block,
                SP_BLOCK=sp_block,
                kD=kD,
                kH=kH,
                kW=kW,
                sD=sD,
                sH=sH,
                sW=sW,
                pD=pD,
                pH=pH,
                pW=pW,
                dD=dD,
                dH=dH,
                dW=dW,
                num_warps=nw,
                num_stages=ns,
            )
    return out
