def _triple(v, name):
    if isinstance(v, (tuple, list)):
        if len(v) != 3:
            raise ValueError(f"{name} must have length 3, got {v}")
        return tuple(int(x) for x in v)
    if isinstance(v, int):
        return (v, v, v)
    raise ValueError(f"invalid {name}: {v}")


