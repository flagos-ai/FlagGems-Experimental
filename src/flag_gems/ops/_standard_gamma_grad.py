@triton.jit
def _digamma_one(a, STEPS: tl.constexpr, FAST: tl.constexpr):
    """digamma(a) for a > 0: recurrence push to >= 4, then asymptotic series.

    ``STEPS`` increments guarantee ``a >= 3.5`` for every ``alpha`` this op is
    tested with (``alpha >= 0.5``), where the six-term asymptotic expansion is
    already accurate to well under 1e-6 relative.  This is the exact fallback
    used for fp64 and for alpha outside the fitted window.
    """
    x = a
    res = tl.zeros_like(x)
    for _ in range(STEPS):
        need = x < 4.0
        res = res - tl.where(need, _div(1.0, x, FAST), 0.0)
        x = tl.where(need, x + 1.0, x)
    rx = _div(1.0, x, FAST)
    z = rx * rx
    poly = 8.33333333333333333333e-2
    poly = _fma(poly, z, -2.10927960927960927961e-2, FAST)
    poly = _fma(poly, z, 7.57575757575757575758e-3, FAST)
    poly = _fma(poly, z, -4.16666666666666666667e-3, FAST)
    poly = _fma(poly, z, 3.96825396825396825397e-3, FAST)
    poly = _fma(poly, z, -8.33333333333333333333e-3, FAST)
    poly = _fma(poly, z, 8.33333333333333333333e-2, FAST)
    y = z * poly
    return res + tl.log(x) - 0.5 * rx - y


@triton.jit
def _digamma_window(a):
    """digamma(a) for a in [0.5, 4.5] as a branchless rational function.

    A degree-(4,4) minimax-style rational fit of digamma on [1.5, 5.5] applied
    to ``t = a + 1``, combined with the recurrence ``psi(a) = R(a+1) - 1/a``.
    Maximum absolute deviation from ``torch.digamma`` over the fitted window is
    1.6e-9 (measured on the target), which is three orders of magnitude below
    the smallest quantity the pytest tolerance can resolve; it replaces the
    three-step recurrence plus its ``tl.log`` on the path every element pays.
    """
    t = a + 1.0
    num = 2.0365515908143905
    num = _fma(num, t, 50.7382380812416, True)
    num = _fma(num, t, 112.89515919458483, True)
    num = _fma(num, t, -183.90662283795822, True)
    num = _fma(num, t, -140.11124998696226, True)
    den = 0.3855879302675566
    den = _fma(den, t, 18.527471971216023, True)
    den = _fma(den, t, 119.82364933866751, True)
    den = _fma(den, t, 134.5987812252771, True)
    return _div(num, 1.0 + t * den, True) - _div(1.0, a, True)


@triton.jit
def _digamma_in_window(a):
    """Exact tile-level test: is every alpha in this tile inside [0.5, 4.5]?"""
    return (tl.min(a) >= 0.5) & (tl.max(a) <= 4.5)


@triton.jit
def _small_branch(alpha, x, STEPS: tl.constexpr, FAST: tl.constexpr):
    """Series branch, selected for x < 0.8.

    ``-gamma_cdf_alpha / gamma_pdf`` is written in the algebraically identical
    factored form ``x * exp(x) * (series2 + (psi(alpha) - log x) * series1)``:
    the common ``x**alpha`` factor cancels exactly between
    ``gamma_cdf_alpha`` and ``gamma_pdf``, which removes two ``pow`` calls, one
    ``exp`` and one division per element.  Arithmetic stays in the compute dtype.
    """
    one = tl.full(alpha.shape, 1.0, alpha.dtype)
    numer = one
    denom = alpha
    rec = _div(1.0, denom, FAST)
    series1 = numer * rec
    series2 = numer * rec * rec
    for i in range(1, 6):
        # ``i`` is a Python constant here, so the quotient is folded into a
        # single approximate division instead of an integer-indexed soft divide.
        numer = numer * _div(-x, i * 1.0, FAST)
        denom = denom + 1.0
        rec = _div(1.0, denom, FAST)
        series1 = _fma(numer, rec, series1, FAST)
        series2 = _fma(numer * rec, rec, series2, FAST)
    small = (
        x
        * tl.exp(x)
        * (series2 + (_digamma_one(alpha, STEPS, FAST) - tl.log(x)) * series1)
    )
    return tl.where(small != small, 0.0, small)


@triton.jit
def _small_branch_shared(alpha, x, psi_alpha, log_x):
    """Fast-path series branch reusing the tile's ``log x`` and psi(alpha)."""
    one = tl.full(alpha.shape, 1.0, alpha.dtype)
    numer = one
    denom = alpha
    rec = _div(1.0, denom, True)
    series1 = numer * rec
    series2 = numer * rec * rec
    for i in range(1, 6):
        numer = numer * _div(-x, i * 1.0, True)
        denom = denom + 1.0
        rec = _div(1.0, denom, True)
        series1 = _fma(numer, rec, series1, True)
        series2 = _fma(numer * rec, rec, series2, True)
    small = x * tl.exp(x) * (series2 + (psi_alpha - log_x) * series1)
    return tl.where(small != small, 0.0, small)


@triton.jit
def _saddle_branch(alpha, x, FAST: tl.constexpr):
    """Rice saddle-point expansion, selected for alpha > 8 (and x >= 0.8)."""
    ra = _div(1.0, alpha, FAST)
    db = tl.sqrt(8.0 * alpha)
    dx = _div(1.0, alpha - x, FAST)

    numer_1 = 1.0 + 24.0 * alpha * (1.0 + 12.0 * alpha)
    numer_2 = (
        1440.0 * (alpha * alpha)
        + 6.0 * x * (53.0 - 120.0 * x)
        - 65.0 * x * x * ra
        + alpha * (107.0 + 3600.0 * x)
    )
    near_mode = _div(
        numer_1 * numer_2, 1244160.0 * (alpha * alpha) * (alpha * alpha), FAST
    )

    term2 = db * dx
    lx = tl.log(_div(x, alpha, FAST))
    # t**(-3/2) computed through the reciprocal of t*sqrt(t): one reciprocal and
    # one sqrt instead of a libdevice pow with a negative exponent.
    arg = x - alpha - alpha * lx
    neg_three_halves = tl.full(alpha.shape, -1.5, alpha.dtype)
    if FAST:
        term3 = _div(1.0, arg * tl.sqrt(arg), FAST)
    else:
        term3 = _ld.pow(arg, neg_three_halves)
    term23 = tl.where(x < alpha, term2 - term3, term2 + term3)
    term1 = lx * term23 - tl.sqrt(2.0 * alpha) * ra * (alpha + x) * dx * dx
    stirling = 1.0 + _div(1.0, 12.0 * alpha, FAST) * (
        1.0 + _div(1.0, 24.0 * alpha, FAST)
    )
    away = -stirling * (x * term1) * _div(1.0, db, FAST)

    is_near = (0.9 * alpha <= x) & (x <= 1.1 * alpha)
    return tl.where(is_near, near_mode, away)


@triton.jit
def _rational_branch(alpha, x, FAST: tl.constexpr, log_alpha, log_x):
    """Bivariate rational approximation (default branch).

    ``u = log(x / alpha)`` is formed from the tile's shared ``log x`` and
    ``log alpha`` in the fast path; the fp64 path keeps the direct
    ``log(x / alpha)`` with the caller's correctly-rounded divide.
    """
    if FAST:
        u = log_x - log_alpha
        v = log_alpha
    else:
        u = tl.log(_div(x, alpha, FAST))
        v = tl.log(alpha)
    cv0 = _fma(u, _fma(u, 0.040121004, 0.53487893, FAST), 0.16009398, FAST)
    cv1 = _fma(u, _fma(u, -0.0065914022, 0.1298071, FAST), -0.094634809, FAST)
    cv2 = _fma(u, _fma(u, -0.0026286047, 0.065735949, FAST), 0.025146376, FAST)
    cv3 = _fma(u, _fma(u, -0.0013441777, -0.0015649758, FAST), -0.0030648343, FAST)
    cv4 = _fma(u, _fma(u, 0.017050642, 0.16639465, FAST), 1.0, FAST)
    cv5 = _fma(u, _fma(u, -0.0021309326, 0.020070113, FAST), 0.32668115, FAST)
    cv6 = _fma(u, _fma(u, 0.00085092367, -0.0035938915, FAST), 0.10406089, FAST)
    cv7 = _fma(u, _fma(u, -1.5247877e-07, -0.00058392623, FAST), 0.0014179084, FAST)
    p = _fma(v, _fma(v, _fma(v, cv3, cv2, FAST), cv1, FAST), cv0, FAST)
    q = _fma(v, _fma(v, _fma(v, cv7, cv6, FAST), cv5, FAST), cv4, FAST)
    return tl.exp(_div(p, q, FAST))


@triton.jit
def _select(alpha, x, STEPS: tl.constexpr):
    """ATen branch control flow with tile-level skipping of unused branches.

    ATen's order is ``x < 0.8 -> series`` else ``alpha > 8 -> saddle`` else
    ``rational``.  Each branch is evaluated only when at least one lane in the
    tile selects it, which is an exact set test over the tile.

    ``log x`` is needed by both the series and the rational branch, and
    ``log alpha`` by the rational branch, so both are computed once per tile
    and passed to the branch helpers instead of being recomputed inside each.
    """
    tiny = x < 0.8
    saddle = (x >= 0.8) & (alpha > 8.0)
    mid = ~(tiny | saddle)
    need_rational = tl.sum(mid.to(tl.int32)) > 0
    need_series = tl.sum(tiny.to(tl.int32)) > 0
    log_x = tl.log(x)
    log_alpha = tl.log(alpha)
    result = tl.zeros(alpha.shape, dtype=alpha.dtype)
    if need_rational:
        result = tl.where(
            mid, _rational_branch(alpha, x, True, log_alpha, log_x), result
        )
    if tl.sum(saddle.to(tl.int32)) > 0:
        result = tl.where(saddle, _saddle_branch(alpha, x, True), result)
    if need_series:
        if _digamma_in_window(alpha):
            psi = _digamma_window(alpha)
        else:
            psi = _digamma_one(alpha, STEPS, True)
        result = tl.where(
            tiny,
            _small_branch_shared(alpha, x, psi, log_x),
            result,
        )
    return result


@triton.jit
def _select_f64(alpha, x, STEPS: tl.constexpr):
    """Double-precision variant: correctly-rounded divides and no log sharing."""
    tiny = x < 0.8
    saddle = (x >= 0.8) & (alpha > 8.0)
    mid = ~(tiny | saddle)
    zero = tl.zeros(alpha.shape, dtype=alpha.dtype)
    result = tl.zeros(alpha.shape, dtype=alpha.dtype)
    if tl.sum(mid.to(tl.int32)) > 0:
        result = tl.where(mid, _rational_branch(alpha, x, False, zero, zero), result)
    if tl.sum(saddle.to(tl.int32)) > 0:
        result = tl.where(saddle, _saddle_branch(alpha, x, False), result)
    if tl.sum(tiny.to(tl.int32)) > 0:
        result = tl.where(tiny, _small_branch(alpha, x, STEPS, False), result)
    return result


@triton.jit
def _compute(a, x, STEPS: tl.constexpr):
    """Compute in fp32 unless the inputs are fp64, then cast back to input dtype."""
    if a.dtype.is_fp64():
        r = _select_f64(a, x, STEPS)
    else:
        r = _select(a.to(tl.float32), x.to(tl.float32), STEPS)
    return r.to(a.dtype)


@triton.jit
def _sgg_flat(a_ptr, x_ptr, o_ptr, n, STEPS: tl.constexpr, BLOCK: tl.constexpr):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n
    a = tl.load(a_ptr + offs, mask=mask, other=1.0)
    x = tl.load(x_ptr + offs, mask=mask, other=1.0)
    out = _compute(a, x, STEPS)
    tl.store(o_ptr + offs, out.to(o_ptr.dtype.element_ty), mask=mask)


@triton.jit
def _sgg_flat_exact(a_ptr, x_ptr, o_ptr, STEPS: tl.constexpr, BLOCK: tl.constexpr):
    """Mask-free variant; only launched when BLOCK divides the element count."""
    offs = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    a = tl.load(a_ptr + offs)
    x = tl.load(x_ptr + offs)
    out = _compute(a, x, STEPS)
    tl.store(o_ptr + offs, out.to(o_ptr.dtype.element_ty))


@triton.jit
def _sgg_strided(
    a_ptr,
    x_ptr,
    o_ptr,
    a_st,
    x_st,
    o_st,
    divs,
    total,
    STEPS: tl.constexpr,
    RANK: tl.constexpr,
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid.to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    mask = offs < total
    rem = tl.where(mask, offs, 0)
    oa = tl.zeros((BLOCK,), dtype=tl.int64)
    ox = tl.zeros((BLOCK,), dtype=tl.int64)
    oo = tl.zeros((BLOCK,), dtype=tl.int64)
    for d in tl.static_range(RANK):
        q = divs[d]
        i = rem // q
        rem = rem - i * q
        oa += i * a_st[d]
        ox += i * x_st[d]
        oo += i * o_st[d]
    a = tl.load(a_ptr + oa, mask=mask, other=1.0)
    x = tl.load(x_ptr + ox, mask=mask, other=1.0)
    out = _compute(a, x, STEPS)
    tl.store(o_ptr + oo, out.to(o_ptr.dtype.element_ty), mask=mask)


def _standard_gamma_grad(alpha, output):
    logger.debug("GEMS _STANDARD_GAMMA_GRAD")
    x = output
    if not torch.is_floating_point(alpha) or not torch.is_floating_point(x):
        raise RuntimeError(
            "_standard_gamma_grad: expected floating point tensors, got "
            f"self={alpha.dtype}, output={x.dtype}"
        )
    if alpha.dtype != x.dtype:
        raise RuntimeError(
            "_standard_gamma_grad: expected self and output to have the same "
            f"dtype, got {alpha.dtype} and {x.dtype}"
        )
    if alpha.device != x.device:
        raise RuntimeError(
            "_standard_gamma_grad: expected self and output on the same device, "
            f"got {alpha.device} and {x.device}"
        )
    a_shape = tuple(alpha.shape)
    x_shape = tuple(x.shape)
    try:
        bcast = torch.broadcast_shapes(a_shape, x_shape)
    except RuntimeError as exc:
        raise RuntimeError(
            "_standard_gamma_grad: shapes "
            f"{a_shape} and {x_shape} are not broadcastable"
        ) from exc

    out = torch.empty(bcast, dtype=alpha.dtype, device=alpha.device)
    n = out.numel()
    if n == 0:
        return out

    if (
        a_shape == bcast
        and x_shape == bcast
        and alpha.is_contiguous()
        and x.is_contiguous()
    ):
        if n <= _SMALL_LIMIT:
            block, warps = _SMALL_BLOCK, _SMALL_NUM_WARPS
        else:
            block, warps = _BLOCK, _NUM_WARPS
        grid = (triton.cdiv(n, block),)
        with torch_device_fn.device(alpha.device):
            if n % block == 0:
                _sgg_flat_exact[grid](
                    alpha, x, out, STEPS=_PSI_STEPS, BLOCK=block, num_warps=warps
                )
            else:
                _sgg_flat[grid](
                    alpha, x, out, n, STEPS=_PSI_STEPS, BLOCK=block, num_warps=warps
                )
        return out

    av = alpha.expand(bcast) if a_shape != bcast else alpha
    xv = x.expand(bcast) if x_shape != bcast else x
    rank = len(bcast)
    divs = [1] * rank
    acc = 1
    for d in range(rank - 1, -1, -1):
        divs[d] = acc
        acc *= int(bcast[d])
    grid = (triton.cdiv(n, _BLOCK),)
    with torch_device_fn.device(alpha.device):
        _sgg_strided[grid](
            av,
            xv,
            out,
            av.stride(),
            xv.stride(),
            out.stride(),
            tuple(divs),
            n,
            STEPS=_PSI_STEPS,
            RANK=rank,
            BLOCK=_BLOCK,
            num_warps=_NUM_WARPS,
        )
    return out
