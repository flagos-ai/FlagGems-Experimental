"""Triton kernel for the reparameterized standard-Gamma gradient.

``out[i] = g(alpha[i], x[i])`` where ``g`` is the reparameterized derivative
``-dF(alpha, x)/dalpha / f(alpha, x)`` of a standard Gamma sample.  The scalar
math mirrors ATen's ``standard_gamma_grad_one``: a Taylor/Bernoulli series for
small ``x``, a Rice saddle-point expansion for large ``alpha``, and a
bivariate rational approximation otherwise.

Four structural choices carry the performance:

* ``tl.where`` is not a branch: both sides are evaluated for every lane.  Each
  specialised branch is therefore additionally gated by an exact tile-level set
  test, so a program skips the series (or the saddle-point) arithmetic entirely
  when no lane in its tile selects it.  The predicates are exact, so the branch
  selected per element is unchanged.
* The kernel is instruction/dependency bound, so single-precision quotients use
  the hardware reciprocal sequence instead of the correctly-rounded soft-divide
  chain.  Every divided quantity here is a well-conditioned constant or affine
  denominator, and the fp64 path keeps the correctly-rounded division.
* Division-free work is minimised per branch: the small-x branch factors
  ``x**alpha`` out of the cdf/pdf ratio, and the saddle-point branch reuses one
  reciprocal of ``alpha - x`` instead of dividing three times.
* The map has no cross-element dependency, so a single warp per program with a
  narrow block is the fastest geometry measured on this target, and the load
  mask is dropped whenever the block divides the element count exactly.
"""

