def _fill_bias_or_zero(out, bias):
    """Fill ``out`` the way native pre-fills its output buffer (bias broadcast
    over the spatial dims, or zeros without a bias). No-op on empty outputs."""
    if out.numel() == 0:
        return
    if bias is None:
        out.zero_()
    else:
        out.copy_(bias.reshape(1, -1, 1, 1, 1).expand_as(out))
