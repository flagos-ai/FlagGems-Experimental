@triton.jit
def _pcq_quant_kernel(
    x_ptr,
    s_ptr,
    zp_ptr,
    out_ptr,
    N,
    CS,
    C,
    QMIN,
    QMAX,
    IS_FP16: tl.constexpr,
    OUT_I8: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Per-channel affine quantization of a float tensor (AO-style fallback):
    q = clamp(nearbyint(x * (1/scale[c])) + zero_point[c], qmin, qmax)."""
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < N
    x = tl.load(x_ptr + offs, mask=mask, other=0.0)
    if IS_FP16:
        x = x.to(tl.float32)
    c = (offs // CS) % C
    s = tl.load(s_ptr + c, mask=mask, other=1.0).to(tl.float32)
    zp = tl.load(zp_ptr + c, mask=mask, other=0).to(tl.int32)
    inv = 1.0 / s
    r = tl.extra.cuda.libdevice.nearbyint(x * inv)
    qi = r.to(tl.int32) + zp
    qi = tl.minimum(tl.maximum(qi, QMIN), QMAX)
    if OUT_I8:
        o = out_ptr.to(tl.pointer_type(tl.int8))
        tl.store(o + offs, qi.to(tl.int8), mask=mask)
    else:
        o = out_ptr.to(tl.pointer_type(tl.uint8))
        tl.store(o + offs, qi.to(tl.uint8), mask=mask)


