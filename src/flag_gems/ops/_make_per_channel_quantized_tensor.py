def _pcq_launch(self: torch.Tensor, q: torch.Tensor, scale, zero_point, axis):
    """Fill ``q``'s raw storage from ``self`` with the source's kernel set.

    Both device kernels address the input by flat offsets, so a non-contiguous
    input is materialized first. The supplied candidate did this inline in the
    integer branch only; the float branch is given the same treatment here,
    because a flat-offset read of a strided input silently quantizes whatever
    happens to sit at the physical offsets (measured: 46/60 elements wrong for
    a transposed (5, 4, 3) view). Making the float branch correct does not
    touch its arithmetic, indexing or block choices.
    """
    if not self.is_contiguous():
        self = self.contiguous()
