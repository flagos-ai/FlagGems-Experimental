    num_ct = tl.cdiv(W_out, S_W * BLOCK_OW)
    num_rt = S_H * tl.cdiv(H_out, S_H * BLOCK_OH)
    num_cob = tl.cdiv(C_out, BLOCK_CO)

    ct = pid % num_ct
    t = pid // num_ct
    rt = t % num_rt
    t = t // num_rt
    co_blk = t % num_cob
    n = t // num_cob

    bw = ct
    r_h = rt % S_H
    bh = rt // S_H
    oh0 = r_h + bh * (S_H * BLOCK_OH)
    ow0 = bw * (S_W * BLOCK_OW)

    co = co_blk * BLOCK_CO + tl.arange(0, BLOCK_CO)
    co_mask = co < C_out

    BLOCK_SP: tl.constexpr = BLOCK_OH * BLOCK_OW
    sp1 = tl.arange(0, BLOCK_SP)
    mh = sp1 // BLOCK_OW
    q = sp1 % BLOCK_OW
    oh = oh0 + mh * S_H
    row_mask = oh < H_out

    acc0 = tl.zeros((BLOCK_CO, BLOCK_SP), dtype=tl.float32)
    if S_W == 2:
        acc1 = tl.zeros((BLOCK_CO, BLOCK_SP), dtype=tl.float32)

    x_base = x_ptr + n * sN
    ci = tl.arange(0, BLOCK_C)
    cim = ci < C_in
    num_cc = tl.cdiv(C_in, BLOCK_C)

    if GH == 1:
        k0_h = ((oh0 + P_H) * INV_H) % S_H
        ih0 = (oh0 + P_H - k0_h * D_H) // S_H
    else:
        k0_h = 0
        ih0 = 0

    # For GH > 1 (stride/dilation share a factor), only the row phase
    # r_h == (-P_H) mod S_H produces non-zero conv contributions; the other
    # row-phase tiles are pure bias. Skip their entire dot loop (uniform
    # per-program branch) while still storing bias below.
    row_valid = True
    if GH > 1:
        row_valid = ((r_h + P_H) % S_H) == 0

    if row_valid:
        for mh_t in tl.static_range(KH_C):
            if GH == 1:
                kh = k0_h + mh_t * STEP_H
                kh_ok = kh < KH
                ih = ih0 + mh - mh_t * D_H
            else:
                # STEP_H == 1 guaranteed by dispatch
                kh = mh_t
                kh_ok = True
                ih = (oh + P_H - kh * D_H) // S_H
            if GH == 1:
                row_ok = kh_ok & (ih >= 0) & (ih < H_in) & row_mask
            else:
                row_ok = (
                    kh_ok & ((oh + P_H) % GH == 0) & (ih >= 0) & (ih < H_in) & row_mask
                )
            for r in tl.static_range(S_W):
                if GW == 1:
                    k0_w = ((ow0 + r + P_W) * INV_W) % S_W
                    iw0 = (ow0 + r + P_W - k0_w * D_W) // S_W
                    w_ok = True
                else:
                    w_ok = (ow0 + r + P_W) % GW == 0
                    k0_w = (((ow0 + r + P_W) // GW) * INV_W) % STEP_W
                    iw0 = 0
                # For GW > 1 only one W-phase (r == (-P_W) mod S_W) is
                # integral; the other phases are bias-only. Skip their whole
                # dot loop with a uniform per-program branch (equivalent to the
                # per-lane parity mask, but also skips the loads).
                phase_valid = True
                if GW > 1:
                    phase_valid = (ow0 + r + P_W) % S_W == 0
                if phase_valid:
                    for mw_t in tl.static_range(KW_C):
                        if GW == 1:
                            kw = k0_w + mw_t * STEP_W
                            kw_ok = kw < KW
                            iw = iw0 + q - mw_t * D_W
                        else:
                            kw = k0_w + mw_t * STEP_W
                            kw_ok = (kw < KW) & w_ok
                            iw = (ow0 + r + P_W - kw * D_W) // S_W + q
                        col_ok = (
                            kw_ok
                            & (iw >= 0)
                            & (iw < W_in)
                            & ((ow0 + r + q * S_W) < W_out)
                        )
                        for cc in range(num_cc):
                            c = cc * BLOCK_C + ci
                            x_off = (
                                x_base
                                + c[:, None] * sC
                                + ih[None, :] * sH
                                + iw[None, :] * sW
                            )
                            xv = tl.load(
                                x_off,
                                mask=cim[:, None] & (row_ok[None, :] & col_ok[None, :]),
                                other=0.0,
                            )
                            w_off = (
                                w_ptr
                                + c[None, :] * wS0
                                + co[:, None] * wS1
                                + kh * wS2
                                + kw * wS3
                            )
                            # kh/kw can exceed the kernel bounds on the last phase
                            # tap (kh = k0_h + mh_t*STEP_H); mask them so the weight
                            # load never reads out of bounds (garbage*0 == NaN
                            # otherwise).
                            wv = tl.load(
                                w_off,
                                mask=co_mask[:, None] & cim[None, :] & (kh_ok & kw_ok),
                                other=0.0,
                            )
                            if X3:
                                # fp32 -> fp16 hi/lo split; 3 fp16 tensor-core dots
                                # reproduce ~22 mantissa bits (error ~1e-6 rel, well
                                # inside the fp32 atol=1e-4 budget).
                                x_hi = xv.to(tl.float16)
                                x_lo = (xv - x_hi.to(tl.float32)).to(tl.float16)
                                w_hi = wv.to(tl.float16)
                                w_lo = (wv - w_hi.to(tl.float32)).to(tl.float16)
                                if r == 0:
                                    acc0 = tl.dot(w_hi, x_hi, acc0)
                                    acc0 = tl.dot(w_hi, x_lo, acc0)
                                    acc0 = tl.dot(w_lo, x_hi, acc0)
                                else:
                                    acc1 = tl.dot(w_hi, x_hi, acc1)
                                    acc1 = tl.dot(w_hi, x_lo, acc1)
                                    acc1 = tl.dot(w_lo, x_hi, acc1)
                            else:
                                if r == 0:
                                    acc0 = tl.dot(wv, xv, acc0, input_precision=PREC)
                                else:
                                    acc1 = tl.dot(wv, xv, acc1, input_precision=PREC)

    if S_W == 1:
        acc = acc0
    else:
        acc = tl.interleave(acc0, acc1)

    if HAS_BIAS:
        bv = tl.load(b_ptr + co, mask=co_mask, other=0.0).to(tl.float32)
        acc += bv[:, None]

    if OUT_DTYPE_ID == 1:
        acc = acc.to(tl.float16)
    elif OUT_DTYPE_ID == 2:
        acc = acc.to(tl.bfloat16)

    # flat output index: row-block mh, then contiguous cols of width S_W*BLOCK_OW
    sp2 = tl.arange(0, BLOCK_OH * S_W * BLOCK_OW)
    mh2 = sp2 // (S_W * BLOCK_OW)
    col2 = sp2 % (S_W * BLOCK_OW)
    o2 = oh0 + mh2 * S_H
    c2 = ow0 + col2
    omask = (o2 < H_out) & (c2 < W_out)
    out_base = out_ptr + n * (C_out * H_out * W_out) + co[:, None] * (H_out * W_out)
    tl.store(
        out_base + o2[None, :] * W_out + c2[None, :],
        acc,
        mask=co_mask[:, None] & omask[None, :],
    )


