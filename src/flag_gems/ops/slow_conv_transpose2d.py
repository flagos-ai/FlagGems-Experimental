# Phase-decomposed 2D tile: BLOCK_OH output rows (step S_H) x BLOCK_OW columns
# per width-phase; the S_W phases are accumulated in separate accs and
# tl.interleave-d so the store is fully contiguous in W.
# General stride/dilation handled via g = gcd(S, D), tap step = S/g.
# fp32 uses an fp16 hi/lo split with 3 tensor-core dots (~22 mantissa bits).
