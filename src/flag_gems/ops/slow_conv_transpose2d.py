def _pair(x):
    if isinstance(x, (tuple, list)):
        return int(x[0]), int(x[1])
    return int(x), int(x)


def _gcd(a, b):
    while b:
        a, b = b, a % b
    return a


def _modinv(a, m):
    # inverse of a mod m, requires gcd(a, m) == 1; m >= 1
    if m == 1:
        return 0
    return pow(a, -1, m)


