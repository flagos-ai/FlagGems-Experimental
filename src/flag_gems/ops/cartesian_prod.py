def cartesian_prod(
    tensors: List[torch.Tensor],
) -> torch.Tensor:
    """Return the Cartesian product of the given 1-D tensors.

    Mirrors ``aten::cartesian_prod(Tensor[] tensors) -> Tensor``. The native
    operator (ATen ``Itertools.cpp``) runs, in order: a dim==1 check on every
    input, an early identity return for a single input, then ``meshgrid(..,
    "ij")`` validation (non-empty list, uniform dtype, uniform device) and a
    ``(prod(sizes), K)`` result whose rows enumerate the Cartesian product in
    lexicographic order, the last input varying fastest. Those checks are
    reproduced here -- registering the operator on the backend key replaces the
    native composite, so without them an invalid call would silently succeed
    instead of raising as native does.

    All K >= 2 inputs are passed to the kernel by ``data_ptr()`` plus their
    logical stride, so non-contiguous 1-D inputs need no materializing copy.
    """
