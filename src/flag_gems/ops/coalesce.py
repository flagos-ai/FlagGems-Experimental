def _shapes(S, shape):
    s = [1] * (_MAX_S - 1)
    for d in range(1, _MAX_S):
        if d < S:
            s[d - 1] = shape[d]
    return s


def _log2(x):
    if x > 0 and (x & (x - 1)) == 0:
        return x.bit_length() - 1
    return -1


def _scan_path(idx, val, shape, S, n, dt, dev):
    """Multi-program histogram + scan + scatter path (any nnz).

    Historically this served only fp16/fp32/bf16, accumulating in fp32; it now
    also serves the small path's dtypes whenever ``nnz > _SMALL_PATH_MAX`` so
    that no dtype is truncated. The accumulation dtype follows the small
    path's convention via ``ACC`` (0 = fp64, 1 = int64, 2 = int32, 3 = fp32),
    so results match what ``_small_path`` would produce, bit for bit, just
    without its 1024-entry ceiling.
    """
    K = 1
    for x in shape:
        K *= x
    s1, s2, s3, s4, s5 = _shapes(S, shape)
    p1 = _log2(shape[1]) if S >= 2 else -1
    p2 = _log2(shape[2]) if S >= 3 else -1

    B = 1024
    NW = (K + 31) // 32

    # One allocation per purpose: ``bits`` is the per-index bit histogram and
    # ``acc`` the per-unique-entry accumulator. They used to share a single
    # int32 buffer (``buf = zeros(NW + n); val32 = buf[NW:].view(float32)``),
    # which relied on the zeroed tail and made the lifetimes hard to follow.
    bits = torch.zeros(NW, dtype=torch.int32, device=dev)
    pack = torch.empty(NW, dtype=torch.int64, device=dev)
    nb2 = (NW + 8191) // 8192
    blk_tot = torch.empty(nb2, dtype=torch.int32, device=dev)
    blk_off = torch.empty(nb2, dtype=torch.int32, device=dev)
    cnt = torch.empty(1, dtype=torch.int32, device=dev)
    if dt == torch.float32:
        acc = torch.zeros(n, dtype=torch.float32, device=dev)
        acc_code = 3
    elif dt == torch.float64:
        acc = torch.zeros(n, dtype=torch.float64, device=dev)
        acc_code = 0
    elif dt == torch.int64:
        acc = torch.zeros(n, dtype=torch.int64, device=dev)
        acc_code = 1
    else:
        # fp16/bf16 keep fp32 accumulation (matching the historical float
        # path); narrower ints and bool accumulate in int32 exactly like the
        # small path. Only fp32 skips the finalize cast (see below); fp16/bf16
        # are finalized down to their own dtype.
        acc = torch.zeros(
            n, dtype=torch.float32 if dt.is_floating_point else torch.int32, device=dev
        )
        acc_code = 3 if dt.is_floating_point else 2
    out_idx = torch.empty(S * n, dtype=torch.int64, device=dev)

    _hist_kernel[(triton.cdiv(n, B),)](
        idx, bits, cnt, n, s1, s2, s3, s4, s5, S=S, BLOCK=B
    )
    _word_scan_kernel[(nb2,)](bits, pack, blk_tot, cnt, NW, BLOCK=8192, num_warps=8)
    _scatter_kernel[(triton.cdiv(n, B),)](
        idx,
        val,
        pack,
        blk_tot,
        blk_off,
        acc,
        out_idx,
        n,
        nb2,
        s1,
        s2,
        s3,
        s4,
        s5,
        BT=triton.next_power_of_2(nb2),
        P1=p1,
        P2=p2,
        ACC=acc_code,
        S=S,
        BLOCK=B,
        num_warps=8,
    )
    r = int(cnt)
    if dt == torch.float32:
        # acc already holds fp32: serve the values directly.
        ov = acc[:r]
    else:
        out_val = torch.empty(n, dtype=dt, device=dev)
        _finalize_kernel[(triton.cdiv(r, B),)](
            acc, out_val, r, IS_BOOL=(dt == torch.bool), BLOCK=B
        )
        ov = out_val[:r]
    oi = out_idx.view(S, n)[:, :r]
    return torch.sparse_coo_tensor(oi, ov, shape)


def _small_path(idx, val, shape, S, n, dt, dev):
    """Single-program sort + accumulate path, correct for ``n <= _SMALL_PATH_MAX``.

    The whole index array is packed into one int64 key per entry
    (``key << shift | position``) and sorted with ``tl.sort`` inside a single
    program, so the working set is bounded by BLOCK = 1024 lanes. Inputs above
    that bound are routed to ``_scan_path`` by ``coalesce``; this function must
    never see ``n > _SMALL_PATH_MAX``.
    """
    s1, s2, s3, s4, s5 = _shapes(S, shape)
    if dt == torch.float64:
        acc_dt = torch.float64
        acc_code = 0
    elif dt == torch.int64:
        acc_dt = torch.int64
        acc_code = 1
    else:
        acc_dt = torch.int32
        acc_code = 2

    BLOCK = 1024
    shift = (n - 1).bit_length() if n > 1 else 0
    p_mask = (1 << shift) - 1 if shift > 0 else 0

    spack = torch.empty(BLOCK, dtype=torch.int64, device=dev)
    acc = torch.zeros(BLOCK, dtype=acc_dt, device=dev)
    cnt = torch.zeros(1, dtype=torch.int32, device=dev)
    out_idx = torch.empty(S * n, dtype=torch.int64, device=dev)
    out_val = torch.empty(n, dtype=dt, device=dev)

    _small_sort_kernel[(1,)](idx, spack, n, shift, s1, s2, s3, s4, s5, S=S, BLOCK=BLOCK)
    _small_run_kernel[(1,)](
        spack,
        val,
        acc,
        out_idx,
        cnt,
        n,
        shift,
        p_mask,
        s1,
        s2,
        s3,
        s4,
        s5,
        ACC=acc_code,
        S=S,
        BLOCK=BLOCK,
    )
    r = int(cnt)
    _small_finalize_kernel[(triton.cdiv(r, BLOCK),)](
        acc, out_val, r, IS_BOOL=(dt == torch.bool), BLOCK=BLOCK
    )
    oi = out_idx.view(S, n)[:, :r]
    ov = out_val[:r]
    return torch.sparse_coo_tensor(oi, ov, shape)


def coalesce(self: torch.Tensor) -> torch.Tensor:
    """Sort a sparse COO tensor's indices and merge duplicate entries.

    Mirrors ``aten::coalesce(Tensor(a) self) -> Tensor(a)``. The returned
    tensor is a fresh sparse COO tensor whose indices are sorted in
    lexicographic (row-major) order and whose duplicate entries have had
    their values added together; the returned tensor reports
    ``is_coalesced() == True``. The input tensor is never modified: when it
    is already coalesced (or has zero stored entries, which native treats as
    coalesced) the *same object* is returned, exactly as native does.

    Two kernel paths mirror the source: a scan path (fp16/fp32/bf16, and any
    dtype whose stored-entry count exceeds the small path's 1024-entry
    ceiling) built on a 32-bit per-element bit histogram + word scan + atomic
    scatter that accumulates in fp32 for floats and fp64/int64/int32 for the
    small path's dtypes, and a small path (fp64/ints/bool with at most 1024
    stored entries) that sorts the whole index array in one program and
    accumulates in fp64/int64/int32.

    The op is registered with the CompositeImplicitAutograd dispatch key,
    which is the only key that reaches it on this build (measured, see
    runs/coalesce/probe*.log): native ``aten::coalesce`` has no backend key
    at all, and the composite kernel is a decomposition, not an
    implementation. Delegating to the native composite from inside this
    function is impossible because that composite *is* this registration;
    calling ``_coalesced_(True)`` on the result restores the flag with the
    native metadata mutation.
    """
    logger.debug("GEMS COALESCE")
    if self.layout != torch.sparse_coo:
        # Native wording (SparseTensor.cpp): "coalesce expected sparse
        # coordinate tensor layout but got <layout>" where <layout> is the
        # layout's C++ enum name (Strided / SparseCsr / SparseBsc ...). This
        # must run BEFORE any metadata access: a strided tensor rejects with
        # this error rather than a NotImplementedError from ``_nnz``.
        raw = str(self.layout).replace("torch.", "")
        parts = raw.split("_")
        layout = "".join(p[:1].upper() + p[1:] for p in parts)
        raise RuntimeError(
            f"coalesce expected sparse coordinate tensor layout but got {layout}"
        )
    shape = tuple(self.shape)
    n = self._nnz()
    S = self.sparse_dim()
    D = self.dense_dim()
    dt = self.dtype
    if self.is_coalesced() or n == 0:
        return self
    idx = self._indices()
    val = self._values()
    dev = self.device
    if D > 0:
        # Hybrid COO (values with trailing dense dims) is unsupported by the
        # supplied kernels: they address ``val_ptr + offs`` with a scalar
        # offset, which reads only the first dense column, and the output is
        # built with a 1-D value tensor, which ``torch.sparse_coo_tensor``
        # rejects for a shape with dense dims. Native instead adds whole
        # value rows (values.stride(0) blocks). Because the op carries no
        # backend key, this override cannot fall back to the native composite
        # either; the limitation is disclosed in the report.
        raise NotImplementedError(
            "coalesce does not support hybrid COO tensors with dense dimensions "
            f"(sparse_dim={S}, dense_dim={D}); the submitted kernel accumulation "
            "is defined for 1-D values only"
        )
    # ``torch_device_fn.device`` is accelerator-specific and raises ValueError
    # for a CPU device; the Triton kernels below are a GPU implementation, so a
    # CPU tensor cannot be served here either. The context is entered for every
    # accelerator device and skipped only for CPU (the CI --ref=cpu phase keeps
    # the implementation input on the accelerator; this is purely defensive).
    if dev.type == "cpu":
        ctx = contextlib.nullcontext()
    else:
        ctx = torch_device_fn.device(dev)
    with ctx:
        if dt in (torch.float16, torch.float32, torch.bfloat16):
            out = _scan_path(idx, val, shape, S, n, dt, dev)
        elif n <= _SMALL_PATH_MAX:
            out = _small_path(idx, val, shape, S, n, dt, dev)
        else:
            # The small path is single-program (BLOCK = 1024 lanes) and would
            # silently drop everything past lane 1023; larger non-float inputs
            # take the multi-program scan path with the same accumulation
            # dtype the small path would have used.
            out = _scan_path(idx, val, shape, S, n, dt, dev)
    out._coalesced_(True)
    return out
