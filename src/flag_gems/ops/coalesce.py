@triton.jit
def _word_scan_kernel(bits_ptr, pack_ptr, blk_tot_ptr, cnt_ptr, n, BLOCK: tl.constexpr):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n
    v = tl.load(bits_ptr + offs, mask=mask, other=0).to(tl.int32)
    pc = libdevice.popc(v).to(tl.int32)
    s = tl.cumsum(pc, axis=0)
    excl = s - pc
    packed = (excl.to(tl.int64) << 32) | (v.to(tl.int64) & 0xFFFFFFFF)
    tl.store(pack_ptr + offs, packed, mask=mask)
    total = tl.sum(pc, axis=0)
    tl.store(blk_tot_ptr + pid, total)
    if total > 0:
        tl.atomic_add(cnt_ptr, total)


