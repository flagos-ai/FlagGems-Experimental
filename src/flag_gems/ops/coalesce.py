    mask = offs < n
    k = tl.load(idx_ptr + offs, mask=mask, other=0).to(tl.int32)
    if S >= 2:
        i1 = tl.load(idx_ptr + n + offs, mask=mask, other=0).to(tl.int32)
        k = k * s1 + i1
    if S >= 3:
        i2 = tl.load(idx_ptr + 2 * n + offs, mask=mask, other=0).to(tl.int32)
        k = k * s2 + i2
    if S >= 4:
        i3 = tl.load(idx_ptr + 3 * n + offs, mask=mask, other=0).to(tl.int32)
        k = k * s3 + i3
    if S >= 5:
        i4 = tl.load(idx_ptr + 4 * n + offs, mask=mask, other=0).to(tl.int32)
        k = k * s4 + i4
    if S >= 6:
        i5 = tl.load(idx_ptr + 5 * n + offs, mask=mask, other=0).to(tl.int32)
        k = k * s5 + i5
    w = k >> 5
    b = k & 31
    pv = tl.load(pack_ptr + w, mask=mask, other=0)
    wv = (pv & 0xFFFFFFFF).to(tl.int32)
    base = (pv >> 32).to(tl.int32)
    pc = libdevice.popc(wv & ((1 << b) - 1)).to(tl.int32)
    blk2 = w >> 13
    pos = base + pc + tl.load(blk_off_ptr + blk2, mask=mask, other=0)
    v = tl.load(val_ptr + offs, mask=mask, other=0)
    # ACC mirrors the small-path accumulation convention (see ``_small_path``):
    # 0 = fp64, 1 = int64, 2 = int32, 3 = fp32. The accumulator buffer is
    # allocated with the matching dtype, so each non-float dtype accumulates
    # exactly like the small path would (no intermediate fp32 rounding).
    if ACC == 0:
        va = v.to(tl.float64)
    elif ACC == 1:
        va = v.to(tl.int64)
    elif ACC == 2:
        va = v.to(tl.int32)
    else:
        va = v.to(tl.float32)
    tl.atomic_add(acc_ptr + pos, va, mask=mask)
    kk = k
    if S >= 6:
        i5o = kk % s5
        kk = kk // s5
        tl.store(out_idx_ptr + 5 * n + pos, i5o.to(tl.int64), mask=mask)
    if S >= 5:
        i4o = kk % s4
        kk = kk // s4
        tl.store(out_idx_ptr + 4 * n + pos, i4o.to(tl.int64), mask=mask)
    if S >= 4:
        i3o = kk % s3
        kk = kk // s3
        tl.store(out_idx_ptr + 3 * n + pos, i3o.to(tl.int64), mask=mask)
    if S >= 3:
        if P2 >= 0:
            i2o = kk & ((1 << P2) - 1)
            kk = kk >> P2
        else:
            i2o = kk % s2
            kk = kk // s2
        tl.store(out_idx_ptr + 2 * n + pos, i2o.to(tl.int64), mask=mask)
    if S >= 2:
        if P1 >= 0:
            i1o = kk & ((1 << P1) - 1)
            kk = kk >> P1
        else:
            i1o = kk % s1
            kk = kk // s1
        tl.store(out_idx_ptr + n + pos, i1o.to(tl.int64), mask=mask)
    tl.store(out_idx_ptr + pos, kk.to(tl.int64), mask=mask)


