    HW = H_in * W_in
    x_base = x_ptr + n * (C_in * HW)
    w_base = w_ptr + co[:, None] * (C_in * KH * KW)

    ohs = oh * stride_h
    ows = ow * stride_w

    for ci in range(C_in):
        xc = x_base + ci * HW
        wc = w_base + ci * (KH * KW)
        for kh in tl.static_range(KH):
            ih = ohs - pad_h + kh * dil_h
            row_ok = (ih >= 0) & (ih < H_in)
            a_off = ih * W_in
            for kw in tl.static_range(KW):
                iw = ows - pad_w + kw * dil_w
                xmask = sp_mask & row_ok & (iw >= 0) & (iw < W_in)
                xv = tl.load(xc + a_off + iw, mask=xmask, other=0.0).to(tl.float32)
                wv = tl.load(wc + kh * KW + kw, mask=co_mask[:, None], other=0.0).to(
                    tl.float32
                )
                acc += wv * xv[None, :]

    if has_bias:
        bv = tl.load(b_ptr + co, mask=co_mask, other=0.0).to(tl.float32)
        acc += bv[:, None]

    if OUT_DTYPE_ID == 1:
        acc = acc.to(tl.float16)
    elif OUT_DTYPE_ID == 2:
        acc = acc.to(tl.bfloat16)

    out_base = out_ptr + n * (C_out * H_out * W_out) + co[:, None] * (H_out * W_out)
    tl.store(out_base + sp[None, :], acc, mask=co_mask[:, None] & sp_mask[None, :])


