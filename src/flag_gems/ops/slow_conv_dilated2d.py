def _slow_conv_dilated2d_dot_kernel(
    x_ptr,
    w_ptr,
    b_ptr,
    out_ptr,
    C_in,
    H_in,
    W_in,
    C_out,
    H_out,
    W_out,
    stride_h,
    stride_w,
    pad_h,
    pad_w,
    dil_h,
    dil_w,
    has_bias: tl.constexpr,
    OUT_DTYPE_ID: tl.constexpr,
    KH: tl.constexpr,
    KW: tl.constexpr,
    BLOCK_CO: tl.constexpr,
    BLOCK_SP: tl.constexpr,
    BLOCK_K: tl.constexpr,
    PREC: tl.constexpr,
):
    # Implicit im2col + tl.dot: reduction axis k = ci*(KH*KW) + kh*KW + kw.
    pid = tl.program_id(0)
    num_sp = tl.cdiv(H_out * W_out, BLOCK_SP)
    num_cob = tl.cdiv(C_out, BLOCK_CO)

    sp_blk = pid % num_sp
    co_blk = (pid // num_sp) % num_cob
    n = pid // (num_sp * num_cob)

    co = co_blk * BLOCK_CO + tl.arange(0, BLOCK_CO)
    sp = sp_blk * BLOCK_SP + tl.arange(0, BLOCK_SP)
    co_mask = co < C_out
    sp_mask = sp < (H_out * W_out)

    oh = sp // W_out
    ow = sp % W_out
    ohs = oh * stride_h
    ows = ow * stride_w

    acc = tl.zeros((BLOCK_CO, BLOCK_SP), dtype=tl.float32)

    HW = H_in * W_in
    KHKW = KH * KW
    K = C_in * KHKW

    x_base = x_ptr + n * (C_in * HW)

    for k0 in range(0, K, BLOCK_K):
        k = k0 + tl.arange(0, BLOCK_K)
        km = k < K
        ci = k // KHKW
        rem = k - ci * KHKW
        kh = rem // KW
        kw = rem - kh * KW
        ih = ohs[None, :] + kh[:, None] * dil_h - pad_h
        iw = ows[None, :] + kw[:, None] * dil_w - pad_w
        xmask = (
            sp_mask[None, :]
            & km[:, None]
            & (ih >= 0)
            & (ih < H_in)
            & (iw >= 0)
            & (iw < W_in)
        )
        x_off = ci[:, None] * HW + ih * W_in + iw
        xt = tl.load(x_base + x_off, mask=xmask, other=0.0)
        wt = tl.load(
            w_ptr + co[:, None] * K + k[None, :],
            mask=co_mask[:, None] & km[None, :],
            other=0.0,
        )
        acc = tl.dot(wt, xt, acc, input_precision=PREC)

    if has_bias:
        bv = tl.load(b_ptr + co, mask=co_mask, other=0.0).to(tl.float32)
        acc += bv[:, None]

    if OUT_DTYPE_ID == 1:
        acc = acc.to(tl.float16)
    elif OUT_DTYPE_ID == 2:
        acc = acc.to(tl.bfloat16)

    out_base = out_ptr + n * (C_out * H_out * W_out) + co[:, None] * (H_out * W_out)
    tl.store(out_base + sp[None, :], acc, mask=co_mask[:, None] & sp_mask[None, :])


