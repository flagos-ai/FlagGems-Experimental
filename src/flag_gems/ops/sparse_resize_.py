    if self.layout != torch.sparse_coo:
        raise NotImplementedError(
            "aten::sparse_resize_ is only implemented for sparse coordinate "
            "(coo) tensors; got layout " + str(self.layout)
        )
    cur = self.shape
    if (
        tuple(size) == tuple(cur)
        and self.sparse_dim() == sparse_dim
        and self.dense_dim() == dense_dim
    ):
        return self

    if sparse_dim + dense_dim != len(size):
        raise RuntimeError(
            "number of dimensions must be sparse_dim ("
            + str(sparse_dim)
            + ") + dense_dim ("
            + str(dense_dim)
            + "), but got "
            + str(len(size))
        )

