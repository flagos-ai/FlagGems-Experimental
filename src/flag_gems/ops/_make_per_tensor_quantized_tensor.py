# aten::_make_per_tensor_quantized_tensor(Tensor self, float scale, int
# zero_point) wraps an integer tensor (uint8/int8/int32) into a per-tensor
# affine quantized tensor. The output dtype is derived from the input dtype via
# toQIntType (uint8 -> quint8, int8 -> qint8, int32 -> qint32). The data path
# is a pure copy: the output's int_repr must be an exact copy of the (logical)
# input values, and scale/zero_point are stored verbatim as qparams.
_QDTYPE = {
    torch.uint8: torch.quint8,
    torch.int8: torch.qint8,
    torch.int32: torch.qint32,
}

# Every quantized dtype in this build (torch.dtype exposes no is_quantized, so
# membership in this set is the check).
_QUANTIZED_DTYPES = {
    torch.quint8,
    torch.qint8,
    torch.qint32,
    torch.quint4x2,
    torch.quint2x4,
}


@triton.jit
def _copy_1d_kernel(src, dst, n_elements, BLOCK: tl.constexpr):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    offs = tl.max_contiguous(tl.multiple_of(offs, BLOCK), BLOCK)
    mask = offs < n_elements
    x = tl.load(src + offs, mask=mask)
    tl.store(dst + offs, x, mask=mask)


@triton.jit
def _gather_1d_kernel(
    src, dst, n_elements, shape_ptr, stride_ptr, ndim, BLOCK: tl.constexpr
):
    # Copy logical (row-major) values of a strided input into a contiguous
    # output: decompose each flat index into per-dim coordinates and gather
    # through the input strides.
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < n_elements
    off = tl.zeros((BLOCK,), dtype=tl.int64)
    rem = offs.to(tl.int64)
    for d in range(ndim - 1, -1, -1):
        s = tl.load(shape_ptr + d)
        st = tl.load(stride_ptr + d)
        c = rem % s
        off += c * st
        rem = rem // s
    x = tl.load(src + off, mask=mask, other=0)
    tl.store(dst + offs, x, mask=mask)


