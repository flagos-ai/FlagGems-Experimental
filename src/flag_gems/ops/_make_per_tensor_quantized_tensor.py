def _fill_int_repr(self: torch.Tensor, out: torch.Tensor) -> None:
    """Copy the input's logical (row-major) values into ``out``'s storage."""
    n = self.numel()
    if n == 0:
        return
    # Zero-copy aliasing view of the quantized tensor's raw storage so the
    # device kernel can fill the int representation directly.
    raw = torch.empty(0, dtype=self.dtype, device=self.device).set_(
        out.untyped_storage(), 0, (n,)
    )
    if self.is_contiguous():
        # 4-byte elements: 4 KiB blocks with 8 warps put more 128-bit requests
        # in flight per block; 1-byte elements prefer a wide block per program
        # (16 KiB blocks are ~10% faster than 4 KiB blocks at 16 MB sizes),
        # with a narrower block for small tensors where launch geometry is
        # overhead-dominated.
        if self.dtype == torch.int32:
            BLOCK = 1024
            num_warps = 8
        elif n < (1 << 21):
            BLOCK = 8192
            num_warps = 4
        else:
            BLOCK = 16384
            num_warps = 8
        grid = (triton.cdiv(n, BLOCK),)
        with torch_device_fn.device(self.device):
            _copy_1d_kernel[grid](self, raw, n, BLOCK=BLOCK, num_warps=num_warps)
    else:
        shape_t = torch.tensor(self.shape, device=self.device, dtype=torch.int64)
        stride_t = torch.tensor(self.stride(), device=self.device, dtype=torch.int64)
        BLOCK = 1024
        grid = (triton.cdiv(n, BLOCK),)
        with torch_device_fn.device(self.device):
            _gather_1d_kernel[grid](
                self, raw, n, shape_t, stride_t, self.dim(), BLOCK=BLOCK, num_warps=8
            )


